-- 2026-10-13: belediye arsalari, muteahhit projeleri, tapu, dukkan kiralama ve zincir sube.
-- Mevcut sirket, eko_proje ve oyuncu kayitlarina dokunmaz. Geri alinabilir ek tablolar.
create table if not exists oyun.eko_arsalar(
 id bigint generated by default as identity primary key,
 il_id smallint not null references oyun.iller(id),
 kademe smallint not null check(kademe in (3,5,10,20,40)),
 alan_m2 integer not null check(alan_m2>0),
 fiyat numeric not null check(fiyat>0),
 durum text not null default 'satilik' check(durum in ('satilik','satildi')),
 sahibi_sirket bigint references oyun.sirketler(id),
 alis_zamani timestamptz,
 olusturma timestamptz not null default now(),
 unique(il_id,kademe)
);
create table if not exists oyun.eko_yapilar(
 id bigint generated by default as identity primary key,
 arsa_id bigint not null unique references oyun.eko_arsalar(id),
 sirket_id bigint not null references oyun.sirketler(id),
 il_id smallint not null references oyun.iller(id),
 ad text not null,
 daire_sayisi integer not null check(daire_sayisi>=0),
 dukkan_sayisi integer not null check(dukkan_sayisi>=0),
 maliyet numeric not null check(maliyet>0),
 baslangic timestamptz not null default now(),
 bitis timestamptz not null
);
create table if not exists oyun.eko_bolumler(
 id bigint generated by default as identity primary key,
 yapi_id bigint not null references oyun.eko_yapilar(id),
 sira integer not null,
 tur text not null check(tur in ('daire','dukkan')),
 alan_m2 integer not null check(alan_m2>0),
 sahibi uuid references auth.users(id),
 satis_fiyati numeric not null check(satis_fiyati>0),
 kira_bedeli numeric check(kira_bedeli is null or kira_bedeli>=100),
 satildi timestamptz,
 unique(yapi_id,sira)
);
create table if not exists oyun.eko_subeler(
 id bigint generated by default as identity primary key,
 bolum_id bigint not null unique references oyun.eko_bolumler(id),
 sirket_id bigint not null references oyun.sirketler(id),
 kiraya_veren uuid not null references auth.users(id),
 kira numeric not null check(kira>=100),
 ilk_acilis timestamptz not null default now(),
 sonraki_kira timestamptz not null,
 son_gelir timestamptz not null default now(),
 toplam_gelir numeric not null default 0,
 aktif boolean not null default true
);
create index if not exists eko_arsalar_il_idx on oyun.eko_arsalar(il_id,durum);
create index if not exists eko_yapilar_sirket_idx on oyun.eko_yapilar(sirket_id,bitis);
create index if not exists eko_bolumler_sahibi_idx on oyun.eko_bolumler(sahibi);
create index if not exists eko_subeler_sirket_idx on oyun.eko_subeler(sirket_id);
alter table oyun.eko_arsalar enable row level security;
alter table oyun.eko_yapilar enable row level security;
alter table oyun.eko_bolumler enable row level security;
alter table oyun.eko_subeler enable row level security;
-- Belediye tarafindan standart imarli parseller her ilde 5 kademe.
insert into oyun.eko_arsalar(il_id,kademe,alan_m2,fiyat)
select i.id, k.kademe, round(k.kademe*135)::integer,
  greatest(15000,round(oyun.mulk_il_bedel(i.id,'daire')*k.kademe*.27*
   (0.85+greatest(0,least(coalesce(d.gelisim,50),100))/500)))
from oyun.iller i
join oyun.il_durum d on d.il_id=i.id
cross join (values (3),(5),(10),(20),(40)) k(kademe)
on conflict(il_id,kademe) do nothing;

create or replace function public.eko_emlak_panel(p_il smallint default null)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare
 u uuid:=auth.uid(); il smallint:=p_il; sonuc jsonb;
begin
 if u is null or not exists(select 1 from oyun.profiller where id=u and not yasakli) then
   raise exception 'Giris yapmalisin.'; end if;
 if il is null then select il_id into il from oyun.profiller where id=u;end if;
 if not exists(select 1 from oyun.iller where id=il) then raise exception 'Il bulunamadi.';end if;
 select jsonb_build_object(
 'il',il, 'il_adi',(select ad from oyun.iller where id=il),
 'gelisim',(select round(gelisim,1) from oyun.il_durum where il_id=il),
 'baz_daire',oyun.mulk_il_bedel(il,'daire'),
 'arsalar',coalesce((select jsonb_agg(jsonb_build_object(
  'id',a.id,'kademe',a.kademe,'m2',a.alan_m2,'fiyat',a.fiyat,'durum',a.durum,'sahip_sirket',a.sahibi_sirket
 ) order by a.kademe) from oyun.eko_arsalar a where a.il_id=il),'[]'::jsonb),
 'yapilar',coalesce((select jsonb_agg(jsonb_build_object(
  'id',y.id,'arsa',y.arsa_id,'ad',y.ad,'sirket',y.sirket_id,'sirket_ad',s.ad,
  'daire',y.daire_sayisi,'dukkan',y.dukkan_sayisi,'maliyet',y.maliyet,
  'bitis',y.bitis,'hazir',y.bitis<=oyun.simdi()
 ) order by y.bitis desc) from oyun.eko_yapilar y
 join oyun.sirketler s on s.id=y.sirket_id where y.il_id=il),'[]'::jsonb),
 'satilik',coalesce((select jsonb_agg(jsonb_build_object(
  'id',b.id,'tur',b.tur,'m2',b.alan_m2,'fiyat',b.satis_fiyati,
  'yapi',y.ad,'sirket',y.sirket_id,'sirket_ad',s.ad
 ) order by b.id desc) from oyun.eko_bolumler b
 join oyun.eko_yapilar y on y.id=b.yapi_id join oyun.sirketler s on s.id=y.sirket_id
 where y.il_id=il and b.sahibi is null and y.bitis<=oyun.simdi()),'[]'::jsonb),
 'kiralik',coalesce((select jsonb_agg(jsonb_build_object(
  'id',b.id,'m2',b.alan_m2,'kira',b.kira_bedeli,'yapi',y.ad,'sahibi',b.sahibi
 ) order by b.id desc) from oyun.eko_bolumler b
 join oyun.eko_yapilar y on y.id=b.yapi_id
 where y.il_id=il and b.tur='dukkan' and b.sahibi is not null and b.kira_bedeli is not null
 and not exists(select 1 from oyun.eko_subeler sb where sb.bolum_id=b.id and sb.aktif)),'[]'::jsonb),
 'benim_arsalarim',coalesce((select jsonb_agg(jsonb_build_object(
  'id',a.id,'il',a.il_id,'fiyat',a.fiyat,'kapasite',a.kademe,'sirket',a.sahibi_sirket
 ) order by a.id desc) from oyun.eko_arsalar a
 where a.sahibi_sirket in (select ei.sirket_id from oyun.eko_isletmeler ei where ei.tur='insaat' and oyun.sirket_yonetici_mi(ei.sirket_id,u))
 and not exists(select 1 from oyun.eko_yapilar y where y.arsa_id=a.id)),'[]'::jsonb),
 'benim_mulklerim',coalesce((select jsonb_agg(jsonb_build_object(
  'id',b.id,'il',y.il_id,'tur',b.tur,'m2',b.alan_m2,'kira',b.kira_bedeli,
  'yapi',y.ad,'kirada',exists(select 1 from oyun.eko_subeler sb where sb.bolum_id=b.id and sb.aktif)
 ) order by b.id desc) from oyun.eko_bolumler b join oyun.eko_yapilar y on y.id=b.yapi_id
 where b.sahibi=u),'[]'::jsonb),
 'benim_subelerim',coalesce((select jsonb_agg(jsonb_build_object(
  'id',sb.id,'il',y.il_id,'yapi',y.ad,'magaza',s.ad,'sirket',sb.sirket_id,
  'kira',sb.kira,'sonraki_kira',sb.sonraki_kira,'son_gelir',sb.son_gelir,'toplam_gelir',sb.toplam_gelir
 ) order by sb.id desc) from oyun.eko_subeler sb
 join oyun.eko_bolumler b on b.id=sb.bolum_id join oyun.eko_yapilar y on y.id=b.yapi_id
 join oyun.sirketler s on s.id=sb.sirket_id
 where sb.aktif and oyun.sirket_yonetici_mi(sb.sirket_id,u)),'[]'::jsonb),
 'muteahhitler',coalesce((select jsonb_agg(jsonb_build_object('id',ei.sirket_id,'ad',s.ad,'kasa',s.kasa))
  from oyun.eko_isletmeler ei join oyun.sirketler s on s.id=ei.sirket_id
  where ei.tur='insaat' and s.aktif and oyun.sirket_yonetici_mi(ei.sirket_id,u)),'[]'::jsonb),
 'magazalar',coalesce((select jsonb_agg(jsonb_build_object('id',ei.sirket_id,'ad',s.ad,'sermaye',s.sermaye,'kasa',s.kasa))
  from oyun.eko_isletmeler ei join oyun.sirketler s on s.id=ei.sirket_id
  where ei.tur='magaza' and s.aktif and oyun.sirket_yonetici_mi(ei.sirket_id,u)),'[]'::jsonb)
 ) into sonuc;
 return sonuc;
end $$;

create or replace function public.eko_emlak_islem(p_eylem text,p_veri jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare
 u uuid:=auth.uid(); t timestamptz:=oyun.simdi(); sonuc jsonb;
 aid bigint:=nullif(p_veri->>'arsa','')::bigint;
 bid bigint:=nullif(p_veri->>'bolum','')::bigint;
 sid bigint:=nullif(p_veri->>'sirket','')::bigint;
 subid bigint:=nullif(p_veri->>'sube','')::bigint;
 nd integer:=coalesce(nullif(p_veri->>'daire','')::integer,0);
 nk integer:=coalesce(nullif(p_veri->>'dukkan','')::integer,0);
 bedel numeric:=coalesce(nullif(p_veri->>'tutar','')::numeric,0);
 maliyet numeric; harc numeric; gun numeric; oran numeric; rakip integer; i integer;
 ar oyun.eko_arsalar; y oyun.eko_yapilar; b oyun.eko_bolumler; sb oyun.eko_subeler;
 s oyun.sirketler; tip text;
begin
 if u is null or not exists(select 1 from oyun.profiller where id=u and not yasakli) then
  raise exception 'Giris yapmalisin.'; end if;
 if p_veri is null or jsonb_typeof(p_veri)<>'object' then raise exception 'Gecersiz islem.';end if;
 if p_eylem='arsa_al' then
  select * into ar from oyun.eko_arsalar where id=aid for update;
  if ar.id is null or ar.durum<>'satilik' then raise exception 'Arsa satista degil.';end if;
  select * into s from oyun.sirketler where id=sid for update;
  if s.id is null or not s.aktif or not oyun.sirket_yonetici_mi(sid,u)
   or not exists(select 1 from oyun.eko_isletmeler where sirket_id=sid and tur='insaat')
   then raise exception 'Arsa icin yetkili bir muteahhitlik sirketi sec.';end if;
  update oyun.sirketler set kasa=kasa-ar.fiyat where id=sid and kasa>=ar.fiyat;
  if not found then raise exception 'Sirket kasasi arsa icin yetersiz.';end if;
  update oyun.eko_arsalar set durum='satildi',sahibi_sirket=sid,alis_zamani=t where id=aid;
  update oyun.il_durum set kasa=kasa+ar.fiyat where il_id=ar.il_id;
  insert into oyun.eko_islem_kayit(sirket_id,oyuncu,tur,tutar,aciklama)
   values(sid,u,'arsa',-ar.fiyat,format('%s ilinde belediye arsasi alimi',ar.il_id));
  return jsonb_build_object('arsa',aid,'odenen',ar.fiyat);
 elsif p_eylem='insaata_basla' then
  select * into ar from oyun.eko_arsalar where id=aid for update;
  if ar.id is null or ar.sahibi_sirket is null or ar.durum<>'satildi' then raise exception 'Arsa sana ait degil.';end if;
  sid:=ar.sahibi_sirket;
  select * into s from oyun.sirketler where id=sid for update;
  if not s.aktif or not oyun.sirket_yonetici_mi(sid,u)
   or not exists(select 1 from oyun.eko_isletmeler where sirket_id=sid and tur='insaat')
   then raise exception 'Bu projeyi baslatma yetkin yok.';end if;
  if exists(select 1 from oyun.eko_yapilar where arsa_id=aid) then raise exception 'Bu arsada proje var.';end if;
  if nd<0 or nk<0 or nd+nk<1 or nd+nk>ar.kademe or nk>greatest(1,ceil(ar.kademe*.3)::integer) then
   raise exception 'Arsanin imar kapasitesine uygun daire ve dukkan sayisi sec.';end if;
  maliyet:=round(oyun.mulk_il_bedel(ar.il_id,'daire')*.62*nd + oyun.mulk_il_bedel(ar.il_id,'dukkan')*.65*nk);
  if maliyet<=0 then raise exception 'Gecersiz maliyet.';end if;
  update oyun.sirketler set kasa=kasa-maliyet where id=sid and kasa>=maliyet;
  if not found then raise exception 'Insaat maliyeti icin sirket kasasi yetersiz.';end if;
  insert into oyun.eko_yapilar(arsa_id,sirket_id,il_id,ad,daire_sayisi,dukkan_sayisi,maliyet,baslangic,bitis)
   values(aid,sid,ar.il_id,left(coalesce(nullif(trim(p_veri->>'ad'),''),'Yeni Konut Projesi'),70),nd,nk,maliyet,t,
   t+(case when nd+nk<=5 then interval '12 hours'
           when nd+nk<=10 then interval '24 hours'
           when nd+nk<=20 then interval '48 hours'
           else interval '96 hours' end))
   returning * into y;
  for i in 1..nd loop
    insert into oyun.eko_bolumler(yapi_id,sira,tur,alan_m2,satis_fiyati)
    values(y.id,i,'daire',110,round(oyun.mulk_il_bedel(ar.il_id,'daire')*1.08));
  end loop;
  for i in 1..nk loop
    insert into oyun.eko_bolumler(yapi_id,sira,tur,alan_m2,satis_fiyati)
    values(y.id,nd+i,'dukkan',75,round(oyun.mulk_il_bedel(ar.il_id,'dukkan')*1.12));
  end loop;
  insert into oyun.eko_islem_kayit(sirket_id,oyuncu,tur,tutar,aciklama)
  values(sid,u,'insaat',-maliyet,format('%s: %s daire, %s dukkan',y.ad,nd,nk));
  return jsonb_build_object('proje',y.id,'maliyet',maliyet,'bitis',y.bitis);
 elsif p_eylem='fiyat_belirle' then
  select * into b from oyun.eko_bolumler where id=bid for update;
  select * into y from oyun.eko_yapilar where id=b.yapi_id;
  if b.id is null or b.sahibi is not null or not oyun.sirket_yonetici_mi(y.sirket_id,u) then
   raise exception 'Bu bolumun satis fiyatini degistiremezsin.';end if;
  if bedel<>round(bedel) or bedel<100 or bedel>1000000000 then raise exception 'Satis fiyati 100 - 1 milyar TL olmali.';end if;
  update oyun.eko_bolumler set satis_fiyati=bedel where id=bid;
  return jsonb_build_object('fiyat',bedel);
 elsif p_eylem='bolum_al' then
  select * into b from oyun.eko_bolumler where id=bid for update;
  if b.id is null or b.sahibi is not null then raise exception 'Bu tasinmaz satilmis.';end if;
  select * into y from oyun.eko_yapilar where id=b.yapi_id;
  if y.bitis>t then raise exception 'Insaat henuz bitmedi.';end if;
  select * into s from oyun.sirketler where id=y.sirket_id for update;
  if not s.aktif then raise exception 'Satici sirket faal degil.';end if;
  harc:=round(b.satis_fiyati*.02);
  perform oyun.para_islem(u,-b.satis_fiyati-harc,'emlak','Yeni '+b.tur+' alimi, %2 tapu harci',t,harc);
  update oyun.sirketler set kasa=kasa+b.satis_fiyati where id=y.sirket_id;
  update oyun.ulke set hazine=hazine+harc where id=1;
  update oyun.eko_bolumler set sahibi=u,satildi=t where id=bid;
  return jsonb_build_object('tapu',bid,'odenen',b.satis_fiyati+harc);
 elsif p_eylem='kira_belirle' then
  select * into b from oyun.eko_bolumler where id=bid for update;
  if b.id is null or b.sahibi<>u or b.tur<>'dukkan' then raise exception 'Bu dukkan sana ait degil.';end if;
  if exists(select 1 from oyun.eko_subeler where bolum_id=bid and aktif) then raise exception 'Kirada olan dukkanin kira bedeli degistirilemez.';end if;
  if bedel<>round(bedel) or bedel<100 or bedel>10000000 then raise exception 'Haftalik kira 100-10 milyon TL olmali.';end if;
  update oyun.eko_bolumler set kira_bedeli=bedel where id=bid;
  return jsonb_build_object('kira',bedel);
 elsif p_eylem='sube_ac' then
  select * into b from oyun.eko_bolumler where id=bid for update;
  if b.id is null or b.tur<>'dukkan' or b.sahibi is null or b.kira_bedeli is null then
   raise exception 'Kiralanabilir dukkan sec.';end if;
  select * into y from oyun.eko_yapilar where id=b.yapi_id;
  if y.bitis>t then raise exception 'Insaat henuz bitmedi.';end if;
  if exists(select 1 from oyun.eko_subeler where bolum_id=bid) then
   raise exception 'Bu dukkanda sube acilmis. Baska dukkan sec.';end if;
  select * into s from oyun.sirketler where id=sid for update;
  if s.id is null or not s.aktif or not oyun.sirket_yonetici_mi(sid,u)
   or not exists(select 1 from oyun.eko_isletmeler where sirket_id=sid and tur='magaza')
   then raise exception 'Sube acmak icin magaza sirketi sec.';end if;
  -- ilk haftalik kira ve acilis gideri pesin; kira dogrudan mulk sahibinin cuzdanina.
  maliyet:=greatest(5000,round(s.sermaye*.02));
  update oyun.sirketler set kasa=kasa-b.kira_bedeli-maliyet where id=sid and kasa>=b.kira_bedeli+maliyet;
  if not found then raise exception 'Kira ve acilis gideri icin sirket kasasi yetersiz.';end if;
  perform oyun.para_islem(b.sahibi,b.kira_bedeli,'kira','Magaza subesi ilk haftalik kira',t);
  insert into oyun.eko_subeler(bolum_id,sirket_id,kiraya_veren,kira,ilk_acilis,sonraki_kira,son_gelir)
   values(bid,sid,b.sahibi,b.kira_bedeli,t,t+interval '7 days',t) returning id into subid;
  insert into oyun.eko_islem_kayit(sirket_id,oyuncu,tur,tutar,aciklama)
   values(sid,u,'sube',-b.kira_bedeli-maliyet,format('Magaza subesi acilisi: dukkan %s',bid));
  return jsonb_build_object('sube',subid,'kira',b.kira_bedeli,'acilis',maliyet);
 elsif p_eylem='sube_gelir' then
  select * into sb from oyun.eko_subeler where id=subid for update;
  if sb.id is null or not sb.aktif or not oyun.sirket_yonetici_mi(sb.sirket_id,u) then raise exception 'Aktif subeni sec.';end if;
  if sb.son_gelir+interval '24 hours'>t then raise exception 'Gunluk kazanc henuz hazir degil.';end if;
  select * into s from oyun.sirketler where id=sb.sirket_id for update;
  if not s.aktif then raise exception 'Magaza sirketi aktif degil.';end if;
  select * into b from oyun.eko_bolumler where id=sb.bolum_id;
  select * into y from oyun.eko_yapilar where id=b.yapi_id;
  -- Vadesi gelmis kirayi tahsil edemeyen magazaya yeni gunluk kar yazilmaz.
  if sb.sonraki_kira<=t then
   update oyun.sirketler set kasa=kasa-sb.kira where id=sb.sirket_id and kasa>=sb.kira;
   if not found then raise exception 'Haftalik kira icin sirket kasasi yetersiz.';end if;
   perform oyun.para_islem(sb.kiraya_veren,sb.kira,'kira','Magaza subesi haftalik kira',t);
   update oyun.eko_subeler set sonraki_kira=greatest(sb.sonraki_kira,t)+interval '7 days' where id=subid;
  end if;
  select count(*) into rakip from oyun.eko_subeler sb2
   join oyun.eko_bolumler b2 on b2.id=sb2.bolum_id join oyun.eko_yapilar y2 on y2.id=b2.yapi_id
   where sb2.aktif and y2.il_id=y.il_id;
  select greatest(.7,least(1.5,.65+coalesce(d.gelisim,50)/100)) into oran
   from oyun.il_durum d where d.il_id=y.il_id;
  -- Nufus olcegi olarak il MV sayisi, il gelismisligi ve rekabet kullanilir.
  select round(greatest(150,least(s.sermaye*.007,
   (s.sermaye*.002+600)*oran*(0.7+least(100,(select mv from oyun.iller where id=y.il_id))::numeric/110)
   /(1+greatest(rakip-1,0)*.12)))) into maliyet;
  update oyun.sirketler set kasa=kasa+maliyet where id=sb.sirket_id;
  update oyun.eko_subeler set son_gelir=t,toplam_gelir=toplam_gelir+maliyet where id=subid;
  insert into oyun.eko_islem_kayit(sirket_id,oyuncu,tur,tutar,aciklama)
   values(sb.sirket_id,u,'sube_gelir',maliyet,format('%s ilinde magaza gunluk net kari',y.il_id));
  return jsonb_build_object('net_kar',maliyet,'rakip',rakip,'sonraki_kazanc',t+interval '24 hours');
 else
  raise exception 'Bilinmeyen emlak islemi.';
 end if;
end $$;
revoke all on function public.eko_emlak_panel(smallint) from public,anon;
revoke all on function public.eko_emlak_islem(text,jsonb) from public,anon;
grant execute on function public.eko_emlak_panel(smallint) to authenticated;
grant execute on function public.eko_emlak_islem(text,jsonb) to authenticated;