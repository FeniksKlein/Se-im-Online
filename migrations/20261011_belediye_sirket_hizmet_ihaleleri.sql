-- Belediye -> oyuncu sirketi ihalesi; il kasasi milyar, sirket kasasi TL.
CREATE TABLE IF NOT EXISTS oyun.belediye_is_ihale (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 il_id smallint NOT NULL REFERENCES oyun.iller(id),
 baskan uuid NOT NULL REFERENCES oyun.profiller(id),
 baslik text NOT NULL,
 aciklama text NOT NULL DEFAULT '',
 sektor text NOT NULL,
 butce numeric NOT NULL CHECK(butce BETWEEN 100000 AND 20000000),
 teklif_bit timestamptz NOT NULL,
 durum text NOT NULL DEFAULT 'acik' CHECK(durum IN ('acik','is_verildi','tamamlandi','iptal','teklif_yok','basarisiz')),
 olusturma timestamptz NOT NULL DEFAULT now(),
 kazanan_sirket bigint REFERENCES oyun.sirketler(id),
 kazanan_teklif numeric,
 secim_zamani timestamptz,
 teslim_zamani timestamptz,
 son_teslim timestamptz,
 memnuniyet_puan numeric,
 CHECK(char_length(baslik) BETWEEN 5 AND 120)
);
CREATE TABLE IF NOT EXISTS oyun.belediye_is_teklif (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ihale_id bigint NOT NULL REFERENCES oyun.belediye_is_ihale(id),
 sirket_id bigint NOT NULL REFERENCES oyun.sirketler(id),
 teklif_veren uuid NOT NULL REFERENCES oyun.profiller(id),
 teklif numeric NOT NULL CHECK(teklif>0),
 zaman timestamptz NOT NULL DEFAULT now(),
 UNIQUE(ihale_id,sirket_id)
);
CREATE INDEX IF NOT EXISTS belediye_is_ihale_durum_idx ON oyun.belediye_is_ihale(durum,teklif_bit);
CREATE INDEX IF NOT EXISTS belediye_is_ihale_il_idx ON oyun.belediye_is_ihale(il_id,durum);
CREATE INDEX IF NOT EXISTS belediye_is_teklif_sirket_idx ON oyun.belediye_is_teklif(sirket_id);
ALTER TABLE oyun.belediye_is_ihale ENABLE ROW LEVEL SECURITY;
ALTER TABLE oyun.belediye_is_teklif ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.belediye_is_ihale_ac(p_baslik text,p_aciklama text,p_sektor text,p_butce numeric,p_saat integer DEFAULT 12)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='oyun','public','pg_temp' AS $$
DECLARE u uuid:=auth.uid(); il smallint; kasa numeric; iid bigint;
BEGIN
 PERFORM oyun.profilim();
 SELECT m.il_id INTO il FROM oyun.makamlar m WHERE m.tur='bel' AND m.bit IS NULL AND m.user_id=u ORDER BY m.id DESC LIMIT 1;
 IF il IS NULL THEN RAISE EXCEPTION 'Yalnizca gorevdeki belediye baskani ihale acabilir'; END IF;
 IF char_length(trim(coalesce(p_baslik,''))) NOT BETWEEN 5 AND 120 OR char_length(coalesce(p_aciklama,''))>1200 THEN RAISE EXCEPTION 'Baslik/aciklama sinirini kontrol et'; END IF;
 IF p_sektor NOT IN ('insaat','teknoloji','ticaret','sanayi','tarim','hizmet') THEN RAISE EXCEPTION 'Gecerli sektor sec'; END IF;
 IF p_saat NOT IN (6,12,24) THEN RAISE EXCEPTION 'Ihale 6, 12 veya 24 saat acik kalabilir'; END IF;
 IF p_butce IS NULL OR p_butce<>round(p_butce) OR p_butce<100000 OR p_butce>20000000
 THEN RAISE EXCEPTION 'Butce 100 bin - 20 milyon TL olmali'; END IF;
 PERFORM pg_advisory_xact_lock(83119,il::integer);
 IF EXISTS(SELECT 1 FROM oyun.belediye_is_ihale WHERE il_id=il AND durum='acik')
 THEN RAISE EXCEPTION 'Bu belediyenin halen acik bir hizmet ihalesi var'; END IF;
 SELECT d.kasa INTO kasa FROM oyun.il_durum d WHERE d.il_id=il FOR UPDATE;
 IF kasa IS NULL OR p_butce>kasa*1000000000*0.05 OR kasa < p_butce/1000000000
 THEN RAISE EXCEPTION 'Ihale butcesi sehir kasasinin en fazla %%5i olabilir'; END IF;
 UPDATE oyun.il_durum SET kasa=kasa-p_butce/1000000000 WHERE il_id=il;
 INSERT INTO oyun.belediye_is_ihale(il_id,baskan,baslik,aciklama,sektor,butce,teklif_bit)
 VALUES(il,u,trim(p_baslik),coalesce(p_aciklama,''),p_sektor,p_butce,now()+make_interval(hours=>p_saat))
 RETURNING id INTO iid;
 RETURN jsonb_build_object('tamam',true,'ihale_id',iid);
END $$;

CREATE OR REPLACE FUNCTION public.belediye_is_teklif_ver(p_ihale bigint,p_sirket bigint,p_tutar numeric)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='oyun','public','pg_temp' AS $$
DECLARE u uuid:=auth.uid(); x oyun.belediye_is_ihale; s oyun.sirketler;
BEGIN
 PERFORM oyun.profilim();
 SELECT * INTO x FROM oyun.belediye_is_ihale WHERE id=p_ihale FOR UPDATE;
 IF x.id IS NULL OR x.durum<>'acik' OR x.teklif_bit<=now() THEN RAISE EXCEPTION 'Teklif suresi sona erdi'; END IF;
 SELECT * INTO s FROM oyun.sirketler WHERE id=p_sirket AND aktif;
 IF s.id IS NULL OR s.sektor<>x.sektor THEN RAISE EXCEPTION 'Sadece istenen sektorde aktif sirket teklif verebilir'; END IF;
 IF NOT EXISTS (SELECT 1 FROM oyun.sirket_ortaklari WHERE sirket_id=p_sirket AND user_id=u AND pay>=25)
 THEN RAISE EXCEPTION 'Teklif icin sirkette en az %%25 pay sahibi olmalisin'; END IF;
 IF EXISTS(SELECT 1 FROM oyun.sirket_ortaklari WHERE sirket_id=p_sirket AND user_id=x.baskan AND pay>0)
 THEN RAISE EXCEPTION 'Belediye baskaninin ortak oldugu sirket kendi ihalesine katilamaz'; END IF;
 IF p_tutar IS NULL OR p_tutar<>round(p_tutar) OR p_tutar<x.butce*0.60 OR p_tutar>x.butce
 THEN RAISE EXCEPTION 'Teklif butcenin %%60-%%100 araliginda tam TL olmali'; END IF;
 INSERT INTO oyun.belediye_is_teklif(ihale_id,sirket_id,teklif_veren,teklif)
 VALUES(p_ihale,p_sirket,u,p_tutar)
 ON CONFLICT (ihale_id,sirket_id) DO UPDATE SET teklif=excluded.teklif,teklif_veren=excluded.teklif_veren,zaman=now();
 RETURN jsonb_build_object('tamam',true);
END $$;

CREATE OR REPLACE FUNCTION oyun.belediye_is_tick()
RETURNS integer LANGUAGE plpgsql SET search_path='oyun','public','pg_temp' AS $$
DECLARE r record; b record; n integer:=0; pct numeric; w integer;
BEGIN
 IF NOT pg_try_advisory_xact_lock(83120,1) THEN RETURN 0; END IF;
 FOR r IN SELECT * FROM oyun.belediye_is_ihale WHERE (durum='acik' AND teklif_bit<=now())
 OR (durum='is_verildi' AND son_teslim<now()) ORDER BY id FOR UPDATE LOOP
   IF r.durum='acik' THEN
     SELECT t.sirket_id,t.teklif INTO b
     FROM oyun.belediye_is_teklif t JOIN oyun.sirketler s ON s.id=t.sirket_id
     WHERE t.ihale_id=r.id AND s.aktif AND s.sektor=r.sektor
       AND NOT EXISTS(SELECT 1 FROM oyun.sirket_ortaklari o WHERE o.sirket_id=s.id AND o.user_id=r.baskan AND o.pay>0)
     ORDER BY t.teklif,t.zaman,t.id LIMIT 1;
     IF b.sirket_id IS NULL THEN
       UPDATE oyun.belediye_is_ihale SET durum='teklif_yok' WHERE id=r.id;
       UPDATE oyun.il_durum SET kasa=kasa+r.butce/1000000000 WHERE il_id=r.il_id;
     ELSE
       UPDATE oyun.belediye_is_ihale SET durum='is_verildi',kazanan_sirket=b.sirket_id,kazanan_teklif=b.teklif,
         secim_zamani=now(),son_teslim=now()+interval '72 hours' WHERE id=r.id;
       UPDATE oyun.il_durum SET kasa=kasa+(r.butce-b.teklif)/1000000000 WHERE il_id=r.il_id;
       INSERT INTO oyun.bildirimler(user_id,zaman,metin)
       SELECT DISTINCT o.user_id,now(),format('Sirketiniz %s Belediyesi hizmet ihalesini kazandi. 72 saat icinde teslim etmeniz gerekiyor.',i.ad)
       FROM oyun.sirket_ortaklari o JOIN oyun.iller i ON i.id=r.il_id WHERE o.sirket_id=b.sirket_id;
     END IF;
   ELSE
     UPDATE oyun.belediye_is_ihale SET durum='basarisiz',teslim_zamani=now() WHERE id=r.id;
     UPDATE oyun.il_durum SET kasa=kasa+r.kazanan_teklif/1000000000,
       memnuniyet=oyun.sinir(memnuniyet-0.75,0,100) WHERE il_id=r.il_id;
     INSERT INTO oyun.bildirimler(user_id,zaman,metin)
     SELECT DISTINCT o.user_id,now(),'Sirketiniz belediye isini suresinde teslim edemedi. Ihale iptal edildi.'
     FROM oyun.sirket_ortaklari o WHERE o.sirket_id=r.kazanan_sirket;
   END IF;
   n:=n+1;
 END LOOP;
 RETURN n;
END $$;

CREATE OR REPLACE FUNCTION public.belediye_is_tamamla(p_ihale bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='oyun','public','pg_temp' AS $$
DECLARE u uuid:=auth.uid(); r oyun.belediye_is_ihale; masraf numeric; kar numeric; puan numeric;
BEGIN
 PERFORM oyun.profilim();
 SELECT * INTO r FROM oyun.belediye_is_ihale WHERE id=p_ihale FOR UPDATE;
 IF r.id IS NULL OR r.durum<>'is_verildi' THEN RAISE EXCEPTION 'Teslim bekleyen ihale bulunamadi'; END IF;
 IF NOT EXISTS(SELECT 1 FROM oyun.sirket_ortaklari WHERE sirket_id=r.kazanan_sirket AND user_id=u AND pay>=25)
 THEN RAISE EXCEPTION 'Bu sirket icin teslim yetkin yok'; END IF;
 IF now()<r.secim_zamani+interval '6 hours' THEN RAISE EXCEPTION 'Isin tamamlanmasi icin en az 6 saat gerekir'; END IF;
 IF now()>r.son_teslim THEN RAISE EXCEPTION 'Teslim suresi dolmus'; END IF;
 PERFORM 1 FROM oyun.sirketler WHERE id=r.kazanan_sirket AND aktif FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Sirket aktif degil'; END IF;
 masraf:=round(r.kazanan_teklif*0.70);
 kar:=r.kazanan_teklif-masraf;
 puan:=least(1.5,greatest(0.3,round(r.kazanan_teklif/2000000,2)));
 UPDATE oyun.sirketler SET kasa=kasa+kar WHERE id=r.kazanan_sirket;
 INSERT INTO oyun.sirket_hareket(sirket_id,zaman,tutar,aciklama,faaliyet_gelir,faaliyet_gider)
 VALUES(r.kazanan_sirket,now(),kar,'Belediye hizmet ihalesi #'||r.id,r.kazanan_teklif,masraf);
 UPDATE oyun.il_durum SET memnuniyet=oyun.sinir(memnuniyet+puan,0,100),
 gelisim=oyun.sinir(gelisim+puan,0,100) WHERE il_id=r.il_id;
 UPDATE oyun.belediye_is_ihale SET durum='tamamlandi',teslim_zamani=now(),memnuniyet_puan=puan WHERE id=r.id;
 PERFORM oyun.olay('belediye',format('Belediye hizmet ihalesi tamamlandi: %s, %s TL.',r.baslik,r.kazanan_teklif),r.il_id,null,now());
 RETURN jsonb_build_object('tamam',true,'sirket_kar',kar,'memnuniyet',puan);
END $$;

CREATE OR REPLACE FUNCTION public.belediye_is_iptal(p_ihale bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='oyun','public','pg_temp' AS $$
DECLARE r oyun.belediye_is_ihale;
BEGIN
 PERFORM oyun.profilim();
 SELECT * INTO r FROM oyun.belediye_is_ihale WHERE id=p_ihale FOR UPDATE;
 IF r.id IS NULL OR r.durum<>'acik' OR NOT EXISTS(
 SELECT 1 FROM oyun.makamlar WHERE tur='bel' AND bit IS NULL AND il_id=r.il_id AND user_id=auth.uid())
 THEN RAISE EXCEPTION 'Ihale iptal yetkisi yok'; END IF;
 IF EXISTS(SELECT 1 FROM oyun.belediye_is_teklif WHERE ihale_id=p_ihale) THEN
 RAISE EXCEPTION 'Teklif verilmis ihale iptal edilemez'; END IF;
 UPDATE oyun.belediye_is_ihale SET durum='iptal' WHERE id=r.id;
 UPDATE oyun.il_durum SET kasa=kasa+r.butce/1000000000 WHERE il_id=r.il_id;
 RETURN jsonb_build_object('tamam',true);
END $$;

CREATE OR REPLACE FUNCTION public.belediye_is_pazar()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path='oyun','public','pg_temp' AS $$
DECLARE u uuid:=auth.uid();
BEGIN
 IF u IS NULL THEN RAISE EXCEPTION 'Oturum gerekli'; END IF;
 RETURN jsonb_build_object(
 'sirketlerim',coalesce((SELECT jsonb_agg(jsonb_build_object('id',s.id,'ad',s.ad,'sektor',s.sektor,'pay',o.pay))
  FROM oyun.sirketler s JOIN oyun.sirket_ortaklari o ON o.sirket_id=s.id WHERE o.user_id=u AND s.aktif AND o.pay>=25),'[]'::jsonb),
 'ihaleler',coalesce((
 SELECT jsonb_agg(jsonb_build_object('id',h.id,'il_id',h.il_id,'il',il.ad,
 'baslik',h.baslik,'aciklama',h.aciklama,'sektor',h.sektor,'butce',h.butce,'teklif_bit',h.teklif_bit,
 'durum',h.durum,'baskan',oyun.kad(h.baskan),'kazanan',s.ad,'kazanan_teklif',h.kazanan_teklif,
 'secim_zamani',h.secim_zamani,'son_teslim',h.son_teslim,'memnuniyet_puan',h.memnuniyet_puan,
 'teklif_sayisi',(SELECT count(*) FROM oyun.belediye_is_teklif t WHERE t.ihale_id=h.id),
 'benim_tekliflerim',coalesce((SELECT jsonb_agg(jsonb_build_object('sirket_id',t.sirket_id,'teklif',t.teklif))
  FROM oyun.belediye_is_teklif t JOIN oyun.sirket_ortaklari o ON o.sirket_id=t.sirket_id
  WHERE t.ihale_id=h.id AND o.user_id=u),'[]'::jsonb),
 'baskanim',EXISTS(SELECT 1 FROM oyun.makamlar m WHERE m.tur='bel' AND m.bit IS NULL AND m.user_id=u AND m.il_id=h.il_id),
 'teslim_yetkim',EXISTS(SELECT 1 FROM oyun.sirket_ortaklari o WHERE o.sirket_id=h.kazanan_sirket AND o.user_id=u AND o.pay>=25)
 ) ORDER BY h.id DESC)
 FROM oyun.belediye_is_ihale h JOIN oyun.iller il ON il.id=h.il_id
 LEFT JOIN oyun.sirketler s ON s.id=h.kazanan_sirket
 WHERE h.durum IN ('acik','is_verildi')
 OR (h.durum IN ('tamamlandi','teklif_yok','basarisiz','iptal') AND h.olusturma>now()-interval '14 days')
 ),'[]'::jsonb));
END $$;
