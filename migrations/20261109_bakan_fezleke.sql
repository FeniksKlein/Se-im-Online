-- 180 · Kesinleşen mahkeme kararıyla görevdeki bakan hakkında Cumhurbaşkanlığı fezlekesi.
-- Sadece yeni kesinleşen davalar; mevcut oyunculara veya geçmiş davalara dokunulmaz.
create table if not exists oyun.bakan_fezleke (
 id bigint generated by default as identity primary key,
 dava_id bigint not null references oyun.adliye_davalar(id),
 makam_id bigint not null references oyun.makamlar(id),
 bakan_id uuid not null references oyun.profiller(id),
 bakanlik text not null references oyun.bakanliklar(kod),
 karar text not null,
 mahkeme_gerekce text not null,
 mahkeme_hakim uuid,
 mahkeme_karar_at timestamptz,
 iletilme timestamptz not null default now(),
 durum text not null default 'bekliyor'
  check (durum in ('bekliyor','gorevden_alindi','gorevde_tutuldu','gorev_sona_erdi')),
 cb_id uuid references oyun.profiller(id),
 cb_gerekce text,
 cb_karar_at timestamptz,
 unique(dava_id,makam_id)
);
create index if not exists bakan_fezleke_bekleyen on oyun.bakan_fezleke(durum,iletilme desc);
create index if not exists bakan_fezleke_bakan on oyun.bakan_fezleke(bakan_id,iletilme desc);
alter table oyun.bakan_fezleke enable row level security;
revoke all on oyun.bakan_fezleke from public,anon,authenticated;
revoke all on sequence oyun.bakan_fezleke_id_seq from public,anon,authenticated;
grant select,insert,update on oyun.bakan_fezleke to service_role;
grant usage,select on sequence oyun.bakan_fezleke_id_seq to service_role;

create or replace function oyun.tg_bakan_fezleke_ilet()
returns trigger language plpgsql security definer set search_path='' as $$
declare m record; v_id bigint; cb uuid; t timestamptz:=oyun.simdi();
begin
 if new.kesin is distinct from true or old.kesin is true
    or new.durum <> 'karar' or new.davali is null
    or new.karar is null or new.karar in ('beraat','dusme') then return new; end if;
 cb := (select x.user_id from oyun.makamlar x where x.tur='cb' and x.bit is null order by x.bas desc limit 1);
 for m in select x.id,x.user_id,x.bakanlik,b.ad from oyun.makamlar x
          join oyun.bakanliklar b on b.kod=x.bakanlik
          where x.tur='bakan' and x.user_id=new.davali and x.bit is null
 loop
   v_id:=null;
   insert into oyun.bakan_fezleke(dava_id,makam_id,bakan_id,bakanlik,karar,mahkeme_gerekce,mahkeme_hakim,mahkeme_karar_at,iletilme)
   values(new.id,m.id,new.davali,m.bakanlik,new.karar,coalesce(nullif(trim(new.gerekce),''),'Mahkemenin kesinleşmiş kararı.'),new.hakim,new.karar_at,t)
   on conflict(dava_id,makam_id) do nothing returning id into v_id;
   if v_id is not null then
     if cb is not null then
       perform oyun.bildir(cb,format('⚖️ Cumhurbaşkanlığına fezleke #%s: %s (%s), kesinleşen Adliye #%s kararı nedeniyle inceleme bekliyor. Adliye > Bakan fezlekeleri.',v_id,oyun.kad(m.user_id),m.ad,new.id),t);
     end if;
     perform oyun.bildir(m.user_id,format('⚖️ Hakkınızda Adliye #%s kararı kesinleşti; %s göreviniz için fezleke #%s Cumhurbaşkanlığına iletildi. Fezleke tek başına görevden alma değildir.',new.id,m.ad,v_id),t);
     perform oyun.olay('adliye',format('Yüksek Mahkeme, kesinleşen Adliye #%s kararı üzerine %s hakkında Cumhurbaşkanlığına fezleke #%s gönderdi.',new.id,oyun.kad(m.user_id),v_id),null,null,t);
   end if;
 end loop;
 return new;
end $$;
revoke all on function oyun.tg_bakan_fezleke_ilet() from public,anon,authenticated;
drop trigger if exists adliye_bakan_fezleke_ilet on oyun.adliye_davalar;
create trigger adliye_bakan_fezleke_ilet
 after update of kesin on oyun.adliye_davalar for each row
 when (new.kesin is true and old.kesin is distinct from true)
 execute function oyun.tg_bakan_fezleke_ilet();

create or replace function public.bakan_fezleke_listesi()
returns jsonb language plpgsql stable security definer set search_path='' as $$
declare p oyun.profiller:=oyun.profilim(); cb boolean;
begin
 cb:=exists(select 1 from oyun.makamlar m where m.tur='cb' and m.user_id=p.id and m.bit is null);
 return jsonb_build_object(
  'cb_miyim',cb,
  'bekleyen',case when cb then (select count(*) from oyun.bakan_fezleke f where f.durum='bekliyor') else 0 end,
  'dosyalar',coalesce((select jsonb_agg(jsonb_build_object(
    'id',q.id,'dava_id',q.dava_id,'bakan',oyun.kad(q.bakan_id),'bakanlik',bk.ad,
    'karar',q.karar,'mahkeme_gerekce',q.mahkeme_gerekce,'mahkeme_hakim',oyun.kad(q.mahkeme_hakim),
    'mahkeme_karar_at',q.mahkeme_karar_at,'iletilme',q.iletilme,'durum',q.durum,
    'cb',oyun.kad(q.cb_id),'cb_gerekce',q.cb_gerekce,'cb_karar_at',q.cb_karar_at,
    'benim',q.bakan_id=p.id,'islem_yapabilirim',cb and q.durum='bekliyor',
    'gorevde',exists(select 1 from oyun.makamlar m where m.id=q.makam_id and m.user_id=q.bakan_id and m.bit is null)
  ) order by q.iletilme desc,q.id desc)
  from (select * from oyun.bakan_fezleke f where cb or f.bakan_id=p.id
        order by f.iletilme desc,f.id desc limit 70) q
  join oyun.bakanliklar bk on bk.kod=q.bakanlik),'[]'::jsonb)
 );
end $$;
revoke all on function public.bakan_fezleke_listesi() from public,anon,authenticated;
grant execute on function public.bakan_fezleke_listesi() to authenticated,service_role;

create or replace function public.bakan_fezleke_karar(p_id bigint,p_karar text,p_gerekce text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare p oyun.profiller:=oyun.profilim(); f oyun.bakan_fezleke; t timestamptz:=oyun.simdi(); g text:=trim(coalesce(p_gerekce,'')); m oyun.makamlar; k text;
begin
 if not exists(select 1 from oyun.makamlar x where x.tur='cb' and x.user_id=p.id and x.bit is null) then
  raise exception 'Fezleke kararı yalnız görevdeki Cumhurbaşkanı tarafından verilebilir.';
 end if;
 if p_karar not in ('gorevden_al','gorevde_tut') or p_karar is null then raise exception 'Geçersiz karar.'; end if;
 if char_length(g) not between 20 and 1200 then raise exception 'Cumhurbaşkanlığı karar gerekçesi 20-1200 karakter olmalıdır.'; end if;
 select * into f from oyun.bakan_fezleke where id=p_id for update;
 if f.id is null then raise exception 'Fezleke bulunamadı.'; end if;
 if f.durum<>'bekliyor' then raise exception 'Bu fezleke daha önce karara bağlanmış.'; end if;
 select * into m from oyun.makamlar where id=f.makam_id for update;
 if m.id is null or m.bit is not null or m.tur<>'bakan' or m.user_id<>f.bakan_id or m.bakanlik<>f.bakanlik then
  update oyun.bakan_fezleke set durum='gorev_sona_erdi',cb_id=p.id,cb_gerekce='Bakanın ilgili görev süresi sona erdi. '||g,cb_karar_at=t where id=f.id;
  perform oyun.bildir(f.bakan_id,format('Fezleke #%s: İlgili bakanlık görevi zaten sona erdiği için dosya kapatıldı.',f.id),t);
  return public.bakan_fezleke_listesi();
 end if;
 if p_karar='gorevden_al' then
  perform oyun.makam_bitir(m.id,t,'gorevden_alindi');
  k:='gorevden_alindi';
 else
  k:='gorevde_tutuldu';
 end if;
 update oyun.bakan_fezleke set durum=k,cb_id=p.id,cb_gerekce=g,cb_karar_at=t where id=f.id;
 perform oyun.bildir(f.bakan_id,format('Cumhurbaşkanlığı fezleke #%s hakkında karar verdi: %s. Gerekçe: %s',f.id,case when k='gorevden_alindi' then 'bakanlık görevinden alındınız' else 'görevde kalacaksınız' end,left(g,450)),t);
 perform oyun.olay('adliye',format('Cumhurbaşkanlığı, %s hakkındaki fezleke #%s dosyasında %s kararı verdi. Gerekçe: %s',oyun.kad(f.bakan_id),f.id,case when k='gorevden_alindi' then 'görevden alma' else 'görevde tutma' end,left(g,330)),null,null,t);
 return public.bakan_fezleke_listesi();
end $$;
revoke all on function public.bakan_fezleke_karar(bigint,text,text) from public,anon,authenticated;
grant execute on function public.bakan_fezleke_karar(bigint,text,text) to authenticated,service_role;
