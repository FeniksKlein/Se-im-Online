-- 21 Ekim erken genel seçiminde milletvekili adaylık kapısı ve CB kampanyaları.
-- Var olan başvurulara, oylara, makamlara ve parti kararlarına dokunmaz.

create or replace function public.aday_ol(p_tur text) returns jsonb
language plpgsql security definer set search_path = 'oyun','public','pg_temp' as $$
declare
  p oyun.profiller := oyun.profilim();
  t timestamptz := oyun.simdi();
  s oyun.secimler;
  k oyun.cb_kararlar;
begin
  if p.id is null then raise exception 'Önce giriş yapmalısın.'; end if;
  if p_tur not in ('mv_on','bel_on','kurultay','cb_on') then
    raise exception 'Geçersiz adaylık türü.';
  end if;

  select * into s from oyun.secimler
  where tur = p_tur and durum = 'bekliyor'
    and t >= basvuru_bas and t < basvuru_bit
    and (
      not ara
      or (p_tur = 'bel_on' and hedef_il_id = p.il_id)
      or (p_tur = 'kurultay' and hedef_parti_id = p.parti_id)
      or (ara_neden = 'erken_secim' and p_tur in ('mv_on','cb_on')
          and hedef_parti_id is null and hedef_il_id is null)
    )
  order by ara desc, basvuru_bit, id desc limit 1;
  if s.id is null then raise exception 'Bu adaylık için başvuru şu anda açık değil.'; end if;
  if p.parti_id is null then raise exception 'Parti adaylığı için bir partiye üye olmalısın. Bağımsız adaylık seçeneğini de kullanabilirsin.'; end if;
  if oyun.uyari(p,t) is not null then raise exception '%', oyun.uyari(p,t); end if;
  if (select kurulus_bit from oyun.partiler where id = p.parti_id) is not null then
    raise exception 'Partin henüz kuruluş aşamasında: kurucu üye sayısı tamamlanmadan seçime katılamaz.';
  end if;
  if s.ara and s.hedef_il_id is not null and p.il_id is distinct from s.hedef_il_id then
    raise exception 'Bu ara seçim senin ilin için değil.';
  end if;
  if s.ara and s.hedef_parti_id is not null and p.parti_id is distinct from s.hedef_parti_id then
    raise exception 'Bu olağanüstü kurultay senin partin için değil.';
  end if;
  if p_tur = 'bel_on' and exists(select 1 from oyun.partiler where gb = p.id) then
    raise exception 'Genel başkan belediye başkanı adayı olamaz; milletvekili adaylığı serbesttir.';
  end if;
  if oyun.teskilat_engeli(p,p_tur) is not null then
    raise exception '%', oyun.teskilat_engeli(p,p_tur);
  end if;
  if p_tur = 'cb_on' then
    select * into k from oyun.cb_kararlar
    where donem = s.donem and parti_id = p.parti_id;
    if k.yontem in ('kendisi','baskasi') then
      raise exception 'Genel başkan Cumhurbaşkanı adayını doğrudan belirledi. Partinin ön seçimi yapılmıyor; aday parti kararında kesinleşti.';
    end if;
    if k.yontem = 'destek' then
      raise exception 'Partin başka partinin Cumhurbaşkanı adayını destekliyor; ön seçim yapılmıyor.';
    end if;
  end if;
  insert into oyun.adaylar(secim_id,user_id,parti_id,il_id,basvuru_at)
  values(s.id,p.id,p.parti_id,case when p_tur in ('mv_on','bel_on') then p.il_id end,t)
  on conflict(secim_id,user_id) do nothing;
  if not found then raise exception 'Bu seçime zaten başvurdun.'; end if;
  perform oyun.aday_ucreti_al(p,p_tur,t);
  return public.durum();
end $$;

-- Kampanya kayıtları açık API şemasında değildir; tüm erişim kimlik doğrulayan RPC'lerden geçer.
create table if not exists oyun.cb_kampanyalar (
  donem text not null,
  user_id uuid not null references oyun.profiller(id),
  slogan text not null default '',
  vizyon text not null default '',
  vaatler jsonb not null default '[]'::jsonb,
  guncelleme timestamptz not null default now(),
  primary key (donem,user_id)
);
create table if not exists oyun.cb_kampanya_etkinlikler (
  id bigint generated by default as identity primary key,
  donem text not null,
  user_id uuid not null references oyun.profiller(id),
  tur text not null check (tur in ('sosyal_medya','afis','halk_bulusmasi','tv')),
  baslik text not null,
  bedel numeric not null,
  zaman timestamptz not null default now()
);
create index if not exists cb_kampanya_etkinlik_donem_idx on oyun.cb_kampanya_etkinlikler(donem,zaman desc);
alter table oyun.cb_kampanyalar enable row level security;
alter table oyun.cb_kampanya_etkinlikler enable row level security;
revoke all on oyun.cb_kampanyalar, oyun.cb_kampanya_etkinlikler from public, anon, authenticated;

create or replace function public.cb_kampanya_bilgi(p_secim bigint default null) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  u uuid := auth.uid();
  s oyun.secimler;
  r jsonb;
begin
  if u is null then raise exception 'Oturum açmalısın.'; end if;
  if p_secim is null then
    select * into s from oyun.secimler where tur='cb' and durum='bekliyor'
      order by ara desc,oy_bas limit 1;
  else
    select * into s from oyun.secimler where id=p_secim and tur in ('cb','cb_on','cb2');
    if s.tur = 'cb_on' then
      select * into s from oyun.secimler where donem=s.donem and tur='cb' order by id desc limit 1;
    end if;
  end if;
  if s.id is null then raise exception 'Cumhurbaşkanlığı seçimi bulunamadı.'; end if;
  select coalesce(jsonb_agg(jsonb_build_object(
    'kad',x.kad,'parti',x.parti,'renk',x.renk,'kisa',x.kisa,
    'benim',x.user_id=u,'kesin',x.kesin,
    'slogan',coalesce(x.slogan,''),'vizyon',coalesce(x.vizyon,''),
    'vaatler',coalesce(x.vaatler,'[]'::jsonb)) order by x.kesin desc,x.kad),'[]'::jsonb)
    into r
  from (
    select distinct on (a.user_id) a.user_id, p.kad, pa.ad as parti,
      pa.renk, pa.kisa, (sec.tur='cb') as kesin,
      kamp.slogan, kamp.vizyon, kamp.vaatler
    from oyun.adaylar a
    join oyun.secimler sec on sec.id=a.secim_id and sec.donem=s.donem and sec.tur in ('cb','cb_on')
    join oyun.profiller p on p.id=a.user_id
    left join oyun.partiler pa on pa.id=a.parti_id
    left join oyun.cb_kampanyalar kamp on kamp.donem=s.donem and kamp.user_id=a.user_id
    order by a.user_id,(sec.tur='cb') desc,a.id desc
  ) x;
  return jsonb_build_object(
    'secim_id',s.id,'donem',s.donem,'oy_bas',s.oy_bas,'oy_bit',s.oy_bit,
    'duzenlenebilir',s.durum='bekliyor' and oyun.simdi()<s.oy_bit,
    'adaylar',r,
    'etkinlikler',coalesce((select jsonb_agg(y order by (y->>'zaman') desc)
      from (select jsonb_build_object('id',ev.id,'tur',ev.tur,'baslik',ev.baslik,
        'kad',p.kad,'zaman',ev.zaman,'bedel',ev.bedel) y
        from oyun.cb_kampanya_etkinlikler ev join oyun.profiller p on p.id=ev.user_id
        where ev.donem=s.donem order by ev.zaman desc limit 40) q),'[]'::jsonb));
end $$;

create or replace function public.cb_kampanya_kaydet(
  p_secim bigint,p_slogan text,p_vizyon text,p_vaatler jsonb default '[]'::jsonb
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  u uuid := auth.uid();
  p oyun.profiller;
  s oyun.secimler;
  sl text; vi text; v jsonb := '[]'::jsonb;
  x text; y jsonb;
begin
  if u is null then raise exception 'Oturum açmalısın.'; end if;
  select * into p from oyun.profiller where id=u;
  select * into s from oyun.secimler where id=p_secim and tur in ('cb','cb_on');
  if s.id is null or s.durum <> 'bekliyor' or oyun.simdi()>=s.oy_bit then
    raise exception 'Bu seçim için kampanya süresi doldu.';
  end if;
  if oyun.uyari(p,oyun.simdi()) is not null then raise exception '%',oyun.uyari(p,oyun.simdi()); end if;
  if not exists(select 1 from oyun.adaylar a join oyun.secimler es on es.id=a.secim_id
    where a.user_id=u and es.donem=s.donem and es.tur in ('cb','cb_on')) then
    raise exception 'Kampanya düzenlemek için bu seçimin Cumhurbaşkanı adayı veya aday adayı olmalısın.';
  end if;
  sl := oyun.metin_temizle(coalesce(p_slogan,''),80);
  vi := oyun.metin_temizle(coalesce(p_vizyon,''),1000);
  if length(btrim(sl))<3 then raise exception 'Slogan en az 3 karakter olmalı.'; end if;
  if p_vaatler is null or jsonb_typeof(p_vaatler)<>'array' or jsonb_array_length(p_vaatler)>5 then
    raise exception 'En fazla 5 kampanya vaadi yazabilirsin.';
  end if;
  for y in select value from jsonb_array_elements(p_vaatler) loop
    if jsonb_typeof(y)<>'string' then raise exception 'Vaatler yazı olmalı.'; end if;
    x := oyun.metin_temizle(y #>> '{}',160);
    if length(btrim(x))<3 then raise exception 'Her vaat en az 3 karakter olmalı.'; end if;
    v := v || jsonb_build_array(x);
  end loop;
  insert into oyun.cb_kampanyalar(donem,user_id,slogan,vizyon,vaatler,guncelleme)
  values(s.donem,u,sl,vi,v,oyun.simdi())
  on conflict(donem,user_id) do update set slogan=excluded.slogan,
    vizyon=excluded.vizyon,vaatler=excluded.vaatler,guncelleme=excluded.guncelleme;
  return jsonb_build_object('tamam',true);
end $$;

create or replace function public.cb_kampanya_etkinlik(
  p_secim bigint,p_tur text,p_baslik text
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  u uuid := auth.uid(); p oyun.profiller; s oyun.secimler;
  bedel numeric; baslik text; yeni_id bigint;
begin
  if u is null then raise exception 'Oturum açmalısın.'; end if;
  select * into p from oyun.profiller where id=u;
  select * into s from oyun.secimler where id=p_secim and tur in ('cb','cb_on');
  if s.id is null or s.durum <> 'bekliyor' or oyun.simdi() >= s.oy_bas then
    raise exception 'Kampanya etkinlikleri sandık açılmadan önce düzenlenebilir.';
  end if;
  if oyun.uyari(p,oyun.simdi()) is not null then raise exception '%',oyun.uyari(p,oyun.simdi()); end if;
  if not exists(select 1 from oyun.adaylar a join oyun.secimler es on es.id=a.secim_id
    where a.user_id=u and es.donem=s.donem and es.tur in ('cb','cb_on')) then
    raise exception 'Yalnız Cumhurbaşkanı adayları etkinlik düzenleyebilir.';
  end if;
  bedel := case p_tur when 'sosyal_medya' then 2000 when 'afis' then 5000
    when 'halk_bulusmasi' then 10000 when 'tv' then 20000 else null end;
  if bedel is null then raise exception 'Geçersiz kampanya etkinliği.'; end if;
  baslik := oyun.metin_temizle(coalesce(p_baslik,''),120);
  if length(btrim(baslik))<5 then raise exception 'Etkinlik açıklaması en az 5 karakter olmalı.'; end if;
  -- İki eşzamanlı isteğin etkinlik sınırını aşmasına izin verme.
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext(u::text),pg_catalog.hashtext(s.donem));
  if (select count(*) from oyun.cb_kampanya_etkinlikler where donem=s.donem and user_id=u)>=6 then
    raise exception 'Bu seçimde en fazla 6 kampanya etkinliği düzenleyebilirsin.';
  end if;
  if exists(select 1 from oyun.cb_kampanya_etkinlikler where donem=s.donem and user_id=u
    and zaman>oyun.simdi()-interval '30 minutes') then
    raise exception 'Yeni etkinlik düzenlemek için 30 dakika beklemelisin.';
  end if;
  perform oyun.para_islem(u,-bedel,'aday',format('Cumhurbaşkanlığı kampanyası: %s',baslik),oyun.simdi());
  insert into oyun.cb_kampanya_etkinlikler(donem,user_id,tur,baslik,bedel,zaman)
    values(s.donem,u,p_tur,baslik,bedel,oyun.simdi()) returning id into yeni_id;
  perform oyun.olay('secim',format('%s Cumhurbaşkanlığı kampanyası: %s',p.kad,baslik),null,p.parti_id,oyun.simdi());
  return jsonb_build_object('id',yeni_id,'bedel',bedel,'tamam',true);
end $$;

revoke all on function public.aday_ol(text),public.cb_kampanya_bilgi(bigint),
  public.cb_kampanya_kaydet(bigint,text,text,jsonb),public.cb_kampanya_etkinlik(bigint,text,text) from public,anon;
grant execute on function public.aday_ol(text),public.cb_kampanya_bilgi(bigint),
  public.cb_kampanya_kaydet(bigint,text,text,jsonb),public.cb_kampanya_etkinlik(bigint,text,text) to authenticated;
