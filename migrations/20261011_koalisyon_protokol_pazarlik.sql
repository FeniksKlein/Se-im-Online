-- Gizli siyasi pazarlik ve imzali koalisyon protokolleri
CREATE TABLE IF NOT EXISTS oyun.koalisyon_protokol (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 teklif_parti bigint NOT NULL REFERENCES oyun.partiler(id),
 hedef_parti bigint NOT NULL REFERENCES oyun.partiler(id),
 teklif_veren uuid NOT NULL REFERENCES oyun.profiller(id),
 baslik text NOT NULL,
 bakanliklar jsonb NOT NULL DEFAULT '[]'::jsonb,
 yasa_destegi text NOT NULL DEFAULT '',
 ittifak_sartlari text NOT NULL DEFAULT '',
 gizli boolean NOT NULL DEFAULT true,
 durum text NOT NULL DEFAULT 'bekliyor'
  CHECK(durum IN ('bekliyor','imzali','reddedildi','iptal','bozuldu')),
 olusturma timestamptz NOT NULL DEFAULT now(),
 imza_zamani timestamptz,
 imzalayan uuid REFERENCES oyun.profiller(id),
 bozan_parti bigint REFERENCES oyun.partiler(id),
 bozulma_nedeni text,
 CHECK(teklif_parti<>hedef_parti),
 CHECK(char_length(baslik) BETWEEN 4 AND 120),
 CHECK(jsonb_typeof(bakanliklar)='array')
);
CREATE INDEX IF NOT EXISTS koalisyon_protokol_gonderen_idx ON oyun.koalisyon_protokol(teklif_parti, durum);
CREATE INDEX IF NOT EXISTS koalisyon_protokol_hedef_idx ON oyun.koalisyon_protokol(hedef_parti, durum);
CREATE TABLE IF NOT EXISTS oyun.koalisyon_itibar (
 parti_id bigint PRIMARY KEY REFERENCES oyun.partiler(id),
 ihlal_sayisi integer NOT NULL DEFAULT 0 CHECK (ihlal_sayisi>=0),
 son_ihlal timestamptz
);
ALTER TABLE oyun.koalisyon_protokol ENABLE ROW LEVEL SECURITY;
ALTER TABLE oyun.koalisyon_itibar ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION oyun.koalisyon_lider(p_parti bigint)
RETURNS boolean LANGUAGE sql STABLE SET search_path='' AS $$
 SELECT EXISTS(SELECT 1 FROM oyun.partiler pa WHERE pa.id=p_parti AND NOT pa.kapali
  AND (pa.gb=auth.uid() OR (pa.gb IS NULL AND pa.gb_vekil=auth.uid())))
$$;

CREATE OR REPLACE FUNCTION public.koalisyon_durum()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path='oyun','public','pg_temp' AS $$
DECLARE u uuid:=auth.uid(); benim bigint;
BEGIN
 IF u IS NULL THEN RAISE EXCEPTION 'Oturum gerekli'; END IF;
 SELECT id INTO benim FROM oyun.partiler WHERE NOT kapali AND (gb=u OR (gb IS NULL AND gb_vekil=u)) ORDER BY id LIMIT 1;
 RETURN jsonb_build_object(
 'yonettigim',benim,
 'partiler',coalesce((SELECT jsonb_agg(jsonb_build_object('id',id,'ad',ad,'kisa',kisa) ORDER BY id) FROM oyun.partiler WHERE NOT kapali),'[]'::jsonb),
 'bakanliklar',coalesce((SELECT jsonb_agg(jsonb_build_object('kod',kod,'ad',ad) ORDER BY sira) FROM oyun.bakanliklar),'[]'::jsonb),
 'anlasmalar',coalesce((
 SELECT jsonb_agg(jsonb_build_object(
  'id',k.id,'baslik',k.baslik,'teklif_parti',k.teklif_parti,'hedef_parti',k.hedef_parti,
  'bakanliklar',k.bakanliklar,'yasa_destegi',k.yasa_destegi,'ittifak_sartlari',k.ittifak_sartlari,
  'gizli',k.gizli,'durum',k.durum,'olusturma',k.olusturma,'imza_zamani',k.imza_zamani,
  'bozan_parti',k.bozan_parti,'bozulma_nedeni',k.bozulma_nedeni
 ) ORDER BY k.id DESC)
 FROM oyun.koalisyon_protokol k
 WHERE k.teklif_parti=benim OR k.hedef_parti=benim
    OR (NOT k.gizli AND k.durum IN ('imzali','bozuldu'))
 ),'[]'::jsonb),
 'itibar',coalesce((SELECT jsonb_agg(jsonb_build_object('parti_id',p.id,'ihlal',coalesce(i.ihlal_sayisi,0)) ORDER BY p.id)
 FROM oyun.partiler p LEFT JOIN oyun.koalisyon_itibar i ON i.parti_id=p.id WHERE NOT p.kapali),'[]'::jsonb));
END $$;

CREATE OR REPLACE FUNCTION public.koalisyon_teklif(
 p_hedef bigint,p_baslik text,p_bakanliklar jsonb,p_yasa text,p_ittifak text,p_gizli boolean DEFAULT true
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='oyun','public','pg_temp' AS $$
DECLARE u uuid:=auth.uid(); kaynak bigint; kid bigint;
BEGIN
 SELECT id INTO kaynak FROM oyun.partiler WHERE NOT kapali AND (gb=u OR (gb IS NULL AND gb_vekil=u)) ORDER BY id LIMIT 1;
 IF kaynak IS NULL THEN RAISE EXCEPTION 'Yalnizca parti genel baskani protokol teklif edebilir'; END IF;
 IF p_hedef IS NULL OR kaynak=p_hedef OR NOT EXISTS(SELECT 1 FROM oyun.partiler WHERE id=p_hedef AND NOT kapali AND gb IS NOT NULL)
 THEN RAISE EXCEPTION 'Gecerli bir diger siyasi parti sec'; END IF;
 IF char_length(trim(coalesce(p_baslik,''))) NOT BETWEEN 4 AND 120
  OR char_length(coalesce(p_yasa,''))>1500 OR char_length(coalesce(p_ittifak,''))>1500
 THEN RAISE EXCEPTION 'Metin uzunluklarini kontrol et'; END IF;
 IF jsonb_typeof(coalesce(p_bakanliklar,'[]'::jsonb))<>'array' OR jsonb_array_length(coalesce(p_bakanliklar,'[]'::jsonb))>50
 THEN RAISE EXCEPTION 'Bakanlik listesi gecersiz'; END IF;
 IF EXISTS(
 SELECT 1 FROM jsonb_array_elements(coalesce(p_bakanliklar,'[]'::jsonb)) x(v)
 WHERE jsonb_typeof(x.v)<>'object'
 OR NOT EXISTS (SELECT 1 FROM oyun.bakanliklar b WHERE b.kod=x.v->>'kod')
 OR coalesce(x.v->>'parti_id','') NOT IN (kaynak::text,p_hedef::text)
 ) THEN RAISE EXCEPTION 'Bakanlik kodu veya paylasimi gecersiz'; END IF;
 IF EXISTS(SELECT 1 FROM (
  SELECT x.v->>'kod' kod FROM jsonb_array_elements(coalesce(p_bakanliklar,'[]'::jsonb)) x(v)
  GROUP BY 1 HAVING count(*)>1) t) THEN RAISE EXCEPTION 'Bakanlik iki kez paylasilamaz'; END IF;
 IF EXISTS(SELECT 1 FROM oyun.koalisyon_protokol WHERE durum='bekliyor' AND teklif_parti=kaynak AND hedef_parti=p_hedef)
 THEN RAISE EXCEPTION 'Bu partiye gonderilmis bekleyen teklifin var'; END IF;
 INSERT INTO oyun.koalisyon_protokol(teklif_parti,hedef_parti,teklif_veren,baslik,bakanliklar,yasa_destegi,ittifak_sartlari,gizli)
 VALUES(kaynak,p_hedef,u,trim(p_baslik),coalesce(p_bakanliklar,'[]'::jsonb),coalesce(p_yasa,''),coalesce(p_ittifak,''),coalesce(p_gizli,true)) RETURNING id INTO kid;
 INSERT INTO oyun.bildirimler(user_id,zaman,metin)
 SELECT gb,now(),'Partinize gizli koalisyon protokolu teklifi geldi. Partiler > Siyasi pazarliklar bolumunden yanitlayin.'
 FROM oyun.partiler WHERE id=p_hedef AND gb IS NOT NULL;
 RETURN jsonb_build_object('tamam',true,'id',kid);
END $$;

CREATE OR REPLACE FUNCTION public.koalisyon_yanit(p_id bigint,p_kabul boolean)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='oyun','public','pg_temp' AS $$
DECLARE k oyun.koalisyon_protokol; u uuid:=auth.uid();
BEGIN
 SELECT * INTO k FROM oyun.koalisyon_protokol WHERE id=p_id FOR UPDATE;
 IF k.id IS NULL OR k.durum<>'bekliyor' OR NOT oyun.koalisyon_lider(k.hedef_parti)
 THEN RAISE EXCEPTION 'Yanitsiz protokol veya yetki bulunamadi'; END IF;
 IF NOT oyun.koalisyon_lider(k.teklif_parti) THEN RAISE EXCEPTION 'Teklif eden partinin genel baskani degismis; yeni teklif gerekir'; END IF;
 UPDATE oyun.koalisyon_protokol SET durum=case when p_kabul then 'imzali' else 'reddedildi' end,
 imza_zamani=case when p_kabul then now() end,imzalayan=case when p_kabul then u end WHERE id=p_id;
 INSERT INTO oyun.bildirimler(user_id,zaman,metin)
 SELECT gb,now(),case when p_kabul then 'Koalisyon protokolunuz imzalandi.' else 'Koalisyon teklifiniz reddedildi.' end
 FROM oyun.partiler WHERE id=k.teklif_parti AND gb IS NOT NULL;
 RETURN jsonb_build_object('tamam',true,'durum',case when p_kabul then 'imzali' else 'reddedildi' end);
END $$;

CREATE OR REPLACE FUNCTION public.koalisyon_sonlandir(p_id bigint,p_neden text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='oyun','public','pg_temp' AS $$
DECLARE k oyun.koalisyon_protokol; u uuid:=auth.uid(); bozan bigint; lider uuid;
BEGIN
 SELECT * INTO k FROM oyun.koalisyon_protokol WHERE id=p_id FOR UPDATE;
 IF k.id IS NULL THEN RAISE EXCEPTION 'Protokol bulunamadi'; END IF;
 IF oyun.koalisyon_lider(k.teklif_parti) THEN bozan:=k.teklif_parti;
 ELSIF oyun.koalisyon_lider(k.hedef_parti) THEN bozan:=k.hedef_parti;
 ELSE RAISE EXCEPTION 'Yalnizca protokolu imzalayan partilerin genel baskanlari islem yapabilir'; END IF;
 IF k.durum='bekliyor' THEN
   IF bozan<>k.teklif_parti THEN RAISE EXCEPTION 'Bekleyen teklifi sadece teklifi yapan iptal edebilir'; END IF;
   UPDATE oyun.koalisyon_protokol SET durum='iptal' WHERE id=p_id;
 ELSIF k.durum='imzali' THEN
   IF char_length(trim(coalesce(p_neden,'')))<10 OR char_length(p_neden)>800 THEN RAISE EXCEPTION 'En az 10 en fazla 800 karakter gerekce yaz'; END IF;
   UPDATE oyun.koalisyon_protokol SET durum='bozuldu',bozan_parti=bozan,bozulma_nedeni=trim(p_neden) WHERE id=p_id;
   INSERT INTO oyun.koalisyon_itibar(parti_id,ihlal_sayisi,son_ihlal) VALUES(bozan,1,now())
    ON CONFLICT(parti_id) DO UPDATE SET ihlal_sayisi=oyun.koalisyon_itibar.ihlal_sayisi+1,son_ihlal=now();
   SELECT gb INTO lider FROM oyun.partiler WHERE id=bozan;
   IF lider IS NOT NULL THEN
    INSERT INTO oyun.itibar(user_id,tutulan,bozulan) VALUES(lider,0,1)
    ON CONFLICT (user_id) DO UPDATE SET bozulan=oyun.itibar.bozulan+1;
   END IF;
 ELSE RAISE EXCEPTION 'Bu protokol artik islem gormuyor'; END IF;
 RETURN jsonb_build_object('tamam',true,'durum',case when k.durum='bekliyor' then 'iptal' else 'bozuldu' end);
END $$;
