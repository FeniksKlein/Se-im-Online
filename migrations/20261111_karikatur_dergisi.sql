-- ESKI gazete, abonelik, oyuncu, sirket ve cuzdan verileri korunur. Tabloya dogrudan Data API erisimi yoktur.
create table if not exists oyun.karikatur_dergi (
 id bigint generated by default as identity primary key,
 ad text not null,
 slogan text not null default '',
 sahip uuid not null references oyun.profiller(id),
 kasa numeric not null default 0 check (kasa >= 0),
 aktif boolean not null default true,
 kurulus timestamptz not null default now(),
 constraint karikatur_dergi_ad_uzunluk check (char_length(ad) between 4 and 40),
 constraint karikatur_dergi_slogan_uzunluk check (char_length(slogan)<=100)
);
create unique index if not exists idx_karikatur_dergi_ad on oyun.karikatur_dergi(lower(ad)) where aktif;
create unique index if not exists idx_karikatur_dergi_sahip on oyun.karikatur_dergi(sahip) where aktif;
create table if not exists oyun.karikatur_sayi (
 id bigint generated by default as identity primary key,
 dergi_id bigint not null references oyun.karikatur_dergi(id),
 no integer not null check(no>=1),
 baslik text not null,
 fiyat numeric not null check(fiyat between 1 and 100000 and fiyat=trunc(fiyat)),
 sayfalar jsonb not null,
 yayin timestamptz not null default now(),
 satis integer not null default 0 check(satis>=0),
 unique(dergi_id,no),
 constraint karikatur_sayi_sayfalar check(jsonb_typeof(sayfalar)='array' and jsonb_array_length(sayfalar) between 1 and 4),
 constraint karikatur_sayi_baslik check(char_length(baslik) between 4 and 90)
);
create table if not exists oyun.karikatur_satin_alma (
 sayi_id bigint not null references oyun.karikatur_sayi(id),
 user_id uuid not null references oyun.profiller(id),
 zaman timestamptz not null default now(),
 tutar numeric not null check(tutar>=0),
 primary key(sayi_id,user_id)
);
create index if not exists idx_karikatur_satin_alma_user on oyun.karikatur_satin_alma(user_id,zaman desc);
create index if not exists idx_karikatur_sayi_yayin on oyun.karikatur_sayi(yayin desc);
alter table oyun.karikatur_dergi enable row level security;
alter table oyun.karikatur_sayi enable row level security;
alter table oyun.karikatur_satin_alma enable row level security;
revoke all on oyun.karikatur_dergi,oyun.karikatur_sayi,oyun.karikatur_satin_alma from public,anon,authenticated;

create or replace function public.dergi_raf()
returns jsonb language plpgsql security definer set search_path='' as $f$
declare u uuid:=auth.uid(); sonuc jsonb;
begin
 if u is null then raise exception 'Oturum acman gerekiyor.'; end if;
 select jsonb_build_object(
  'kurulus_ucreti', oyun.gazete_kur_ucreti(),
  'benim', (select jsonb_build_object('id',d.id,'ad',d.ad,'slogan',d.slogan,'kasa',d.kasa,
    'toplam_satis',(select coalesce(sum(s.satis),0) from oyun.karikatur_sayi s where s.dergi_id=d.id))
    from oyun.karikatur_dergi d where d.sahip=u and d.aktif limit 1),
  'dergiler', coalesce((select jsonb_agg(jsonb_build_object('id',d.id,'ad',d.ad,'slogan',d.slogan,
    'sahip',coalesce(p.kad,'Oyuncu'),
    'sayi_sayisi',(select count(*) from oyun.karikatur_sayi s where s.dergi_id=d.id),
    'son_sayi',(select max(no) from oyun.karikatur_sayi s where s.dergi_id=d.id))
    order by d.kurulus desc) from oyun.karikatur_dergi d
    left join oyun.profiller p on p.id=d.sahip where d.aktif),'[]'::jsonb),
  'sayilar', coalesce((select jsonb_agg(jsonb_build_object(
    'id',s.id,'dergi_id',d.id,'dergi',d.ad,'no',s.no,'baslik',s.baslik,'fiyat',s.fiyat,
    'sablon',s.sayfalar->0->>'sablon',
    'sayfa_sayisi',jsonb_array_length(s.sayfalar),'yayin',s.yayin,'satis',s.satis,
    'sahibim',d.sahip=u,'satin_aldim',exists(select 1 from oyun.karikatur_satin_alma x where x.sayi_id=s.id and x.user_id=u)
    ) order by s.yayin desc)
    from oyun.karikatur_sayi s join oyun.karikatur_dergi d on d.id=s.dergi_id where d.aktif),'[]'::jsonb)
 ) into sonuc;
 return sonuc;
end; $f$;

create or replace function public.dergi_kur(p_ad text,p_slogan text default '')
returns jsonb language plpgsql security definer set search_path='' as $f$
declare u uuid:=auth.uid(); t timestamptz:=oyun.simdi(); ucret numeric:=oyun.gazete_kur_ucreti(); idd bigint;
begin
 if u is null or not exists(select 1 from oyun.profiller where id=u) then raise exception 'Oyuncu profili gerekli.';end if;
 p_ad:=btrim(regexp_replace(coalesce(p_ad,''),'\s+',' ','g'));
 p_slogan:=btrim(coalesce(p_slogan,''));
 if char_length(p_ad) not between 4 and 40 then raise exception 'Dergi adi 4-40 karakter olmali.';end if;
 if char_length(p_slogan)>100 then raise exception 'Slogan en fazla 100 karakter olabilir.';end if;
 if exists(select 1 from oyun.karikatur_dergi where sahip=u and aktif) then raise exception 'Zaten bir dergin var.';end if;
 if exists(select 1 from oyun.karikatur_dergi where lower(ad)=lower(p_ad) and aktif) then raise exception 'Bu dergi adi kullaniliyor.';end if;
 perform oyun.para_islem(u,-ucret,'dergi_kur',format('%s karikatur dergisi kuruldu',p_ad),t);
 insert into oyun.karikatur_dergi(ad,slogan,sahip,kurulus) values(p_ad,p_slogan,u,t) returning id into idd;
 return jsonb_build_object('id',idd,'ad',p_ad,'kurulus_ucreti',ucret);
end; $f$;

create or replace function public.dergi_sayi_yayinla(p_dergi bigint,p_baslik text,p_fiyat numeric,p_sayfalar jsonb)
returns jsonb language plpgsql security definer set search_path='' as $f$
declare u uuid:=auth.uid(); d oyun.karikatur_dergi; s jsonb; n int; k text; bas text; alan text; fld text; sid bigint;
begin
 if u is null then raise exception 'Oturum gerekli.';end if;
 select * into d from oyun.karikatur_dergi where id=p_dergi and aktif for update;
 if d.id is null or d.sahip<>u then raise exception 'Bu dergiyi yayinlama yetkin yok.';end if;
 p_baslik:=btrim(coalesce(p_baslik,''));
 if char_length(p_baslik) not between 4 and 90 then raise exception 'Sayi basligi 4-90 karakter olmali.';end if;
 if p_fiyat is null or p_fiyat<>trunc(p_fiyat) or p_fiyat not between 1 and 100000 then
   raise exception 'Sayi fiyati 1-100000 TL arasinda tam sayi olmali.';
 end if;
 if p_sayfalar is null or jsonb_typeof(p_sayfalar)<>'array' then raise exception 'Gecerli sayfalar gerekli.';end if;
 if jsonb_array_length(p_sayfalar) not between 1 and 4 or length(p_sayfalar::text)>9000 then
  raise exception 'Bir sayida 1-4 karikatur olabilir; metin uzunluklarini kisalt.';
 end if;
 for s in select value from jsonb_array_elements(p_sayfalar) loop
   if jsonb_typeof(s)<>'object' then raise exception 'Sayfa yapisi gecersiz.';end if;
   k:=coalesce(s->>'sablon','');
   if k not in ('meclis','tv','eylem','adliye','kapak') then raise exception 'Gecerli bir sablon sec.';end if;
   foreach fld in array array['baslik','sol','sag','orta','karakter1','karakter2','karakter3'] loop
    if jsonb_typeof(s->fld) not in ('string','null') and s ? fld then raise exception 'Metin alani hatali.';end if;
    alan:=coalesce(s->>fld,'');
    if char_length(alan)>case when fld in ('sol','sag','orta') then 200 when fld='baslik' then 90 else 45 end then
     raise exception 'Karikatur metni cok uzun: %',fld;
    end if;
   end loop;
 end loop;
 select coalesce(max(no),0)+1 into n from oyun.karikatur_sayi where dergi_id=d.id;
 insert into oyun.karikatur_sayi(dergi_id,no,baslik,fiyat,sayfalar,yayin)
 values(d.id,n,p_baslik,p_fiyat,p_sayfalar,oyun.simdi()) returning id into sid;
 return jsonb_build_object('id',sid,'no',n,'dergi',d.ad,'fiyat',p_fiyat);
end; $f$;

create or replace function public.dergi_sayi_detay(p_sayi bigint)
returns jsonb language plpgsql security definer set search_path='' as $f$
declare u uuid:=auth.uid(); s oyun.karikatur_sayi; d oyun.karikatur_dergi; var boolean;
begin
 if u is null then raise exception 'Oturum gerekli.';end if;
 select * into s from oyun.karikatur_sayi where id=p_sayi;
 select * into d from oyun.karikatur_dergi where id=s.dergi_id and aktif;
 if d.id is null then raise exception 'Dergi sayisi bulunamadi.';end if;
 var:=d.sahip=u or exists(select 1 from oyun.karikatur_satin_alma where sayi_id=s.id and user_id=u);
 return jsonb_build_object('id',s.id,'dergi_id',d.id,'dergi',d.ad,'no',s.no,'baslik',s.baslik,
   'fiyat',s.fiyat,'yayin',s.yayin,'satis',s.satis,'erisim',var,'sahibim',d.sahip=u,
   'sayfa_sayisi',jsonb_array_length(s.sayfalar),'sayfalar',case when var then s.sayfalar else null end);
end; $f$;

create or replace function public.dergi_sayi_satinal(p_sayi bigint)
returns jsonb language plpgsql security definer set search_path='' as $f$
declare u uuid:=auth.uid(); s oyun.karikatur_sayi; d oyun.karikatur_dergi; t timestamptz:=oyun.simdi();
begin
 if u is null or not exists(select 1 from oyun.profiller where id=u) then raise exception 'Oyuncu profili gerekli.';end if;
 select * into s from oyun.karikatur_sayi where id=p_sayi for update;
 select * into d from oyun.karikatur_dergi where id=s.dergi_id and aktif for update;
 if d.id is null then raise exception 'Dergi sayisi bulunamadi.';end if;
 if d.sahip=u then return public.dergi_sayi_detay(s.id);end if;
 if exists(select 1 from oyun.karikatur_satin_alma where sayi_id=s.id and user_id=u) then
  return public.dergi_sayi_detay(s.id);
 end if;
 perform oyun.para_islem(u,-s.fiyat,'dergi_satin_al',format('%s - %s. sayi',d.ad,s.no),t);
 insert into oyun.karikatur_satin_alma(sayi_id,user_id,zaman,tutar) values(s.id,u,t,s.fiyat);
 update oyun.karikatur_dergi set kasa=kasa+s.fiyat where id=d.id;
 update oyun.karikatur_sayi set satis=satis+1 where id=s.id;
 return public.dergi_sayi_detay(s.id);
end; $f$;

create or replace function public.dergi_kazanc_cek(p_dergi bigint,p_tutar numeric)
returns jsonb language plpgsql security definer set search_path='' as $f$
declare u uuid:=auth.uid(); d oyun.karikatur_dergi; t timestamptz:=oyun.simdi();
begin
 if u is null then raise exception 'Oturum gerekli.';end if;
 select * into d from oyun.karikatur_dergi where id=p_dergi and aktif for update;
 if d.id is null or d.sahip<>u then raise exception 'Yalniz dergi sahibi kazanc cekebilir.';end if;
 if p_tutar is null or p_tutar<>trunc(p_tutar) or p_tutar<1 or p_tutar>d.kasa then
  raise exception 'Gecerli bir cekim tutari gir.';
 end if;
 update oyun.karikatur_dergi set kasa=kasa-p_tutar where id=d.id;
 perform oyun.para_islem(u,p_tutar,'dergi_kazanc',format('%s dergisi satis geliri',d.ad),t);
 return jsonb_build_object('kasa',d.kasa-p_tutar,'cekilen',p_tutar);
end; $f$;
revoke all on function public.dergi_raf(),public.dergi_kur(text,text),public.dergi_sayi_yayinla(bigint,text,numeric,jsonb),
 public.dergi_sayi_detay(bigint),public.dergi_sayi_satinal(bigint),public.dergi_kazanc_cek(bigint,numeric)
 from public,anon,authenticated;
grant execute on function public.dergi_raf(),public.dergi_kur(text,text),public.dergi_sayi_yayinla(bigint,text,numeric,jsonb),
 public.dergi_sayi_detay(bigint),public.dergi_sayi_satinal(bigint),public.dergi_kazanc_cek(bigint,numeric)
 to authenticated;
