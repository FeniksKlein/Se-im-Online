-- Resmî makam kabulleri: karşı taraf onay vermeden görüşme, olay ve kıdem oluşmaz.
CREATE TABLE IF NOT EXISTS oyun.resmi_kabul_davetleri (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kod text NOT NULL REFERENCES oyun.resmi_program_tur(kod),
  davet_eden uuid NOT NULL REFERENCES oyun.profiller(id),
  hedef uuid NOT NULL REFERENCES oyun.profiller(id),
  makam text NOT NULL,
  unvan text NOT NULL,
  bakanlik text,
  il_id smallint,
  metin text,
  zaman timestamptz NOT NULL DEFAULT oyun.simdi(),
  son_tarih timestamptz NOT NULL DEFAULT (oyun.simdi() + interval '72 hours'),
  durum text NOT NULL DEFAULT 'bekliyor'
    CHECK (durum IN ('bekliyor','kabul','ret','suresi_doldu')),
  cevap_zaman timestamptz,
  program_id bigint REFERENCES oyun.resmi_program(id),
  CONSTRAINT resmi_kabul_kendine_davet_yok CHECK (davet_eden <> hedef)
);
CREATE UNIQUE INDEX IF NOT EXISTS resmi_kabul_tek_bekleyen
  ON oyun.resmi_kabul_davetleri(davet_eden, hedef, kod) WHERE durum = 'bekliyor';
CREATE INDEX IF NOT EXISTS resmi_kabul_gelen_ix
  ON oyun.resmi_kabul_davetleri(hedef, zaman DESC);
CREATE INDEX IF NOT EXISTS resmi_kabul_giden_ix
  ON oyun.resmi_kabul_davetleri(davet_eden, zaman DESC);
ALTER TABLE oyun.resmi_kabul_davetleri ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON oyun.resmi_kabul_davetleri FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.resmi_kabul_davetlerim()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO ''
AS $func$
DECLARE
  p oyun.profiller := oyun.profilim();
  t timestamptz := oyun.simdi();
BEGIN
  RETURN jsonb_build_object(
    'gelen', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'id', d.id, 'kod', d.kod, 'makam', d.makam, 'unvan', d.unvan,
        'gonderen', g.kad, 'metin', d.metin, 'zaman', d.zaman, 'son_tarih', d.son_tarih
      ) ORDER BY d.zaman DESC)
      FROM oyun.resmi_kabul_davetleri d
      JOIN oyun.profiller g ON g.id = d.davet_eden
      WHERE d.hedef = p.id AND d.durum = 'bekliyor' AND d.son_tarih > t
    ), '[]'::jsonb),
    'giden', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'id', d.id, 'kod', d.kod, 'hedef', h.kad, 'zaman', d.zaman,
        'son_tarih', d.son_tarih, 'durum', d.durum
      ) ORDER BY d.zaman DESC)
      FROM oyun.resmi_kabul_davetleri d
      JOIN oyun.profiller h ON h.id = d.hedef
      WHERE d.davet_eden = p.id AND d.durum = 'bekliyor' AND d.son_tarih > t
    ), '[]'::jsonb)
  );
END
$func$;

CREATE OR REPLACE FUNCTION public.resmi_kabul_yanit(p_id bigint, p_kabul boolean)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $func$
DECLARE
  p oyun.profiller := oyun.profilim();
  t timestamptz := oyun.simdi();
  d oyun.resmi_kabul_davetleri;
  g oyun.profiller;
  k oyun.resmi_program_tur;
  r record;
  son timestamptz;
  pid bigint;
  ozet text;
BEGIN
  SELECT * INTO d FROM oyun.resmi_kabul_davetleri WHERE id = p_id FOR UPDATE;
  IF d.id IS NULL OR d.hedef IS DISTINCT FROM p.id THEN
    RAISE EXCEPTION 'Bu daveti yanıtlama yetkin yok.';
  END IF;
  IF d.durum <> 'bekliyor' THEN
    RAISE EXCEPTION 'Bu davet zaten yanıtlanmış.';
  END IF;
  IF d.son_tarih <= t THEN
    UPDATE oyun.resmi_kabul_davetleri
      SET durum = 'suresi_doldu', cevap_zaman = t WHERE id = d.id;
    RETURN jsonb_build_object('durum', 'suresi_doldu', 'id', d.id);
  END IF;
  IF p_kabul IS DISTINCT FROM true THEN
    UPDATE oyun.resmi_kabul_davetleri SET durum = 'ret', cevap_zaman = t WHERE id = d.id;
    PERFORM oyun.bildir(d.davet_eden, format('%s, %s makam kabul davetini reddetti.', p.kad, d.unvan), t);
    RETURN jsonb_build_object('durum', 'ret', 'id', d.id);
  END IF;
  SELECT * INTO g FROM oyun.profiller WHERE id = d.davet_eden;
  IF g.id IS NULL OR g.yasakli THEN RAISE EXCEPTION 'Davet gönderen oyuncu artık uygun değil.'; END IF;
  SELECT * INTO k FROM oyun.resmi_program_tur WHERE kod = d.kod;
  IF k.kod IS NULL OR k.kategori <> 'Kabul' OR k.nisan IS NOT NULL OR NOT k.hedef THEN
    RAISE EXCEPTION 'Bu davet makam kabulü için geçerli değil.';
  END IF;
  SELECT * INTO r FROM oyun.rp_makamlar(g.id) x
    WHERE x.makam = d.makam
      AND x.bakanlik IS NOT DISTINCT FROM d.bakanlik
      AND x.il_id IS NOT DISTINCT FROM d.il_id LIMIT 1;
  IF r.makam IS NULL THEN RAISE EXCEPTION 'Davet gönderen kişi artık ilgili makamda değil.'; END IF;
  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtext('resmi_program'), pg_catalog.hashtext(g.id::text || d.kod)
  );
  SELECT max(zaman) INTO son FROM oyun.resmi_program
    WHERE user_id = g.id AND kod = d.kod;
  IF son IS NOT NULL AND son + make_interval(hours => k.bekleme_saat) > t THEN
    RAISE EXCEPTION 'Makam sahibi bu kabul için bekleme süresinde.';
  END IF;
  IF EXISTS (SELECT 1 FROM oyun.resmi_program
       WHERE kod = d.kod AND hedef = p.id AND zaman > t - interval '3 days') THEN
    RAISE EXCEPTION 'Bu oyuncu son 3 günde zaten kabul edilmiş.';
  END IF;
  INSERT INTO oyun.resmi_program(
    kod,user_id,makam,unvan,bakanlik,il_id,hedef,metin,zaman,katilim_bit
  ) VALUES (
    d.kod,g.id,d.makam,r.unvan,d.bakanlik,d.il_id,p.id,d.metin,t,null
  ) RETURNING id INTO pid;
  IF k.kidem_yapan > 0 THEN PERFORM oyun.kidem_ekle(g.id,k.kidem_yapan); END IF;
  IF k.kidem_hedef > 0 THEN PERFORM oyun.kidem_ekle(p.id,k.kidem_hedef); END IF;
  UPDATE oyun.resmi_kabul_davetleri
    SET durum = 'kabul', cevap_zaman = t, program_id = pid WHERE id = d.id;
  ozet := format('%s %s, %s adlı oyuncuyu makamında kabul etti%s.',
    r.unvan,g.kad,p.kad,coalesce(' (' || d.metin || ')',''));
  PERFORM oyun.olay('makam',ozet,d.il_id,g.parti_id,t);
  PERFORM oyun.bildir(g.id, format('%s makam kabul davetini onayladı. Görüşme resmî kayda geçti.', p.kad),t);
  PERFORM oyun.bildir(p.id, format('%s %s makamında kabul edildin. Kıdemin +%s.',r.unvan,g.kad,k.kidem_hedef),t);
  RETURN jsonb_build_object('durum','kabul','id',d.id,'program_id',pid);
END
$func$;

-- Eski RPC'nin izin verilen kabuller için doğrudan kayıt yapmasını sunucuda durdur.
-- Kaynağın kalan bütün kontrollerini ve diğer protokol programlarını değiştirme.
DO $patch$
DECLARE
  fn text;
  marker text := '  mal := oyun.rp_maliyet(k, coalesce(il, r.il_id));';
  ek text := $insert$
  IF k.kategori = 'Kabul' AND k.hedef AND k.nisan IS NULL THEN
    UPDATE oyun.resmi_kabul_davetleri
      SET durum = 'suresi_doldu', cevap_zaman = t
      WHERE davet_eden = p.id AND hedef = h.id AND kod = k.kod
        AND durum = 'bekliyor' AND son_tarih <= t;
    IF EXISTS (SELECT 1 FROM oyun.resmi_kabul_davetleri
       WHERE davet_eden = p.id AND hedef = h.id AND kod = k.kod
         AND durum = 'bekliyor' AND son_tarih > t) THEN
      RAISE EXCEPTION 'Bu oyuncuya gönderilmiş yanıt bekleyen davetin var.';
    END IF;
    INSERT INTO oyun.resmi_kabul_davetleri
      (kod,davet_eden,hedef,makam,unvan,bakanlik,il_id,metin,zaman,son_tarih)
    VALUES (k.kod,p.id,h.id,k.makam,r.unvan,r.bakanlik,il,mt,t,t + interval '72 hours');
    PERFORM oyun.bildir(h.id,
      format('Makam kabul daveti: %s %s seni makamında ağırlamak istiyor.%s Bildirimler ekranından kabul et veya reddet.',
      r.unvan,p.kad,coalesce(' Konu: ' || mt || '.', '')),t);
    RETURN public.resmi_program_panel();
  END IF;
$insert$;
BEGIN
  SELECT pg_catalog.pg_get_functiondef(
    'public.resmi_program_yap(text,integer,text,text)'::pg_catalog.regprocedure
  ) INTO fn;
  IF pg_catalog.strpos(fn, 'INSERT INTO oyun.resmi_kabul_davetleri') = 0 THEN
    IF pg_catalog.strpos(fn, marker) = 0 THEN
      RAISE EXCEPTION 'resmi_program_yap imzası değişmiş; güvenli otomatik yama durduruldu.';
    END IF;
    fn := pg_catalog.replace(fn, marker, ek || E'\n' || marker);
    EXECUTE fn;
  END IF;
END
$patch$;
REVOKE ALL ON FUNCTION public.resmi_kabul_davetlerim() FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.resmi_kabul_yanit(bigint,boolean) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.resmi_kabul_davetlerim() TO authenticated;
GRANT EXECUTE ON FUNCTION public.resmi_kabul_yanit(bigint,boolean) TO authenticated;
