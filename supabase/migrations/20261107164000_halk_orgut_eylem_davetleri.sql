create or replace function public.sokak_davet_gonder(p_eylem bigint,p_hedef_tur text,p_hedef_id bigint)
returns jsonb language plpgsql security definer set search_path='' as $f$
declare u uuid:=auth.uid(); x oyun.sokak_eylem; lider uuid; org_ad text; t timestamptz:=oyun.simdi(); did bigint;
begin
 if u is null then raise exception 'Oturum gerekli';end if;
 perform pg_advisory_xact_lock(781231,1);
 if (select yasakli from oyun.profiller where id=u) then raise exception 'Hesap kısıtlı';end if;
 select * into x from oyun.sokak_eylem where id=p_eylem for update;
 if x.id is null or x.baslatan<>u or x.durum<>'aktif' or x.bitis<=t then raise exception 'Yalnız aktif eylemin organizatörü davet gönderebilir';end if;
 if p_hedef_tur is null or p_hedef_tur not in ('parti','dernek') or p_hedef_id is null then raise exception 'Geçersiz davet hedefi';end if;
 if x.org_tur=p_hedef_tur and x.org_id=p_hedef_id then raise exception 'Kurucu kuruluş zaten eylemde';end if;
 if p_hedef_tur='parti' then select gb,ad into lider,org_ad from oyun.partiler where id=p_hedef_id and not kapali;
 else select baskan,ad into lider,org_ad from oyun.dernekler where id=p_hedef_id and not kapali;end if;
 if lider is null then raise exception 'Bu kuruluşun aktif lideri yok';end if;
 if exists(select 1 from oyun.sokak_eylem_destek where eylem_id=p_eylem and destekci_tur=p_hedef_tur and destekci_id=p_hedef_id::text and taraf='muhalefet') then raise exception 'Kuruluş zaten destek veriyor';end if;
 insert into oyun.sokak_davet(eylem_id,hedef_tur,hedef_id,gonderen) values(p_eylem,p_hedef_tur,p_hedef_id,u)
 on conflict(eylem_id,hedef_tur,hedef_id) do update set durum='bekliyor',gonderme=t,cevap_zamani=null,gonderen=u returning id into did;
 insert into oyun.bildirimler(user_id,zaman,metin)
 values(lider,t,'Halk hareketi #'||p_eylem||' için '||org_ad||' davet edildi. Halk Hareketleri ekranından yanıtlayın.');
 return jsonb_build_object('tamam',true,'davet_id',did);
end $f$;
create or replace function public.sokak_davet_yanit(p_davet bigint,p_kabul boolean)
returns jsonb language plpgsql security definer set search_path='' as $f$
declare u uuid:=auth.uid(); v oyun.sokak_davet; x oyun.sokak_eylem; lider uuid; a oyun.sokak_eylem_ayar; t timestamptz:=oyun.simdi();
begin
 if u is null or p_kabul is null then raise exception 'Oturum ve yanıt gerekli';end if;
 perform pg_advisory_xact_lock(781231,1);
 if (select yasakli from oyun.profiller where id=u) then raise exception 'Hesap kısıtlı';end if;
 select * into v from oyun.sokak_davet where id=p_davet for update;
 if v.id is null or v.durum<>'bekliyor' then raise exception 'Bekleyen davet bulunamadı';end if;
 if v.hedef_tur='parti' then select gb into lider from oyun.partiler where id=v.hedef_id and not kapali;
 else select baskan into lider from oyun.dernekler where id=v.hedef_id and not kapali;end if;
 if lider is distinct from u then raise exception 'Yalnız davet edilen kuruluşun lideri yanıtlayabilir';end if;
 select * into x from oyun.sokak_eylem where id=v.eylem_id for update;
 if x.id is null or x.durum<>'aktif' or x.bitis<=t then raise exception 'Eylem artık aktif değil';end if;
 if p_kabul then
  select * into a from oyun.sokak_eylem_ayar where id=1;
  if not exists(select 1 from oyun.sokak_eylem_destek where eylem_id=x.id and destekci_tur=v.hedef_tur and destekci_id=v.hedef_id::text)
   and (select count(distinct d.eylem_id) from oyun.sokak_eylem_destek d join oyun.sokak_eylem e on e.id=d.eylem_id where d.destekci_tur=v.hedef_tur and d.destekci_id=v.hedef_id::text and e.durum='aktif' and e.bitis>t)>=a.orgut_es_zamanli_destek_siniri
  then raise exception 'Kuruluşun aynı anda destekleyebileceği eylem sınırı dolu';end if;
  if exists(select 1 from oyun.sokak_eylem_destek where eylem_id=x.id and destekci_tur=v.hedef_tur and destekci_id=v.hedef_id::text and taraf='iktidar') then raise exception 'Kuruluş bu eylemde karşı tarafı destekliyor';end if;
  insert into oyun.sokak_eylem_destek(eylem_id,destekci_tur,destekci_id,taraf,temsilci,destek_turu,tutar)
  values(x.id,v.hedef_tur,v.hedef_id::text,'muhalefet',u,'katilim',0) on conflict do nothing;
 end if;
 update oyun.sokak_davet set durum=case when p_kabul then 'kabul' else 'ret' end,cevap_zamani=t where id=v.id;
 perform oyun.sokak_duyur(x.id,'Eylem #'||x.id||' kuruluş daveti '||case when p_kabul then 'kabul edildi.' else 'reddedildi.' end);
 if p_kabul then perform oyun.sokak_yenile(x.id);end if;
 return jsonb_build_object('tamam',true,'kabul',p_kabul);
end $f$;

create or replace function public.sokak_org_panel()
returns jsonb language plpgsql security definer set search_path='' as $f$
declare u uuid:=auth.uid(); b jsonb;
begin
 if u is null then raise exception 'Oturum gerekli';end if;
 b:=public.sokak_uzlasma_panel();
 return b||jsonb_build_object(
  'baslatma_kaynaklari',coalesce((select jsonb_agg(q order by q.ad) from (
   select 'parti' tur,id,ad from oyun.partiler where gb=u and not kapali
   union all select 'dernek',id,ad from oyun.dernekler where baskan=u and not kapali
  )q),'[]'::jsonb),
  'davet_hedefleri',coalesce((select jsonb_agg(q order by q.ad) from (
   select 'parti' tur,id,ad from oyun.partiler where not kapali and gb is not null
   union all select 'dernek',id,ad from oyun.dernekler where not kapali and baskan is not null
  )q),'[]'::jsonb),
  'davetler',coalesce((select jsonb_agg(jsonb_build_object('id',v.id,'eylem_id',v.eylem_id,'hedef_tur',v.hedef_tur,'hedef_id',v.hedef_id,'durum',v.durum,
   'kurulus',case when v.hedef_tur='parti' then (select ad from oyun.partiler where id=v.hedef_id) else (select ad from oyun.dernekler where id=v.hedef_id) end,
   'eylem',e.gerekce,'il',(select ad from oyun.iller where id=e.il_id),'gonderme',v.gonderme))
   from oyun.sokak_davet v join oyun.sokak_eylem e on e.id=v.eylem_id
   where v.durum='bekliyor' and e.durum='aktif' and e.bitis>oyun.simdi()
   and (v.hedef_tur='parti' and exists(select 1 from oyun.partiler where id=v.hedef_id and gb=u and not kapali)
    or v.hedef_tur='dernek' and exists(select 1 from oyun.dernekler where id=v.hedef_id and baskan=u and not kapali))),'[]'::jsonb)
 );
end $f$;

do $do$
declare s text;
begin
 s:=pg_get_functiondef('public.sokak_eylemler()'::regprocedure);
 if position('and not oyun.sokak_iktidar(u)' in s)=0 then raise exception 'Güncellenecek temel panel bulunamadı';end if;
 s:=replace(s,'exists(select 1 from oyun.partiler where gb=u and not kapali) and not oyun.sokak_iktidar(u)',
 '(exists(select 1 from oyun.partiler where gb=u and not kapali) or exists(select 1 from oyun.dernekler where baskan=u and not kapali))');
 s:=replace(s,'''parti'',pa.ad,''il'',i.ad','''parti'',case when e.org_tur=''dernek'' then (select ad from oyun.dernekler where id=e.org_id) else pa.ad end,''il'',i.ad');
 s:=replace(s,'join oyun.partiler pa on pa.id=e.parti_id','left join oyun.partiler pa on pa.id=e.parti_id');
 execute s;
 s:=pg_get_functiondef('public.sokak_destek(bigint,text,text,bigint,numeric)'::regprocedure);
 s:=replace(s,'''muhalefet'' and oyun.sokak_iktidar(u) then raise exception ''İktidar üyeleri uzlaşma tarafını destekleyebilir'';', '''muhalefet'' and false then raise exception ''İktidar üyeleri uzlaşma tarafını destekleyebilir'';');
 execute s;
end $do$;
