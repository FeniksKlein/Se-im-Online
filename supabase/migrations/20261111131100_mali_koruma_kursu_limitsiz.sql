CREATE TABLE IF NOT EXISTS oyun.mali_inceleme_kayit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 zaman timestamptz NOT NULL DEFAULT now(),
 olay text NOT NULL,
 kaynak_id bigint NOT NULL,
 sirket_id bigint,
 oyuncu uuid,
 tutar numeric NOT NULL,
 aciklama text,
 durum text NOT NULL DEFAULT 'inceleme',
 UNIQUE (olay,kaynak_id)
);
ALTER TABLE oyun.mali_inceleme_kayit ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION oyun.banka_sermaye_soguma()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
BEGIN
 IF NEW.tur='sermaye_iade' THEN
  IF EXISTS (
    SELECT 1 FROM oyun.sirket_hareket h
    WHERE h.sirket_id=NEW.banka_id AND h.tutar>0
      AND h.aciklama LIKE 'Ortak % şirket kasasına kendi parasından %'
      AND h.zaman>now()-interval '72 hours'
  ) THEN
    RAISE EXCEPTION 'Banka sermayesi son 72 saatte artırıldı. Sermaye azaltımı için 72 saatlik güvenlik süresi dolmalı.';
  END IF;
  IF EXISTS (
    SELECT 1 FROM oyun.banka_temettu b
    WHERE b.banka_id=NEW.banka_id AND b.tur='sermaye_iade'
      AND b.zaman>now()-interval '7 days'
  ) THEN
    RAISE EXCEPTION 'Aynı bankada sermaye azaltımı en fazla 7 günde bir yapılabilir.';
  END IF;
 END IF;
 RETURN NEW;
END $function$;

CREATE OR REPLACE FUNCTION oyun.buyuk_sirket_ceki_izle()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
BEGIN
 IF NEW.borclu_sirket IS NOT NULL AND NEW.tutar>=1000000 THEN
   INSERT INTO oyun.mali_inceleme_kayit(olay,kaynak_id,sirket_id,oyuncu,tutar,aciklama)
   VALUES('buyuk_sirket_ceki',NEW.id,NEW.borclu_sirket,NEW.duzenleyen,NEW.tutar,
      'Büyük tutarlı şirket çeki; ticari dayanak ve lehtar ilişkisi denetlenebilir.')
   ON CONFLICT(olay,kaynak_id) DO NOTHING;
 END IF;
 RETURN NEW;
END $function$;

CREATE OR REPLACE FUNCTION oyun.cek_taraf_tipi_koruma()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
BEGIN
 IF NEW.borclu_sirket IS NOT NULL THEN
   IF NEW.ilk_lehtar_sirket IS NULL OR NEW.ilk_lehtar IS NOT NULL
      OR NEW.hamil_sirket IS NULL OR NEW.hamil IS NOT NULL THEN
     RAISE EXCEPTION 'Şirket çeki kişiye yazılamaz veya kişiye devredilemez. Şirket çeki yalnızca şirkete düzenlenir.';
   END IF;
 ELSE
   IF (NEW.ilk_lehtar_sirket IS NULL AND NEW.ilk_lehtar IS NULL)
      OR (NEW.ilk_lehtar_sirket IS NOT NULL AND NEW.ilk_lehtar IS NOT NULL)
      OR (NEW.hamil_sirket IS NULL AND NEW.hamil IS NULL)
      OR (NEW.hamil_sirket IS NOT NULL AND NEW.hamil IS NOT NULL) THEN
     RAISE EXCEPTION 'Çek lehtarı ve hamili bir oyuncu veya bir şirket olmalıdır; aynı anda ikisi olamaz.';
   END IF;
 END IF;
 RETURN NEW;
END $function$;

CREATE OR REPLACE FUNCTION oyun.cek_toptan_kaynak_dogrula()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
BEGIN
 IF NEW.borclu_sirket IS NOT NULL
    AND COALESCE(NEW.aciklama,'') LIKE 'Toptan mal bedeli%' THEN
   IF NOT EXISTS (
     SELECT 1 FROM oyun.cek_toptan_teklif x
     WHERE x.cek_id=NEW.id AND x.durum='kabul'
       AND x.magaza_id=NEW.borclu_sirket
       AND x.uretici_id=NEW.ilk_lehtar_sirket
       AND x.cek_hesap_id=NEW.hesap_id
       AND x.toplam-x.nakit=NEW.tutar
       AND x.cek_tarih=NEW.tarih
   ) THEN
      RAISE EXCEPTION 'Toptan mal bedeli çekinde onaylanmış stok/teklif kaydı bulunamadı. Çekli toptan alım ekranını kullanın.';
   END IF;
 END IF;
 RETURN NEW;
END $function$;

CREATE OR REPLACE FUNCTION oyun.sirket_ticaret_hacmi(p_alici bigint, p_satici bigint, p_gun integer DEFAULT 60)
 RETURNS numeric
 LANGUAGE sql
 STABLE
 SET search_path TO ''
AS $function$
 SELECT COALESCE((SELECT SUM(b.tutar) FROM oyun.eko_b2b b
   WHERE b.alici=p_alici AND b.satici=p_satici AND b.zaman>now()-make_interval(days=>p_gun)),0)
 + COALESCE((SELECT SUM(c.tutar) FROM oyun.cekler c
   JOIN oyun.cek_toptan_teklif x ON x.cek_id=c.id AND x.durum='kabul'
   WHERE c.borclu_sirket=p_alici AND c.ilk_lehtar_sirket=p_satici
     AND c.durum<>'iptal' AND c.keside_at>now()-make_interval(days=>p_gun)
     AND x.magaza_id=c.borclu_sirket AND x.uretici_id=c.ilk_lehtar_sirket
     AND x.toplam-x.nakit=c.tutar),0)
$function$;

CREATE OR REPLACE FUNCTION public.akis_yaz(p_metin text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'oyun', 'public', 'pg_temp'
AS $function$
DECLARE
 p oyun.profiller:=oyun.profilim();
 t timestamptz:=oyun.simdi();
 m text; id0 bigint; e text;
BEGIN
 IF p.susturma_bitis IS NOT NULL AND p.susturma_bitis>t THEN
  RAISE EXCEPTION 'Hesabın % tarihine kadar mesaj gönderemez (kural ihlali).',
    to_char(p.susturma_bitis AT TIME ZONE 'Europe/Istanbul','DD.MM.YYYY HH24:MI');
 END IF;
 IF p.adliye_susturma_bitis IS NOT NULL AND p.adliye_susturma_bitis>t THEN
  RAISE EXCEPTION 'Mahkeme kararıyla % tarihine kadar sohbetten susturuldunuz.',
    to_char(p.adliye_susturma_bitis AT TIME ZONE 'Europe/Istanbul','DD.MM.YYYY HH24:MI');
 END IF;
 m:=oyun.metin_temizle(p_metin,1000);
 IF m ~* '(https?://|www\.|\.com\b|\.net\b|\.org\b|t\.me/)' THEN
   RAISE EXCEPTION 'Paylaşımlarda bağlantı kullanılamaz.';
 END IF;
 IF EXISTS (SELECT 1 FROM oyun.akis WHERE user_id=p.id AND zaman>t-interval '1 day' AND lower(metin)=lower(m)) THEN
   RAISE EXCEPTION 'Aynı paylaşımı tekrar yapamazsın.';
 END IF;
 INSERT INTO oyun.akis(user_id,metin,zaman,il_id,parti_id)
 VALUES(p.id,m,t,p.il_id,p.parti_id) RETURNING id INTO id0;
 FOREACH e IN ARRAY oyun.akis_etiketleri(m) LOOP
   INSERT INTO oyun.akis_etiket(akis_id,etiket,zaman,user_id)
   VALUES(id0,e,t,p.id) ON CONFLICT DO NOTHING;
 END LOOP;
 UPDATE oyun.profiller SET son_mesaj=t WHERE id=p.id;
 RETURN jsonb_build_object('tamam',true,'id',id0);
END $function$;

DROP TRIGGER IF EXISTS cek_toptan_kaynak_dogrula_trg ON oyun.cekler;
CREATE CONSTRAINT TRIGGER cek_toptan_kaynak_dogrula_trg
 AFTER INSERT OR UPDATE ON oyun.cekler
 DEFERRABLE INITIALLY DEFERRED
 FOR EACH ROW EXECUTE FUNCTION oyun.cek_toptan_kaynak_dogrula();

DROP TRIGGER IF EXISTS banka_sermaye_soguma_trg ON oyun.banka_temettu;
CREATE TRIGGER banka_sermaye_soguma_trg BEFORE INSERT ON oyun.banka_temettu
 FOR EACH ROW EXECUTE FUNCTION oyun.banka_sermaye_soguma();

DROP TRIGGER IF EXISTS buyuk_sirket_ceki_izle_trg ON oyun.cekler;
CREATE TRIGGER buyuk_sirket_ceki_izle_trg AFTER INSERT ON oyun.cekler
 FOR EACH ROW EXECUTE FUNCTION oyun.buyuk_sirket_ceki_izle();

DROP TRIGGER IF EXISTS cek_taraf_tipi_koruma_trg ON oyun.cekler;
CREATE TRIGGER cek_taraf_tipi_koruma_trg
 BEFORE INSERT OR UPDATE OF borclu_sirket, ilk_lehtar, ilk_lehtar_sirket, hamil, hamil_sirket
 ON oyun.cekler
 FOR EACH ROW EXECUTE FUNCTION oyun.cek_taraf_tipi_koruma();

INSERT INTO oyun.mali_inceleme_kayit (olay,kaynak_id,sirket_id,oyuncu,tutar,aciklama)
SELECT 'gecmis_sirket_sahis_ceki',c.id,c.borclu_sirket,c.duzenleyen,c.odenen,
       'Şirket çekinden şahsi tahsilat: ticari neden ve yetki incelenmeli.'
FROM oyun.cekler c
WHERE c.borclu_sirket IS NOT NULL AND c.durum='odendi'
  AND c.odenen>0 AND c.hamil_sirket IS NULL AND c.hamil IS NOT NULL
ON CONFLICT (olay,kaynak_id) DO NOTHING;
