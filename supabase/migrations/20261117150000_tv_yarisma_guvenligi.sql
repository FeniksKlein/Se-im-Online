
-- TV yarışma, doğrulanmış soru bankası ve tekerrürlü ödül önleme (17 Kasım 2026).
create table if not exists oyun.tv_soru_havuzu (
  id bigint generated by default as identity primary key,
  kategori text not null,
  zorluk smallint not null check(zorluk between 1 and 3),
  soru text not null unique,
  secenekler jsonb not null check(jsonb_typeof(secenekler)='array' and jsonb_array_length(secenekler)=4),
  dogru smallint not null check(dogru between 0 and 3),
  aktif boolean not null default true,
  ekleme timestamptz not null default now()
);
alter table oyun.tv_soru_havuzu enable row level security;
revoke all on oyun.tv_soru_havuzu from public,anon,authenticated;
alter table oyun.tv_anket add column if not exists havuz_soru_id bigint references oyun.tv_soru_havuzu(id);
create unique index if not exists tv_anket_havuz_tekil_idx on oyun.tv_anket(program_id,havuz_soru_id) where havuz_soru_id is not null;
create index if not exists tv_odul_kazanc_kisi_zaman_idx on oyun.tv_odul_kazanc(user_id,zaman desc) where tutar>0;
create index if not exists tv_odul_kazanc_program_idx on oyun.tv_odul_kazanc(program_id) where tutar>0;
create table if not exists oyun.tv_odul_denetim (
  program_id bigint primary key references oyun.tv_program(id),
  kanal_id bigint not null references oyun.tv_kanal(id),
  durum text not null,
  gecerli_soru integer not null,
  gecerli_katilimci integer not null,
  odul_havuzu numeric not null,
  odenen numeric not null,
  iade numeric not null,
  aciklama text not null,
  kayit timestamptz not null default now()
);
alter table oyun.tv_odul_denetim enable row level security;
revoke all on oyun.tv_odul_denetim from public,anon,authenticated;
create or replace function public.tv_soru_listesi(p_program bigint,p_kategori text default null,p_zorluk integer default null)
returns jsonb language plpgsql security definer set search_path = '' as $f$
declare p oyun.profiller:=oyun.profilim(); pr oyun.tv_program; sonuc jsonb;
begin
 select * into pr from oyun.tv_program where id=p_program;
 if pr.id is null or pr.tur<>'yarisma' then raise exception 'Bilgi yarışması bulunamadı.'; end if;
 if not oyun.tv_yonetici_mi(pr,p.id) then raise exception 'Soru havuzunu yalnız sunucu veya kanal sahibi açabilir.'; end if;
 if pr.durum not in ('planli','canli') then raise exception 'Program tamamlandı.'; end if;
 select coalesce(jsonb_agg(jsonb_build_object('id',x.id,'kategori',x.kategori,'zorluk',x.zorluk,'soru',x.soru,'secenekler',x.secenekler)),'[]'::jsonb)
 into sonuc from (
  select q.id,q.kategori,q.zorluk,q.soru,q.secenekler from oyun.tv_soru_havuzu q where q.aktif
    and (p_kategori is null or p_kategori='' or q.kategori=p_kategori)
    and (p_zorluk is null or q.zorluk=p_zorluk)
    and not exists(select 1 from oyun.tv_anket a where a.program_id=p_program and a.havuz_soru_id=q.id)
    order by random() limit 30
 ) x;
 return jsonb_build_object('sorular',sonuc,'toplam',(select count(*) from oyun.tv_soru_havuzu where aktif));
end $f$;
revoke all on function public.tv_soru_listesi(bigint,text,integer) from public,anon;
grant execute on function public.tv_soru_listesi(bigint,text,integer) to authenticated,service_role;

create or replace function public.tv_havuz_soru_ac(p_program bigint,p_soru_id bigint,p_saniye integer default 30)
returns jsonb language plpgsql security definer set search_path = '' as $f$
declare p oyun.profiller:=oyun.profilim(); t timestamptz:=oyun.simdi(); pr oyun.tv_program;
 q oyun.tv_soru_havuzu; sec jsonb; dogru_konum integer; sn integer; soru_id bigint; no integer;
begin
 perform oyun.tv_program_guncelle(p_program);
 select * into pr from oyun.tv_program where id=p_program for update;
 if pr.id is null or pr.tur<>'yarisma' then raise exception 'Bilgi yarışması bulunamadı.'; end if;
 if not oyun.tv_yonetici_mi(pr,p.id) then raise exception 'Soru yalnız sunucu veya kanal sahibi tarafından sorulur.'; end if;
 if pr.durum<>'canli' then raise exception 'Soru yalnız canlı yayında sorulur.'; end if;
 perform oyun.yazabilir_mi(p,t);
 select * into q from oyun.tv_soru_havuzu where id=p_soru_id and aktif;
 if q.id is null then raise exception 'Soru havuzda bulunamadı.'; end if;
 if exists(select 1 from oyun.tv_anket where program_id=p_program and havuz_soru_id=q.id)
   then raise exception 'Bu soru bu programda zaten sorulmuş.'; end if;
 if exists(select 1 from oyun.tv_anket where program_id=p_program and not kapandi and kapanis>t)
   then raise exception 'Açık soru bitmeden yeni soru sorulamaz.'; end if;
 if (select count(*) from oyun.tv_anket where program_id=p_program)>=60
   then raise exception 'Bir programda en çok 60 soru/anket açılabilir.'; end if;
 sn:=least(90,greatest(15,coalesce(p_saniye,30)));
 select jsonb_agg(z.cevap order by z.yeni_sira),
        max(case when z.eski_sira=q.dogru+1 then z.yeni_sira-1 end)::int
 into sec,dogru_konum
 from (select x.cevap,x.eski_sira,row_number() over(order by random()) yeni_sira
       from jsonb_array_elements_text(q.secenekler) with ordinality as x(cevap,eski_sira)) z;
 if sec is null or dogru_konum is null then raise exception 'Sorunun cevapları geçersiz.'; end if;
 insert into oyun.tv_anket(program_id,tur,soru,secenekler,dogru,acilis,kapanis,plan_kapanis,olusturan,havuz_soru_id)
 values(pr.id,'yarisma',q.soru,sec,dogru_konum,t,t+make_interval(secs=>sn),t+make_interval(secs=>sn),p.id,q.id)
 returning id into soru_id;
 select count(*) into no from oyun.tv_anket where program_id=pr.id and tur='yarisma';
 insert into oyun.tv_mesaj(program_id,user_id,rol,metin,zaman)
 values(pr.id,p.id,'sistem',format('Soru %s · %s (%s saniye)',no,q.soru,sn),t);
 perform oyun.tv_sinyal(pr.id);
 return jsonb_build_object('tamam',true,'id',soru_id,'soru_no',no);
end $f$;
revoke all on function public.tv_havuz_soru_ac(bigint,bigint,integer) from public,anon;
grant execute on function public.tv_havuz_soru_ac(bigint,bigint,integer) to authenticated,service_role;

create or replace function oyun.tv_odul_dagit(p_program bigint)
returns void language plpgsql security definer set search_path = '' as $f$
declare t timestamptz:=oyun.simdi(); pr oyun.tv_program; k oyun.tv_kanal; r record;
 sira integer:=0; pay numeric; bugun numeric; hafta numeric; kanal_hafta numeric;
 ver numeric; kalan numeric; odenen numeric:=0; ilk text; a record;
 soru_sayisi integer:=0; katilimci integer:=0; aciklama text:='Ödül şartları sağlanmadı';
begin
 select * into pr from oyun.tv_program where id=p_program for update;
 if pr.id is null or pr.odul_dagitildi or pr.durum not in ('bitti','iptal') then return; end if;
 for a in select id from oyun.tv_anket where program_id=pr.id and not kapandi loop
  perform oyun.tv_anket_kapat_ic(a.id);
 end loop;
 select * into k from oyun.tv_kanal where id=pr.kanal_id for update;
 kalan:=greatest(0,coalesce(pr.odul,0));
 select count(*) into soru_sayisi from oyun.tv_anket a
 where a.program_id=pr.id and a.tur='yarisma' and a.kapandi and a.havuz_soru_id is not null;
 select count(distinct o.user_id) into katilimci
 from oyun.tv_anket_oy o join oyun.tv_anket q on q.id=o.anket_id
 join oyun.profiller pp on pp.id=o.user_id
 where q.program_id=pr.id and q.tur='yarisma' and q.kapandi and q.havuz_soru_id is not null
   and pp.olusturma<=t-interval '24 hours' and not pp.yasakli
   and o.user_id<>k.sahip and o.user_id<>pr.sunucu
   and not exists(select 1 from oyun.tv_konuk x where x.program_id=pr.id and x.user_id=o.user_id and x.durum='kabul')
   and not exists(select 1 from oyun.tv_sunucu x where x.kanal_id=k.id and x.user_id=o.user_id and x.durum='aktif');
 if kalan>0 and pr.durum='bitti' and pr.tur='yarisma' and soru_sayisi>=5 and katilimci>=5 then
  aciklama:='En az 5 havuz sorusu ve 5 bağımsız katılımcı doğrulandı';
  for r in
   select o.user_id,sum(o.puan)::int puan,min(o.zaman) ilk_cevap
   from oyun.tv_anket_oy o join oyun.tv_anket q on q.id=o.anket_id
   join oyun.profiller pp on pp.id=o.user_id
   where q.program_id=pr.id and q.tur='yarisma' and q.kapandi and q.havuz_soru_id is not null
     and pp.olusturma<=t-interval '24 hours' and not pp.yasakli
     and o.user_id<>k.sahip and o.user_id<>pr.sunucu
     and not exists(select 1 from oyun.tv_konuk x where x.program_id=pr.id and x.user_id=o.user_id and x.durum='kabul')
     and not exists(select 1 from oyun.tv_sunucu x where x.kanal_id=k.id and x.user_id=o.user_id and x.durum='aktif')
   group by o.user_id having count(distinct o.anket_id)>=3 and sum(o.puan)>0
   order by sum(o.puan) desc,min(o.zaman) limit 100
  loop
   if sira>=3 then exit; end if;
   perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(r.user_id::text,2026));
   if exists(select 1 from oyun.tv_odul_kazanc z join oyun.tv_program pp on pp.id=z.program_id
       where z.user_id=r.user_id and z.tutar>0 and pp.kanal_id=k.id and z.zaman>t-interval '7 days')
    then continue; end if;
   if (select count(*) from oyun.tv_odul_kazanc z
       where z.user_id=r.user_id and z.tutar>0 and z.zaman>t-interval '7 days')>=2
    then continue; end if;
   select coalesce(sum(z.tutar),0) into bugun from oyun.tv_odul_kazanc z
    where z.user_id=r.user_id and (z.zaman at time zone 'Europe/Istanbul')::date=(t at time zone 'Europe/Istanbul')::date;
   select coalesce(sum(z.tutar),0) into hafta from oyun.tv_odul_kazanc z
    where z.user_id=r.user_id and z.tutar>0 and z.zaman>t-interval '7 days';
   select coalesce(sum(z.tutar),0) into kanal_hafta from oyun.tv_odul_kazanc z
    join oyun.tv_program kp on kp.id=z.program_id
    where kp.kanal_id=k.id and z.tutar>0 and z.zaman>t-interval '7 days';
   pay:=round(pr.odul*case sira when 0 then 0.5 when 1 then 0.3 else 0.2 end);
   ver:=least(pay,greatest(0,50000-bugun),greatest(0,100000-hafta),greatest(0,250000-kanal_hafta),kalan);
   if ver<1000 then continue; end if;
   sira:=sira+1;
   insert into oyun.tv_odul_kazanc(program_id,user_id,sira,puan,tutar,zaman)
   values(pr.id,r.user_id,sira,r.puan,ver,t);
   perform oyun.para_islem(r.user_id,ver,'odul',format('%s · "%s" doğrulanmış bilgi yarışması %s.liği',k.ad,pr.baslik,sira),t);
   odenen:=odenen+ver; kalan:=kalan-ver;
   perform oyun.bildir(r.user_id,format('%s · "%s" bilgi yarışmasında %s. oldun (%s puan): %s ₺ ödül cüzdanına geçti.',k.ad,pr.baslik,sira,r.puan,oyun.tl(ver)),t);
   if sira=1 then ilk:=oyun.kad(r.user_id)||' ('||r.puan||' puan)'; end if;
  end loop;
  if ilk is not null then
   perform oyun.olay('basin',format('%s · "%s" bilgi yarışmasının birincisi %s; dağıtılan ödül %s ₺.',k.ad,pr.baslik,ilk,oyun.tl(odenen)),null,null,t);
  end if;
 end if;
 if pr.durum='iptal' then aciklama:='Program iptal edildi'; end if;
 if kalan>0 then
  update oyun.tv_kanal set kasa=kasa+kalan where id=k.id;
  insert into oyun.tv_hareket(kanal_id,zaman,tutar,tur,aciklama)
  values(k.id,t,kalan,'odul_iade',format('"%s" · dağıtılmayan veya güvenlik şartlarını sağlamayan yarışma ödülü iade edildi',pr.baslik));
 end if;
 insert into oyun.tv_odul_denetim(program_id,kanal_id,durum,gecerli_soru,gecerli_katilimci,odul_havuzu,odenen,iade,aciklama,kayit)
 values(pr.id,k.id,case when odenen>0 then 'odendi' else 'iade' end,soru_sayisi,katilimci,pr.odul,odenen,kalan,aciklama,t)
 on conflict(program_id) do nothing;
 update oyun.tv_program set odul_dagitildi=true where id=pr.id;
end $f$;
