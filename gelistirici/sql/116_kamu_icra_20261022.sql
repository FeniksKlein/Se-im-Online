CREATE OR REPLACE FUNCTION public.icra_haczet(p_id bigint, p_tur text, p_varlik bigint DEFAULT NULL::bigint, p_kod text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE u uuid:=auth.uid(); d oyun.icra_takip; n numeric; v numeric; t timestamptz:=oyun.simdi();
 qty numeric; fiyat numeric; pay numeric; hid bigint; korunan numeric:=0;
BEGIN
 IF u IS NULL THEN RAISE EXCEPTION 'Giriş yap';END IF;
 SELECT * INTO d FROM oyun.icra_takip WHERE id=p_id FOR UPDATE;
 IF d.id IS NULL OR d.durum NOT IN ('teblig','haciz') OR
   (d.durum='teblig' AND d.odeme_son>t) THEN RAISE EXCEPTION 'Ödeme emri süresi veya itiraz süreci devam ediyor';END IF;
 IF d.kaynak='kredi' AND NOT EXISTS(SELECT 1 FROM oyun.sirket_ortaklari
    WHERE sirket_id=d.alacakli_sirket AND user_id=u AND pay>=50)
  OR d.kaynak='emlak_vergisi' AND NOT EXISTS(SELECT 1 FROM oyun.makamlar
    WHERE user_id=u AND bit IS NULL AND (tur='cb' OR(tur='bakan' AND bakanlik='maliye')))
 THEN RAISE EXCEPTION 'Takip yetkin yok';END IF;
 n:=oyun.icra_kalan_hesapla(d.id);
 IF n<=0 THEN UPDATE oyun.icra_takip SET durum='kapandi' WHERE id=d.id;RETURN jsonb_build_object('durum','kapandi');END IF;
 -- Aynı borç için birden fazla açık artırma borç tutarını aşamasın.
 IF p_tur IN ('gayrimenkul','sirket_payi') THEN
  IF EXISTS(SELECT 1 FROM oyun.icra_haciz_yeni h WHERE h.takip_id=d.id AND h.durum='ilan'
    AND h.tur=p_tur AND h.varlik_id=p_varlik) THEN RAISE EXCEPTION 'Bu varlık zaten hacizli';END IF;
  IF p_tur='gayrimenkul' THEN
    SELECT alis_bedeli INTO v FROM oyun.yatirim_mulkleri WHERE id=p_varlik AND user_id=d.borclu;
    -- Tek konut istisnası oyun içi ihtiyatlı koruma, İİK 82 koşulları somut olayda değişir.
    IF EXISTS(SELECT 1 FROM oyun.yatirim_mulkleri WHERE id=p_varlik AND tip='daire')
      AND (SELECT COUNT(*) FROM oyun.yatirim_mulkleri WHERE user_id=d.borclu AND tip='daire')=1
    THEN RAISE EXCEPTION 'Borçlunun tek konutu koruma incelemesine tabi; otomatik haciz yapılamaz';END IF;
    IF EXISTS(SELECT 1 FROM oyun.icra_haciz_yeni h JOIN oyun.icra_takip x ON x.id=h.takip_id
      WHERE h.tur=p_tur AND h.varlik_id=p_varlik AND h.durum='ilan') THEN
      RAISE EXCEPTION 'Taşınmaz başka dosyada satışta';END IF;
  ELSE
    SELECT s.sermaye*o.pay/100,o.pay INTO v,pay FROM oyun.sirket_ortaklari o
     JOIN oyun.sirketler s ON s.id=o.sirket_id
     WHERE o.sirket_id=p_varlik AND o.user_id=d.borclu;
    IF EXISTS(SELECT 1 FROM oyun.icra_haciz_yeni h JOIN oyun.icra_takip x ON x.id=h.takip_id
      WHERE h.tur=p_tur AND h.varlik_id=p_varlik AND x.borclu=d.borclu AND h.durum='ilan')
    THEN RAISE EXCEPTION 'Bu pay başka dosyada satışta';END IF;
  END IF;
  IF v IS NULL OR v<=0 THEN RAISE EXCEPTION 'Borçluya ait pozitif değerli varlık yok';END IF;
  IF EXISTS(SELECT 1 FROM oyun.icra_haciz_yeni h WHERE h.takip_id=d.id AND h.durum='ilan'
       HAVING COALESCE(SUM(h.deger),0)>n*2) THEN
    RAISE EXCEPTION 'Ölçüsüz haciz: satışta yeterli teminat var';END IF;
  INSERT INTO oyun.icra_haciz_yeni(takip_id,tur,varlik_id,deger,haczedilen_pay,satis_son)
  VALUES(d.id,p_tur,p_varlik,round(v,2),pay,t+interval '48 hours') RETURNING id INTO hid;
  UPDATE oyun.icra_takip SET durum='haciz' WHERE id=d.id;
  RETURN jsonb_build_object('haciz_id',hid,'deger',v,'satis_son',t+interval '48 hours');
 ELSIF p_tur='cuzdan' THEN
  SELECT greatest(0,coalesce(sum(tutar),0)*0.75) INTO korunan FROM oyun.hesap_hareket
   WHERE user_id=d.borclu AND tur IN ('maas','gorev') AND tutar>0 AND zaman>t-interval '24 hours';
  SELECT greatest(0,para-least(para,korunan)) INTO v FROM oyun.cuzdan WHERE user_id=d.borclu FOR UPDATE;
  v:=least(n,coalesce(v,0));
  IF v>0 THEN
   PERFORM oyun.para_islem(d.borclu,-v,'icra_haciz','İcra dosyası #'||d.id||' cüzdan haczi',t);
  END IF;
 ELSIF p_tur='banka' THEN
  SELECT greatest(0,vadesiz) INTO v FROM oyun.banka_musteri WHERE user_id=d.borclu FOR UPDATE;
  v:=least(n,coalesce(v,0));
  IF v>0 THEN
   UPDATE oyun.banka_musteri SET vadesiz=vadesiz-v WHERE user_id=d.borclu;
   INSERT INTO oyun.banka_hareket(user_id,zaman,hesap,tutar,aciklama)
    VALUES(d.borclu,t,'vadesiz',-v,'İcra dosyası #'||d.id||' banka haczi');
  END IF;
 ELSIF p_tur='borsa' THEN
  SELECT p.miktar,a.fiyat INTO qty,fiyat FROM oyun.piyasa_pozisyon p
   JOIN oyun.piyasa_varlik a ON a.kod=p.kod
   WHERE p.user_id=d.borclu AND p.kod=p_kod AND p.miktar>0 AND a.aktif AND a.fiyat>0
   FOR UPDATE OF p;
  IF qty IS NULL THEN RAISE EXCEPTION 'Satılabilir borsa varlığı bulunamadı';END IF;
  pay:=least(qty,trunc(n/fiyat,8));
  IF pay<=0 THEN RAISE EXCEPTION 'Kalan alacak bu varlığın en küçük satış biriminin altında'; END IF;
  v:=least(n,round(pay*fiyat,2));
  UPDATE oyun.piyasa_pozisyon SET miktar=miktar-pay,
   maliyet=CASE WHEN miktar<=pay THEN 0 ELSE round(maliyet*(miktar-pay)/miktar,2) END
   WHERE user_id=d.borclu AND kod=p_kod;
  INSERT INTO oyun.piyasa_islem(user_id,kod,yon,miktar,fiyat,brut,komisyon,zaman)
   VALUES(d.borclu,p_kod,'sat',pay,fiyat,v,0,t);
 ELSE RAISE EXCEPTION 'Haciz türü geçersiz';END IF;
 IF v IS NULL OR v<=0 THEN RAISE EXCEPTION 'Haczedilebilir tutar bulunamadı'; END IF;
 v:=oyun.icra_tahsil_et(d.id,v,p_tur);
 UPDATE oyun.icra_takip SET durum=CASE WHEN oyun.icra_kalan_hesapla(d.id)<=0 THEN 'kapandi' ELSE 'haciz' END WHERE id=d.id;
 RETURN jsonb_build_object('tahsil',v,'kalan',oyun.icra_kalan_hesapla(d.id));
END $function$;

CREATE OR REPLACE FUNCTION public.icra_ihale_teklif(p_haciz bigint, p_tutar numeric)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE h oyun.icra_haciz_yeni; d oyun.icra_takip; u uuid:=auth.uid();t timestamptz:=oyun.simdi();
BEGIN
 IF u IS NULL THEN RAISE EXCEPTION 'Giriş yap';END IF;
 SELECT * INTO h FROM oyun.icra_haciz_yeni WHERE id=p_haciz FOR UPDATE;
 IF h.id IS NULL OR h.durum<>'ilan' OR h.satis_son<=t THEN RAISE EXCEPTION 'İhale açık değil'; END IF;
 SELECT * INTO d FROM oyun.icra_takip WHERE id=h.takip_id;
 IF d.durum NOT IN ('haciz','teblig') OR oyun.icra_kalan_hesapla(d.id)<=0 THEN RAISE EXCEPTION 'İhale dosyası kapandı'; END IF;
 IF d.borclu=u OR (d.alacakli_sirket IS NOT NULL AND EXISTS
    (SELECT 1 FROM oyun.sirket_ortaklari WHERE sirket_id=d.alacakli_sirket AND user_id=u AND pay>0))
 THEN RAISE EXCEPTION 'Borçlu veya alacaklı banka ihalede teklif veremez';END IF;
 IF p_tutar IS NULL OR p_tutar<>round(p_tutar) OR p_tutar<ceil(h.deger*0.5) OR
    (h.teklif IS NOT NULL AND p_tutar<h.teklif*1.01)
 THEN RAISE EXCEPTION 'Teklif kıymet takdirinin yarısından az olamaz; mevcut teklifi en az %%1 aş';END IF;
 PERFORM oyun.para_islem(u,-p_tutar,'icra_tem',format('İcra ihalesi #%s bloke bedel',h.id),t);
 IF h.teklif_veren IS NOT NULL THEN
   PERFORM oyun.para_islem(h.teklif_veren,h.teklif,'icra_tem_iade',format('İcra ihalesi #%s önceki teklif iadesi',h.id),t);
 END IF;
 UPDATE oyun.icra_haciz_yeni SET teklif=p_tutar,teklif_veren=u WHERE id=h.id;
 RETURN jsonb_build_object('teklif',p_tutar,'son',h.satis_son);
END $function$;

CREATE OR REPLACE FUNCTION public.icra_ihale_sonuclandir(p_haciz bigint)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE h oyun.icra_haciz_yeni;d oyun.icra_takip;v numeric; k numeric; u uuid:=auth.uid();
BEGIN
 IF u IS NULL THEN RAISE EXCEPTION 'Giriş yap';END IF;
 SELECT * INTO h FROM oyun.icra_haciz_yeni WHERE id=p_haciz FOR UPDATE;
 IF h.id IS NULL OR h.durum<>'ilan' OR h.satis_son>oyun.simdi() THEN RAISE EXCEPTION 'Satış süresi tamamlanmadı'; END IF;
