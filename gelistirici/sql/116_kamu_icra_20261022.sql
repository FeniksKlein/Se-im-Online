 RETURN jsonb_build_object(
  'cb',EXISTS(SELECT 1 FROM oyun.makamlar WHERE tur='cb' AND user_id=u AND bit IS NULL),
  'belediye_iller',COALESCE((SELECT jsonb_agg(il_id) FROM oyun.makamlar WHERE tur='bel' AND user_id=u AND bit IS NULL),'[]'::jsonb),
  'atamalar',COALESCE((SELECT jsonb_agg(jsonb_build_object(
   'id',a.id,'gorev',a.gorev,'il_id',a.il_id,'aday',p.kad,'benim_teklifim',a.aday=u,'ben_atadim',a.atayan=u,
