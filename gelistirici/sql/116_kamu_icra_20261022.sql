CREATE OR REPLACE FUNCTION public.icra_baslatilabilir()
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE u uuid:=auth.uid();vergi_yetkili boolean;
BEGIN
 IF u IS NULL THEN RAISE EXCEPTION 'Giriş yap';END IF;
 vergi_yetkili:=EXISTS(SELECT 1 FROM oyun.makamlar WHERE user_id=u AND bit IS NULL
   AND (tur='cb' OR(tur='bakan' AND bakanlik='maliye')));
 RETURN jsonb_build_object(
  'krediler',coalesce((SELECT jsonb_agg(jsonb_build_object('id',k.id,'banka',s.ad,'borclu',p.kad,'kalan',k.kalan))
   FROM oyun.oyb_icra i JOIN oyun.oyb_kredi k ON k.id=i.kredi_id
    JOIN oyun.sirketler s ON s.id=k.banka_id JOIN oyun.profiller p ON p.id=k.borclu
   WHERE i.durum='kabul' AND i.kesin_son<=oyun.simdi() AND k.kalan>0
    AND EXISTS(SELECT 1 FROM oyun.sirket_ortaklari o WHERE o.sirket_id=i.banka_id AND o.user_id=u AND o.pay>=50)
    AND NOT EXISTS(SELECT 1 FROM oyun.icra_takip d WHERE d.kaynak='kredi' AND d.kaynak_id=k.id)),'[]'::jsonb),
  'vergiler',CASE WHEN vergi_yetkili THEN coalesce((SELECT jsonb_agg(jsonb_build_object(
     'id',m.id,'borclu',p.kad,'tutar',m.vergi_borc,'tip',m.tip))
     FROM oyun.yatirim_mulkleri m JOIN oyun.profiller p ON p.id=m.user_id
      WHERE m.vergi_borc>0 AND NOT EXISTS(SELECT 1 FROM oyun.icra_takip d WHERE d.kaynak='emlak_vergisi' AND d.kaynak_id=m.id)),'[]'::jsonb)
   ELSE '[]'::jsonb END
 );
END $function$;

CREATE OR REPLACE FUNCTION public.icra_varliklar(p_id bigint)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE d oyun.icra_takip; u uuid:=auth.uid();yetkili boolean;
BEGIN
 IF u IS NULL THEN RAISE EXCEPTION 'Giriş yap';END IF;
 SELECT * INTO d FROM oyun.icra_takip WHERE id=p_id;
 IF d.id IS NULL THEN RAISE EXCEPTION 'Dosya yok';END IF;
 yetkili:=d.borclu=u OR (d.kaynak='kredi' AND EXISTS
   (SELECT 1 FROM oyun.sirket_ortaklari WHERE sirket_id=d.alacakli_sirket AND user_id=u AND pay>=50))
 OR (d.kaynak='emlak_vergisi' AND EXISTS(SELECT 1 FROM oyun.makamlar
     WHERE user_id=u AND bit IS NULL AND (tur='cb' OR(tur='bakan' AND bakanlik='maliye'))));
 IF NOT yetkili THEN RAISE EXCEPTION 'Bu dosyanın varlıklarını görme yetkin yok';END IF;
 RETURN jsonb_build_object(
  'bankadaki',coalesce((SELECT vadesiz FROM oyun.banka_musteri WHERE user_id=d.borclu),0),
  'cuzdan',coalesce((SELECT para FROM oyun.cuzdan WHERE user_id=d.borclu),0),
  'borsa',coalesce((SELECT jsonb_agg(jsonb_build_object('kod',p.kod,'miktar',p.miktar,'fiyat',v.fiyat))
   FROM oyun.piyasa_pozisyon p JOIN oyun.piyasa_varlik v ON v.kod=p.kod
   WHERE p.user_id=d.borclu AND p.miktar>0 AND v.fiyat>0),'[]'::jsonb),
  'mulk',coalesce((SELECT jsonb_agg(jsonb_build_object('id',id,'tip',tip,'deger',alis_bedeli))
   FROM oyun.yatirim_mulkleri WHERE user_id=d.borclu),'[]'::jsonb),
  'sirketler',coalesce((SELECT jsonb_agg(jsonb_build_object('id',o.sirket_id,'ad',s.ad,'pay',o.pay,'deger',round(s.sermaye*o.pay/100,2)))
   FROM oyun.sirket_ortaklari o JOIN oyun.sirketler s ON s.id=o.sirket_id
   WHERE o.user_id=d.borclu AND o.pay>0),'[]'::jsonb)
 );
END $function$;

