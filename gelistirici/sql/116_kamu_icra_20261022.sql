   FROM (SELECT * FROM oyun.kamu_kurum_atama
    WHERE durum='aktif' OR aday=u OR atayan=u ORDER BY id DESC LIMIT 150)a
    JOIN oyun.profiller p ON p.id=a.aday),'[]'::jsonb)
 );
END $function$;

CREATE OR REPLACE FUNCTION public.kamu_kurum_islem(p_eylem text, p_id bigint DEFAULT NULL::bigint, p_gorev text DEFAULT NULL::text, p_il smallint DEFAULT NULL::smallint, p_kad text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE u uuid:=auth.uid(); a oyun.kamu_kurum_atama; v_aday uuid; i bigint; authorized boolean;
BEGIN
 IF u IS NULL THEN RAISE EXCEPTION 'Giris gerekli';END IF;
 IF p_eylem='teklif' THEN
  IF p_gorev NOT IN ('vali','emniyet_muduru','spk_baskani','rekabet_baskani','vergi_idaresi_baskani','belediye_genel_sekreteri')
   OR (p_gorev IN ('vali','emniyet_muduru','belediye_genel_sekreteri') AND (p_il IS NULL OR NOT EXISTS(SELECT 1 FROM oyun.iller WHERE id=p_il)))
   OR (p_gorev NOT IN ('vali','emniyet_muduru','belediye_genel_sekreteri') AND p_il IS NOT NULL)
  THEN RAISE EXCEPTION 'Gorev veya il uygun degil';END IF;
  authorized:=CASE WHEN p_gorev='belediye_genel_sekreteri' THEN
   EXISTS(SELECT 1 FROM oyun.makamlar WHERE tur='bel' AND il_id=p_il AND user_id=u AND bit IS NULL)
   ELSE EXISTS(SELECT 1 FROM oyun.makamlar WHERE tur='cb' AND user_id=u AND bit IS NULL) END;
  IF NOT authorized THEN RAISE EXCEPTION 'Bu kuruma atama teklifi yapma yetkin yok';END IF;
  SELECT id INTO v_aday FROM oyun.profiller WHERE lower(kad)=lower(trim(p_kad)) AND NOT yasakli LIMIT 1;
  IF v_aday IS NULL THEN RAISE EXCEPTION 'Oyuncu adi bulunamadi';END IF;
  IF v_aday=u THEN RAISE EXCEPTION 'Kendine gorev teklif edemezsin';END IF;
  INSERT INTO oyun.kamu_kurum_atama(gorev,il_id,aday,atayan) VALUES(p_gorev,p_il,v_aday,u) RETURNING id INTO i;
  RETURN jsonb_build_object('id',i,'durum','teklif');
 END IF;
 SELECT * INTO a FROM oyun.kamu_kurum_atama WHERE id=p_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Atama kaydi bulunamadi';END IF;
 authorized:=CASE WHEN a.gorev='belediye_genel_sekreteri' THEN
   EXISTS(SELECT 1 FROM oyun.makamlar WHERE tur='bel' AND il_id=a.il_id AND user_id=u AND bit IS NULL)
   ELSE EXISTS(SELECT 1 FROM oyun.makamlar WHERE tur='cb' AND user_id=u AND bit IS NULL) END;
 IF p_eylem='cevap_kabul' AND a.aday=u AND a.durum='teklif' THEN
  IF a.teklif_at+interval '24 hours'<now() THEN RAISE EXCEPTION 'Teklif suresi dolmus';END IF;
  IF EXISTS(SELECT 1 FROM oyun.makamlar WHERE user_id=u AND bit IS NULL AND tur IN ('cb','bakan','mv','bel','cb_yardimcisi'))
  THEN RAISE EXCEPTION 'Secilmis veya siyasi gorev ile bu atanmis gorev birlestirilemez';END IF;
  -- Eski yönetici kayıtları silinmez, sadece görev sonlandırılır.
  UPDATE oyun.kamu_kurum_atama SET durum='gorevden_alindi',yanit_at=now()
   WHERE gorev=a.gorev AND il_id IS NOT DISTINCT FROM a.il_id AND durum='aktif';
  UPDATE oyun.kamu_kurum_atama SET durum='aktif',yanit_at=now() WHERE id=a.id;
 ELSIF p_eylem='cevap_ret' AND a.aday=u AND a.durum='teklif' THEN
  UPDATE oyun.kamu_kurum_atama SET durum='ret',yanit_at=now() WHERE id=a.id;
 ELSIF p_eylem='iptal' AND authorized AND a.durum='teklif' THEN
  UPDATE oyun.kamu_kurum_atama SET durum='geri_cekildi',yanit_at=now() WHERE id=a.id;
 ELSIF p_eylem='gorevden_al' AND authorized AND a.durum='aktif' THEN
  UPDATE oyun.kamu_kurum_atama SET durum='gorevden_alindi',yanit_at=now() WHERE id=a.id;
 ELSE RAISE EXCEPTION 'Bu atama islemine yetkin yok';END IF;
 RETURN jsonb_build_object('id',a.id,'durum',p_eylem);
END $function$;

CREATE OR REPLACE FUNCTION oyun.icra_kalan_hesapla(p_id bigint)
 RETURNS numeric
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
DECLARE d oyun.icra_takip; v numeric;
BEGIN
 SELECT * INTO d FROM oyun.icra_takip WHERE id=p_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Dosya yok'; END IF;
 IF d.kaynak='kredi' THEN
  SELECT greatest(0,kalan) INTO v FROM oyun.oyb_kredi WHERE id=d.kaynak_id;
 ELSE
  SELECT greatest(0,vergi_borc) INTO v FROM oyun.yatirim_mulkleri WHERE id=d.kaynak_id;
 END IF;
 RETURN coalesce(v,0);
END $function$;

CREATE OR REPLACE FUNCTION oyun.icra_tahsil_et(p_id bigint, p_tutar numeric, p_tur text)
 RETURNS numeric
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
DECLARE d oyun.icra_takip; k oyun.oyb_kredi; em oyun.yatirim_mulkleri;
 v numeric:=0;
BEGIN
 SELECT * INTO d FROM oyun.icra_takip WHERE id=p_id FOR UPDATE;
 IF d.id IS NULL OR d.durum NOT IN ('teblig','haciz') THEN RAISE EXCEPTION 'Aktif takip yok'; END IF;
 IF p_tutar<=0 THEN RETURN 0;END IF;
 IF d.kaynak='kredi' THEN
  SELECT * INTO k FROM oyun.oyb_kredi WHERE id=d.kaynak_id FOR UPDATE;
  IF k.id IS NULL THEN RAISE EXCEPTION 'Kredi bulunamadi';END IF;
  v:=least(p_tutar,greatest(0,k.kalan));
  IF v>0 THEN
   UPDATE oyun.oyb_kredi SET kalan=kalan-v,
    anapara_odendi=anapara_odendi+least(v,greatest(0,anapara-anapara_odendi)),
    durum=CASE WHEN kalan<=v THEN 'odendi' ELSE durum END,
    kapanis=CASE WHEN kalan<=v THEN oyun.simdi() ELSE kapanis END WHERE id=k.id;
   UPDATE oyun.sirketler SET kasa=kasa+v WHERE id=d.alacakli_sirket;
   IF k.kalan<=v THEN
    UPDATE oyun.oyb_icra SET durum='kapandi' WHERE kredi_id=k.id AND durum='kabul';
    UPDATE oyun.oyb_icra_haciz SET durum='iptal' WHERE icra_id IN
      (SELECT id FROM oyun.oyb_icra WHERE kredi_id=k.id) AND durum='acik';
   END IF;
  END IF;
 ELSE
  SELECT * INTO em FROM oyun.yatirim_mulkleri WHERE id=d.kaynak_id FOR UPDATE;
  IF em.id IS NULL THEN RAISE EXCEPTION 'Vergi borcu bulunamadi';END IF;
  v:=least(p_tutar,greatest(0,em.vergi_borc));
  IF v>0 THEN
   UPDATE oyun.yatirim_mulkleri SET vergi_borc=greatest(0,vergi_borc-v) WHERE id=em.id;
   UPDATE oyun.ulke SET hazine=hazine+v/1000000000 WHERE id=1;
  END IF;
 END IF;
 IF v>0 THEN
  INSERT INTO oyun.icra_haciz_hareket(takip_id,tur,tutar,notlar)
  VALUES(p_id,p_tur,v,'Kesinleşmiş alacağa mahsup');
 END IF;
 IF oyun.icra_kalan_hesapla(p_id)<=0 THEN
  UPDATE oyun.icra_takip SET durum='kapandi' WHERE id=p_id;
  -- Açık artırmadaki yatırılmış en yüksek teklifler ilgili sonlandırıcı RPC ile iadeye çıkar.
 END IF;
 RETURN v;
END $function$;

CREATE OR REPLACE FUNCTION public.icra_takip_ac(p_kaynak text, p_kaynak_id bigint)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE u uuid:=auth.uid(); b uuid; s bigint; miktar numeric; cid bigint; d oyun.oyb_icra;
 t timestamptz:=oyun.simdi(); son timestamptz;
BEGIN
 IF u IS NULL THEN RAISE EXCEPTION 'Giriş yap';END IF;
 IF p_kaynak='kredi' THEN
  SELECT * INTO d FROM oyun.oyb_icra WHERE kredi_id=p_kaynak_id AND durum='kabul'
    AND kesin_son<=t ORDER BY id DESC LIMIT 1;
  IF d.id IS NULL THEN RAISE EXCEPTION 'Kesinleşmiş yargı kararı yok';END IF;
  IF NOT EXISTS(SELECT 1 FROM oyun.sirket_ortaklari WHERE sirket_id=d.banka_id AND user_id=u AND pay>=50)
  THEN RAISE EXCEPTION 'Alacaklı bankayı temsil etmiyorsun';END IF;
  SELECT borclu,kalan,banka_id INTO b,miktar,s FROM oyun.oyb_kredi WHERE id=p_kaynak_id;
  son:=t+interval '7 days';
 ELSIF p_kaynak='emlak_vergisi' THEN
  IF NOT EXISTS(SELECT 1 FROM oyun.makamlar WHERE user_id=u AND bit IS NULL
      AND (tur='cb' OR (tur='bakan' AND bakanlik='maliye')))
  THEN RAISE EXCEPTION 'Vergi tahsil yetkin yok'; END IF;
  SELECT user_id,vergi_borc INTO b,miktar FROM oyun.yatirim_mulkleri WHERE id=p_kaynak_id;
  son:=t+interval '15 days';
 ELSE RAISE EXCEPTION 'Takip kaynağı geçersiz';END IF;
 IF b IS NULL OR coalesce(miktar,0)<=0 THEN RAISE EXCEPTION 'Tahsil edilecek muaccel borç yok';END IF;
 INSERT INTO oyun.icra_takip(kaynak,kaynak_id,borclu,alacakli_sirket,baslangic_borc,teblig,odeme_son)
 VALUES(p_kaynak,p_kaynak_id,b,s,miktar,t,son)
 ON CONFLICT(kaynak,kaynak_id) DO UPDATE SET teblig=oyun.icra_takip.teblig
 RETURNING id INTO cid;
 PERFORM oyun.bildir(b,'İcra ödeme emri # '||cid||' ('||miktar||' TL). Son tarih: '||
     to_char(son AT TIME ZONE 'Europe/Istanbul','DD.MM.YYYY HH24:MI')||'. İtiraz ve mal bildirimi haklarını incele.',t);
 RETURN jsonb_build_object('id',cid,'odeme_son',son);
END $function$;

CREATE OR REPLACE FUNCTION public.icra_itiraz_et(p_id bigint, p_gerekce text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE d oyun.icra_takip;
BEGIN
 IF char_length(trim(coalesce(p_gerekce,''))) NOT BETWEEN 10 AND 1500 THEN RAISE EXCEPTION 'İtiraz gerekçesi 10-1500 karakter olmalı';END IF;
 SELECT * INTO d FROM oyun.icra_takip WHERE id=p_id AND borclu=auth.uid() FOR UPDATE;
 IF d.id IS NULL OR d.durum<>'teblig' OR d.odeme_son<oyun.simdi() THEN RAISE EXCEPTION 'İtiraz süresi doldu';END IF;
 UPDATE oyun.icra_takip SET durum='itiraz',itiraz=trim(p_gerekce),itiraz_tarih=oyun.simdi() WHERE id=d.id;
 RETURN jsonb_build_object('id',d.id,'durum','itiraz');
END $function$;

CREATE OR REPLACE FUNCTION public.icra_itiraz_karar(p_id bigint, p_ret boolean, p_gerekce text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE d oyun.icra_takip; u uuid:=auth.uid();
BEGIN
 IF u IS NULL OR NOT EXISTS(SELECT 1 FROM oyun.mahkeme_uye WHERE user_id=u)
  THEN RAISE EXCEPTION 'Yetkili mahkeme üyesi olmalısın';END IF;
 IF char_length(trim(coalesce(p_gerekce,'')))<12 THEN RAISE EXCEPTION 'Gerekçeli karar zorunlu';END IF;
 SELECT * INTO d FROM oyun.icra_takip WHERE id=p_id FOR UPDATE;
 IF d.id IS NULL OR d.durum<>'itiraz' THEN RAISE EXCEPTION 'Karar bekleyen itiraz yok';END IF;
 IF u=d.borclu OR (d.alacakli_sirket IS NOT NULL AND EXISTS
   (SELECT 1 FROM oyun.sirket_ortaklari WHERE sirket_id=d.alacakli_sirket AND user_id=u AND pay>0))
 THEN RAISE EXCEPTION 'Tarafsız olmayan yargıç karar veremez'; END IF;
 -- Vergi itirazlarında kamu idaresinin muhatap olduğu yargı simüle edilir; üretimde bağımsız inceleme önerilir.
 UPDATE oyun.icra_takip SET durum=CASE WHEN p_ret THEN 'haciz' ELSE 'iptal' END,
 karar_gerekce=trim(p_gerekce),karar_tarih=oyun.simdi() WHERE id=d.id;
 RETURN jsonb_build_object('durum',CASE WHEN p_ret THEN 'haciz' ELSE 'iptal' END);
END $function$;

