CREATE OR REPLACE FUNCTION public.kamu_butce_panel()
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE u uuid:=auth.uid();
BEGIN
 IF u IS NULL THEN RAISE EXCEPTION 'Giris gerekli'; END IF;
 RETURN jsonb_build_object(
  'hazine',(SELECT hazine FROM oyun.ulke WHERE id=1),
  'ekonomi',(SELECT jsonb_build_object('buyume',buyume,'enflasyon',enflasyon,'issizlik',issizlik,'memnuniyet',memnuniyet) FROM oyun.ulke WHERE id=1),
  'bakanliklar',COALESCE((SELECT jsonb_agg(jsonb_build_object('kod',kod,'kasa',kasa) ORDER BY kod) FROM oyun.bakanlik_kasa),'[]'::jsonb),
  'yetkili',EXISTS(SELECT 1 FROM oyun.makamlar WHERE tur='cb' AND user_id=u AND bit IS NULL),
  'son_karar',(SELECT tarih FROM oyun.kamu_butce_kararlar ORDER BY id DESC LIMIT 1),
  'kararlar',COALESCE((SELECT jsonb_agg(jsonb_build_object('id',x.id,'toplam',x.toplam_milyar,'paylar',x.paylar,'tarih',x.tarih) ORDER BY x.id DESC)
   FROM (SELECT * FROM oyun.kamu_butce_kararlar ORDER BY id DESC LIMIT 20)x),'[]'::jsonb)
 );
END $function$;

CREATE OR REPLACE FUNCTION public.kamu_butce_dagit(p_toplam numeric, p_paylar jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE u uuid:=auth.uid(); total numeric:=0; c record; t timestamptz:=oyun.simdi();
BEGIN
 IF NOT EXISTS(SELECT 1 FROM oyun.makamlar WHERE user_id=u AND tur='cb' AND bit IS NULL) THEN
  RAISE EXCEPTION 'Yalnizca gorevdeki cumhurbaskani butce dagitabilir';
 END IF;
 IF p_toplam IS NULL OR p_toplam<0.001 OR p_toplam>5 OR p_toplam<>round(p_toplam,3)
  OR p_paylar IS NULL OR jsonb_typeof(p_paylar)<>'object' OR
  (SELECT COUNT(*) FROM jsonb_object_keys(p_paylar))<>5 THEN
  RAISE EXCEPTION 'Dagitilacak tutar 0.001-5 milyar TL ve tam 5 butce kalemi olmali';
 END IF;
 FOR c IN SELECT key,value FROM jsonb_each_text(p_paylar) LOOP
  IF c.key NOT IN ('egitim','saglik','savunma','icisleri','ulastirma') OR
    c.value !~ '^[0-9]+([.][0-9]+)?$' OR (c.value)::numeric>100
  THEN RAISE EXCEPTION 'Gecersiz butce payi: %',c.key;END IF;
  total:=total+(c.value)::numeric;
 END LOOP;
 IF total<>100 THEN RAISE EXCEPTION 'Butce paylari toplamda %%100 olmali'; END IF;
 PERFORM pg_advisory_xact_lock(920044,1);
 IF EXISTS(SELECT 1 FROM oyun.kamu_butce_kararlar WHERE tarih>t-interval '24 hours') THEN
  RAISE EXCEPTION 'Ulusal butce en erken 24 saat sonra yeniden dagitilabilir';
 END IF;
 UPDATE oyun.ulke SET hazine=hazine-p_toplam WHERE id=1 AND hazine>=p_toplam;
 IF NOT FOUND THEN RAISE EXCEPTION 'Hazinede yeterli kaynak yok'; END IF;
 FOR c IN SELECT key,value FROM jsonb_each_text(p_paylar) LOOP
  UPDATE oyun.bakanlik_kasa SET kasa=kasa+round(p_toplam*(c.value)::numeric/100,6) WHERE kod=c.key;
  IF NOT FOUND THEN RAISE EXCEPTION 'Bakanlik kasasi eksik: %',c.key;END IF;
 END LOOP;
 INSERT INTO oyun.kamu_butce_kararlar(karar_veren,toplam_milyar,paylar,tarih)
 VALUES(u,p_toplam,p_paylar,t);
 RETURN public.kamu_butce_panel();
END $function$;

CREATE OR REPLACE FUNCTION public.kamu_toptan_panel()
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE u uuid:=auth.uid();
BEGIN
 IF u IS NULL THEN RAISE EXCEPTION 'Giris gerekli'; END IF;
 RETURN jsonb_build_object(
  'sirketler',COALESCE((SELECT jsonb_agg(jsonb_build_object('id',s.id,'ad',s.ad,'tur',e.tur,'kasa',s.kasa))
   FROM oyun.sirketler s JOIN oyun.eko_isletmeler e ON e.sirket_id=s.id
   WHERE s.aktif AND oyun.sirket_yonetici_mi(s.id,u)),'[]'::jsonb),
  'stoklar',COALESCE((SELECT jsonb_agg(jsonb_build_object('sirket',s.id,'ad',s.ad,'urun',st.urun,'adet',st.adet,'fiyat',st.satis_fiyati))
   FROM oyun.eko_urun_stok st JOIN oyun.sirketler s ON s.id=st.sirket_id
   JOIN oyun.eko_isletmeler e ON e.sirket_id=s.id AND e.tur='fabrika'
   WHERE s.aktif AND st.adet>0 AND st.satis_fiyati>0),'[]'::jsonb),
  'teklifler',COALESCE((SELECT jsonb_agg(jsonb_build_object(
   'id',x.id,'alici',x.alici,'satici',x.satici,'alici_ad',a.ad,'satici_ad',s.ad,'urun',x.urun,
   'adet',x.adet,'birim',x.birim_fiyat,'toplam',x.birim_fiyat*x.adet,'durum',x.durum,
   'teklif_eden',x.teklif_eden,'son_tarih',x.son_tarih,'olusturma',x.olusturma,
   'alici_yetkili',oyun.sirket_yonetici_mi(x.alici,u),
   'satici_yetkili',oyun.sirket_yonetici_mi(x.satici,u)) ORDER BY x.id DESC)
   FROM (SELECT * FROM oyun.kamu_toptan_teklif
      WHERE EXISTS(SELECT 1 FROM oyun.sirket_ortaklari o WHERE o.user_id=u AND o.sirket_id IN (alici,satici))
      ORDER BY id DESC LIMIT 80)x
   JOIN oyun.sirketler a ON a.id=x.alici JOIN oyun.sirketler s ON s.id=x.satici),'[]'::jsonb)
 );
END $function$;

CREATE OR REPLACE FUNCTION public.kamu_toptan_islem(p_eylem text, p_id bigint DEFAULT NULL::bigint, p_alici bigint DEFAULT NULL::bigint, p_satici bigint DEFAULT NULL::bigint, p_urun text DEFAULT NULL::text, p_adet integer DEFAULT NULL::integer)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE u uuid:=auth.uid(); d oyun.kamu_toptan_teklif; st oyun.eko_urun_stok; i bigint; res jsonb;
BEGIN
 IF u IS NULL THEN RAISE EXCEPTION 'Giris gerekli';END IF;
 IF p_eylem='teklif' THEN
  IF p_alici IS NULL OR p_satici IS NULL OR p_alici=p_satici OR p_adet NOT BETWEEN 1 AND 500
     OR NOT oyun.sirket_yonetici_mi(p_alici,u)
     OR NOT EXISTS(SELECT 1 FROM oyun.eko_isletmeler WHERE sirket_id=p_alici AND tur='magaza')
  THEN RAISE EXCEPTION 'Yalnizca yonettigin magazadan gecerli bir siparis verebilirsin';END IF;
  SELECT * INTO st FROM oyun.eko_urun_stok WHERE sirket_id=p_satici AND urun=p_urun;
  IF st.sirket_id IS NULL OR st.adet<p_adet OR st.satis_fiyati<=0
    OR NOT EXISTS(SELECT 1 FROM oyun.eko_isletmeler WHERE sirket_id=p_satici AND tur='fabrika')
    OR NOT EXISTS(SELECT 1 FROM oyun.sirketler WHERE id=p_satici AND aktif)
  THEN RAISE EXCEPTION 'Fabrikada yeterli satilik stok bulunmuyor';END IF;
  IF NOT EXISTS(SELECT 1 FROM oyun.sirketler WHERE id=p_alici AND aktif AND kasa>=st.satis_fiyati*p_adet) THEN
   RAISE EXCEPTION 'Magaza kasasi teklif tutarini karsilamiyor'; END IF;
  INSERT INTO oyun.kamu_toptan_teklif(alici,satici,urun,adet,birim_fiyat,teklif_eden)
  VALUES(p_alici,p_satici,p_urun,p_adet,st.satis_fiyati,u) RETURNING id INTO i;
  RETURN jsonb_build_object('id',i,'durum','teklif','birim_fiyat',st.satis_fiyati);
 END IF;
 SELECT * INTO d FROM oyun.kamu_toptan_teklif WHERE id=p_id FOR UPDATE;
 IF NOT FOUND OR d.durum<>'teklif' THEN RAISE EXCEPTION 'Acik teklif bulunamadi';END IF;
 IF d.son_tarih<oyun.simdi() THEN
   UPDATE oyun.kamu_toptan_teklif SET durum='suresi_doldu',bitis=now() WHERE id=d.id;
   RETURN jsonb_build_object('durum','suresi_doldu');
 END IF;
 IF p_eylem='iptal' AND oyun.sirket_yonetici_mi(d.alici,u) THEN
  UPDATE oyun.kamu_toptan_teklif SET durum='iptal',bitis=now() WHERE id=d.id;
 ELSIF p_eylem='ret' AND oyun.sirket_yonetici_mi(d.satici,u) THEN
  UPDATE oyun.kamu_toptan_teklif SET durum='ret',bitis=now() WHERE id=d.id;
 ELSIF p_eylem='kabul' AND oyun.sirket_yonetici_mi(d.satici,u) THEN
  SELECT * INTO st FROM oyun.eko_urun_stok WHERE sirket_id=d.satici AND urun=d.urun FOR UPDATE;
  IF st.sirket_id IS NULL OR st.adet<d.adet OR st.satis_fiyati<>d.birim_fiyat THEN
   RAISE EXCEPTION 'Stok veya birim fiyat degisti; yeni teklif isteyin';END IF;
  res:=oyun.eko_urun_toptan(d.alici,d.satici,d.urun,d.adet,u);
  UPDATE oyun.kamu_toptan_teklif SET durum='tamam',bitis=now() WHERE id=d.id;
  RETURN jsonb_build_object('durum','tamam','sonuc',res);
 ELSE RAISE EXCEPTION 'Bu teklif icin yetkili degilsin';END IF;
 RETURN jsonb_build_object('durum',p_eylem,'id',d.id);
END $function$;

CREATE OR REPLACE FUNCTION public.kamu_kurum_panel()
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE u uuid:=auth.uid();
BEGIN
