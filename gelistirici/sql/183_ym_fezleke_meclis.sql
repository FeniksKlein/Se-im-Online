--  183 (11.11.2026) · YÜKSEK MAHKEME FEZLEKESİ → TBMM → MECLİS SORUŞTURMASI → YÜCE DİVAN
--  Anayasa m.106/5-7 örnek alınarak (görev süreleri oyunun 1 aylık dönemine göre kısaltıldı):
--   1) Yüksek Mahkeme üyesi, görevdeki bir bakan ya da Cumhurbaşkanı Yardımcısı hakkında görevle ilgili
--      suç isnadını içeren fezleke yazar. Görevdeki üyelerin çoğunluğu imzalayınca fezleke TBMM'ye gider
--      (tek üye varsa kendi imzası yeter). İmza süresi 72 saat.
--   2) TBMM: dolu sandalyelerin salt çoğunluğu "soruşturma önergesi"ni imzalarsa (5 gün) Genel Kurul oylaması açılır.
--   3) Soruşturma açılması: gizli oy, dolu sandalyelerin 3/5'i (3 gün).
--   4) Soruşturma Komisyonu incelemesi (2 gün). İlgili bakan yazılı savunma verebilir.
--   5) Yüce Divan'a sevk: gizli oy, dolu sandalyelerin 2/3'ü (3 gün). Sevk edilen bakan görevden düşer.
--  Hakkında fezleke yazılan kişi kendi dosyasında imza ve oy kullanamaz. Oylar gizlidir: oylama sürerken
--  yalnız katılım, kapanınca kabul/ret sayısı görünür.
--  Yalnız ekler; mevcut tablolara, oyunculara ve 180'deki Cumhurbaşkanlığı fezlekesine dokunmaz.
-- =====================================================================

create table if not exists oyun.ym_fezleke (
  id           bigint generated by default as identity primary key,
  bakan_id     uuid   not null references oyun.profiller(id),
  makam_id     bigint not null references oyun.makamlar(id),
  makam_ad     text   not null,
  baslik       text   not null check (char_length(baslik) between 10 and 150),
  isnat        text   not null check (char_length(isnat) between 100 and 8000),
  deliller     text   not null default '' check (char_length(deliller) <= 6000),
  hukuki       text   not null check (char_length(hukuki) between 50 and 6000),
  yazan        uuid   not null references oyun.profiller(id),
  imzalar      uuid[] not null default '{}',
  durum        text   not null default 'imza'
    check (durum in ('imza','onerge','oylama1','komisyon','oylama2','yuce_divan','ret','dusmus','geri_cekildi')),
  olusturma    timestamptz not null default now(),
  gonderilme   timestamptz,
  asama_bit    timestamptz,
  savunma      text check (savunma is null or char_length(savunma) between 20 and 6000),
  savunma_at   timestamptz,
  oy1_kabul    int, oy1_ret int, oy1_gerek int,
  oy2_kabul    int, oy2_ret int, oy2_gerek int,
  sonuc        text,
  karar_at     timestamptz
);
create index if not exists ym_fezleke_durum on oyun.ym_fezleke(durum, asama_bit);
create index if not exists ym_fezleke_bakan on oyun.ym_fezleke(bakan_id);
create unique index if not exists ym_fezleke_tek_acik on oyun.ym_fezleke(makam_id)
  where durum in ('imza','onerge','oylama1','komisyon','oylama2');

create table if not exists oyun.ym_fezleke_onerge (
  fezleke_id bigint not null references oyun.ym_fezleke(id) on delete cascade,
  vekil      uuid   not null references oyun.profiller(id),
  zaman      timestamptz not null default now(),
  primary key (fezleke_id, vekil)
);
create table if not exists oyun.ym_fezleke_oy (
  fezleke_id bigint   not null references oyun.ym_fezleke(id) on delete cascade,
  asama      smallint not null check (asama in (1,2)),
  vekil      uuid     not null references oyun.profiller(id),
  oy         text     not null check (oy in ('kabul','ret')),
  zaman      timestamptz not null default now(),
  primary key (fezleke_id, asama, vekil)
);
alter table oyun.ym_fezleke enable row level security;
alter table oyun.ym_fezleke_onerge enable row level security;
alter table oyun.ym_fezleke_oy enable row level security;
revoke all on oyun.ym_fezleke, oyun.ym_fezleke_onerge, oyun.ym_fezleke_oy from public, anon, authenticated;
grant select, insert, update on oyun.ym_fezleke, oyun.ym_fezleke_onerge, oyun.ym_fezleke_oy to service_role;

-- ---------- yardımcılar ----------
create or replace function oyun.ymf_esik(p_tur text) returns int language sql stable set search_path = '' as $$
  select case p_tur
    when 'onerge' then greatest(1, oyun.aktif_vekil_sayi() / 2 + 1)
    when 'sorusturma' then greatest(1, ceil(oyun.aktif_vekil_sayi() * 3 / 5.0)::int)
    else greatest(1, ceil(oyun.aktif_vekil_sayi() * 2 / 3.0)::int) end
$$;
create or replace function oyun.ymf_vekil_mi(u uuid) returns boolean language sql stable set search_path = '' as $$
  select exists (select 1 from oyun.makamlar where user_id = u and tur = 'mv' and bit is null)
$$;
create or replace function oyun.ymf_imza_gerek() returns int language sql stable set search_path = '' as $$
  select oyun.cogunluk(greatest(1, coalesce(array_length(oyun.mahkeme_uyeleri(), 1), 0)))
$$;
create or replace function oyun.ymf_durum_ad(d text) returns text language sql immutable as $$
  select case d
    when 'imza' then 'Yüksek Mahkeme imza aşamasında'
    when 'onerge' then 'TBMM''de · soruşturma önergesi imzaya açık'
    when 'oylama1' then 'Genel Kurul · soruşturma açılması oylaması'
    when 'komisyon' then 'Meclis Soruşturma Komisyonu incelemesinde'
    when 'oylama2' then 'Genel Kurul · Yüce Divan''a sevk oylaması'
    when 'yuce_divan' then 'Yüce Divan''a sevk edildi'
    when 'ret' then 'Meclis reddetti'
    when 'dusmus' then 'Dosya düştü'
    when 'geri_cekildi' then 'Geri çekildi'
    else d end
$$;
-- Dosyayla ilgilenen herkese (bakan, yazan, imzalayan üyeler, CB, TBMM Başkanı) bildirim
create or replace function oyun.ymf_bildir_ilgililer(f oyun.ym_fezleke, p_metin text, t timestamptz) returns void
language plpgsql set search_path = '' as $$
declare u uuid;
begin
  for u in select distinct x from unnest(array[f.bakan_id, f.yazan] || f.imzalar
             || array(select m.user_id from oyun.makamlar m where m.tur in ('cb','tbmm') and m.bit is null)) x where x is not null loop
    perform oyun.bildir(u, p_metin, t);
  end loop;
end $$;

-- Fezleke TBMM'ye ulaşır
create or replace function oyun.ymf_meclise_gonder(p_id bigint, t timestamptz) returns void
language plpgsql set search_path = '' as $$
declare f oyun.ym_fezleke; u uuid;
begin
  update oyun.ym_fezleke set durum = 'onerge', gonderilme = t, asama_bit = t + interval '5 days'
   where id = p_id and durum = 'imza' returning * into f;
  if f.id is null then return; end if;
  for u in select m.user_id from oyun.makamlar m where m.tur = 'mv' and m.bit is null and m.user_id <> f.bakan_id loop
    perform oyun.bildir(u, format('⚖️ TBMM''ye Yüksek Mahkeme fezlekesi #%s ulaştı: %s (%s). Meclis soruşturması önergesi için %s vekil imzası gerekiyor. Meclis › Yasama › Fezlekeler.',
      f.id, oyun.kad(f.bakan_id), f.makam_ad, oyun.ymf_esik('onerge')), t);
  end loop;
  perform oyun.ymf_bildir_ilgililer(f, format('⚖️ Yüksek Mahkeme fezlekesi #%s (%s hakkında) TBMM Başkanlığına gönderildi.', f.id, oyun.kad(f.bakan_id)), t);
  perform oyun.olay('meclis', format('Yüksek Mahkeme, %s %s hakkında görevle ilgili suç isnadıyla düzenlediği fezleke #%s''i TBMM''ye gönderdi: "%s"',
    f.makam_ad, oyun.kad(f.bakan_id), f.id, f.baslik), null, null, t);
end $$;

-- Oylamayı say; erken karar verilebiliyorsa ya da süre bittiyse sonuçlandır
create or replace function oyun.ymf_oy_say(p_id bigint, t timestamptz) returns void
language plpgsql set search_path = '' as $$
declare f oyun.ym_fezleke; a smallint; kabul int; ret int; gerek int; aktif int := oyun.aktif_vekil_sayi(); oyhakki int;
begin
  select * into f from oyun.ym_fezleke where id = p_id for update;
  if f.id is null or f.durum not in ('oylama1','oylama2') then return; end if;
  a := case when f.durum = 'oylama1' then 1 else 2 end;
  gerek := oyun.ymf_esik(case when a = 1 then 'sorusturma' else 'sevk' end);
  select count(*) filter (where o.oy = 'kabul'), count(*) filter (where o.oy = 'ret') into kabul, ret
    from oyun.ym_fezleke_oy o join oyun.makamlar m on m.user_id = o.vekil and m.tur = 'mv' and m.bit is null
   where o.fezleke_id = f.id and o.asama = a and o.vekil <> f.bakan_id;
  oyhakki := aktif - case when oyun.ymf_vekil_mi(f.bakan_id) then 1 else 0 end;
  if kabul >= gerek then
    if a = 1 then
      update oyun.ym_fezleke set durum = 'komisyon', asama_bit = t + interval '2 days', oy1_kabul = kabul, oy1_ret = ret, oy1_gerek = gerek where id = f.id;
      perform oyun.ymf_bildir_ilgililer(f, format('⚖️ TBMM, fezleke #%s üzerine %s hakkında Meclis soruşturması açtı (%s kabul, %s ret; gerekli %s). Soruşturma Komisyonu 2 gün inceleyecek; ilgili bakan yazılı savunma verebilir.',
        f.id, oyun.kad(f.bakan_id), kabul, ret, gerek), t);
      perform oyun.olay('meclis', format('TBMM, %s %s hakkında gizli oyla Meclis soruşturması açtı (%s kabul, %s ret).', f.makam_ad, oyun.kad(f.bakan_id), kabul, ret), null, null, t);
    else
      update oyun.ym_fezleke set durum = 'yuce_divan', asama_bit = null, oy2_kabul = kabul, oy2_ret = ret, oy2_gerek = gerek, karar_at = t,
             sonuc = format('Yüce Divan''a sevk edildi (%s kabul, %s ret; gerekli %s).', kabul, ret, gerek) where id = f.id;
      perform oyun.makam_bitir(f.makam_id, t, 'yuce_divan');
      perform oyun.ymf_bildir_ilgililer(f, format('⚖️ TBMM, fezleke #%s dosyasında %s''i Yüce Divan''a sevk etti (%s kabul, %s ret). Anayasa gereği %s görevi sona erdi.',
        f.id, oyun.kad(f.bakan_id), kabul, ret, f.makam_ad), t);
      perform oyun.olay('meclis', format('TBMM, %s %s''i gizli oyla Yüce Divan''a sevk etti (%s kabul, %s ret). Sevk edilen bakan görevden düştü.', f.makam_ad, oyun.kad(f.bakan_id), kabul, ret), null, null, t);
    end if;
  elsif t >= f.asama_bit or ret > oyhakki - gerek then
    if a = 1 then
      update oyun.ym_fezleke set durum = 'ret', asama_bit = null, oy1_kabul = kabul, oy1_ret = ret, oy1_gerek = gerek, karar_at = t,
             sonuc = format('Meclis soruşturması açılması reddedildi (%s kabul, %s ret; gerekli %s).', kabul, ret, gerek) where id = f.id;
    else
      update oyun.ym_fezleke set durum = 'ret', asama_bit = null, oy2_kabul = kabul, oy2_ret = ret, oy2_gerek = gerek, karar_at = t,
             sonuc = format('Yüce Divan''a sevk reddedildi (%s kabul, %s ret; gerekli %s).', kabul, ret, gerek) where id = f.id;
    end if;
    perform oyun.ymf_bildir_ilgililer(f, format('⚖️ Fezleke #%s: TBMM %s reddetti (%s kabul, %s ret; gerekli %s).', f.id,
      case when a = 1 then 'soruşturma açılmasını' else 'Yüce Divan''a sevki' end, kabul, ret, gerek), t);
    perform oyun.olay('meclis', format('TBMM, %s hakkındaki fezleke #%s dosyasında %s reddetti (%s kabul, %s ret).', oyun.kad(f.bakan_id), f.id,
      case when a = 1 then 'soruşturma açılmasını' else 'Yüce Divan''a sevki' end, kabul, ret), null, null, t);
  end if;
end $$;

-- Bakanın/CB yardımcısının görevi başka yoldan bittiyse açık dosya düşer
create or replace function oyun.ymf_gorev_kontrol(f oyun.ym_fezleke, t timestamptz) returns boolean
language plpgsql set search_path = '' as $$
begin
  if exists (select 1 from oyun.makamlar m where m.id = f.makam_id and m.bit is null) then return false; end if;
  update oyun.ym_fezleke set durum = 'dusmus', asama_bit = null, karar_at = t,
         sonuc = 'İlgili kişinin görevi başka bir nedenle sona erdiği için dosya Meclis gündeminden düştü.' where id = f.id;
  perform oyun.ymf_bildir_ilgililer(f, format('⚖️ Fezleke #%s: %s görevi sona erdiği için dosya düştü.', f.id, f.makam_ad), t);
  return true;
end $$;

-- ---------- zamanlayıcı ----------
create or replace function oyun.ym_fezleke_tick() returns int
language plpgsql set search_path = '' as $$
declare t timestamptz := oyun.simdi(); f oyun.ym_fezleke; n int := 0; imza int; gerek int;
begin
  if not pg_try_advisory_xact_lock(hashtext('oyun.ym_fezleke_tick')) then return 0; end if;
  for f in select * from oyun.ym_fezleke where durum in ('imza','onerge','oylama1','komisyon','oylama2') order by id loop
    n := n + 1;
    if oyun.ymf_gorev_kontrol(f, t) then continue; end if;
    if f.durum = 'imza' then
      if cardinality(f.imzalar) >= oyun.ymf_imza_gerek() then
        perform oyun.ymf_meclise_gonder(f.id, t);
      elsif t >= f.asama_bit then
        update oyun.ym_fezleke set durum = 'dusmus', asama_bit = null, karar_at = t,
               sonuc = 'Yüksek Mahkeme üyelerinin çoğunluğu 72 saat içinde imzalamadığı için fezleke gönderilmedi.' where id = f.id;
        perform oyun.bildir(f.yazan, format('Fezleke #%s yeterli üye imzası toplanamadığı için düştü.', f.id), t);
      end if;
    elsif f.durum = 'onerge' then
      select count(*) into imza from oyun.ym_fezleke_onerge o join oyun.makamlar m on m.user_id = o.vekil and m.tur = 'mv' and m.bit is null
       where o.fezleke_id = f.id and o.vekil <> f.bakan_id;
      gerek := oyun.ymf_esik('onerge');
      if imza >= gerek then
        update oyun.ym_fezleke set durum = 'oylama1', asama_bit = t + interval '3 days' where id = f.id;
        perform oyun.olay('meclis', format('Fezleke #%s: %s hakkındaki Meclis soruşturması önergesi %s imzayla Genel Kurul gündemine alındı. Gizli oylama 3 gün sürecek.', f.id, oyun.kad(f.bakan_id), imza), null, null, t);
        perform oyun.ymf_bildir_ilgililer(f, format('⚖️ Fezleke #%s: soruşturma önergesi Genel Kurul''da oylamaya açıldı (3/5 gerekli).', f.id), t);
      elsif t >= f.asama_bit then
        update oyun.ym_fezleke set durum = 'dusmus', asama_bit = null, karar_at = t,
               sonuc = format('Soruşturma önergesi süresinde yeter sayıya ulaşmadı (%s imza; gerekli %s).', imza, gerek) where id = f.id;
        perform oyun.ymf_bildir_ilgililer(f, format('⚖️ Fezleke #%s: soruşturma önergesi yeter sayıya ulaşmadığı için dosya düştü (%s/%s imza).', f.id, imza, gerek), t);
      end if;
    elsif f.durum = 'komisyon' then
      if t >= f.asama_bit then
        update oyun.ym_fezleke set durum = 'oylama2', asama_bit = t + interval '3 days' where id = f.id;
        perform oyun.olay('meclis', format('Meclis Soruşturma Komisyonu %s hakkındaki incelemesini tamamladı. Yüce Divan''a sevk için gizli oylama başladı (2/3 gerekli).', oyun.kad(f.bakan_id)), null, null, t);
        perform oyun.ymf_bildir_ilgililer(f, format('⚖️ Fezleke #%s: Yüce Divan''a sevk oylaması 3 gün sürecek.', f.id), t);
      end if;
    else
      perform oyun.ymf_oy_say(f.id, t);
    end if;
  end loop;
  return n;
end $$;

-- ---------- oyuncu işlemleri ----------
create or replace function public.ym_fezleke_yaz(p_hedef text, p_baslik text, p_isnat text, p_deliller text, p_hukuki text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare p oyun.profiller := oyun.profilim(); t timestamptz := oyun.simdi(); h oyun.profiller; m oyun.makamlar; yeni bigint;
  b text := btrim(coalesce(p_baslik,'')); i text := btrim(coalesce(p_isnat,'')); d text := btrim(coalesce(p_deliller,'')); hk text := btrim(coalesce(p_hukuki,''));
begin
  if not oyun.mahkeme_uyesi_mi(p.id) then raise exception 'Fezlekeyi yalnız Yüksek Mahkeme üyeleri yazabilir.'; end if;
  select * into h from oyun.profiller where lower(kad) = lower(btrim(coalesce(p_hedef,''))) and not yasakli;
  if h.id is null then raise exception 'Oyuncu bulunamadı.'; end if;
  select * into m from oyun.makamlar where user_id = h.id and tur in ('bakan','cb_yardimcisi') and bit is null order by (tur = 'bakan') desc, bas desc limit 1;
  if m.id is null then raise exception 'Fezleke yalnız görevdeki bir bakan ya da Cumhurbaşkanı Yardımcısı hakkında yazılabilir.'; end if;
  if exists (select 1 from oyun.ym_fezleke where makam_id = m.id and durum in ('imza','onerge','oylama1','komisyon','oylama2')) then
    raise exception 'Bu görev için zaten açık bir fezleke var.'; end if;
  if (select count(*) from oyun.ym_fezleke where yazan = p.id and olusturma > t - interval '24 hours') >= 2 then
    raise exception 'Bir üye 24 saatte en fazla 2 fezleke yazabilir.'; end if;
  if char_length(b) not between 10 and 150 then raise exception 'Fezleke başlığı 10–150 karakter olmalı.'; end if;
  if char_length(i) not between 100 and 8000 then raise exception 'Suç isnadı ve olaylar 100–8000 karakter olmalı.'; end if;
  if char_length(d) > 6000 then raise exception 'Deliller en fazla 6000 karakter olabilir.'; end if;
  if char_length(hk) not between 50 and 6000 then raise exception 'Hukuki değerlendirme 50–6000 karakter olmalı.'; end if;
  insert into oyun.ym_fezleke(bakan_id, makam_id, makam_ad, baslik, isnat, deliller, hukuki, yazan, imzalar, olusturma, asama_bit)
  values (h.id, m.id, oyun.makam_ad(m.tur, m.il_id, m.bakanlik), b, i, d, hk, p.id, array[p.id], t, t + interval '72 hours') returning id into yeni;
  if 1 >= oyun.ymf_imza_gerek() then
    perform oyun.ymf_meclise_gonder(yeni, t);
  else
    perform oyun.bildir(u, format('⚖️ %s, %s hakkında fezleke #%s taslağı yazdı ve imzanızı bekliyor. Adliye › Yüksek Mahkeme › Fezlekeler.', p.kad, oyun.kad(h.id), yeni), t)
      from unnest(oyun.mahkeme_uyeleri()) u where u <> p.id;
  end if;
  return jsonb_build_object('tamam', true, 'id', yeni, 'durum', (select durum from oyun.ym_fezleke where id = yeni));
end $$;

create or replace function public.ym_fezleke_imzala(p_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare p oyun.profiller := oyun.profilim(); t timestamptz := oyun.simdi(); f oyun.ym_fezleke;
begin
  if not oyun.mahkeme_uyesi_mi(p.id) then raise exception 'Fezlekeyi yalnız Yüksek Mahkeme üyeleri imzalayabilir.'; end if;
  select * into f from oyun.ym_fezleke where id = p_id for update;
  if f.id is null or f.durum <> 'imza' then raise exception 'Bu fezleke imzaya açık değil.'; end if;
  if p.id = any(f.imzalar) then raise exception 'Bu fezlekeyi zaten imzaladın.'; end if;
  update oyun.ym_fezleke set imzalar = imzalar || p.id where id = f.id returning * into f;
  perform oyun.bildir(f.yazan, format('%s fezleke #%s''i imzaladı.', p.kad, f.id), t);
  if cardinality(f.imzalar) >= oyun.ymf_imza_gerek() then perform oyun.ymf_meclise_gonder(f.id, t); end if;
  return jsonb_build_object('tamam', true, 'durum', (select durum from oyun.ym_fezleke where id = f.id));
end $$;

create or replace function public.ym_fezleke_geri_cek(p_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare p oyun.profiller := oyun.profilim(); t timestamptz := oyun.simdi();
begin
  update oyun.ym_fezleke set durum = 'geri_cekildi', asama_bit = null, karar_at = t, sonuc = 'Yazan üye taslağı TBMM''ye gönderilmeden geri çekti.'
   where id = p_id and yazan = p.id and durum = 'imza';
  if not found then raise exception 'Yalnız kendi yazdığın ve henüz TBMM''ye gitmemiş fezlekeyi geri çekebilirsin.'; end if;
  return jsonb_build_object('tamam', true);
end $$;

create or replace function public.ym_fezleke_onerge_imzala(p_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare p oyun.profiller := oyun.profilim(); t timestamptz := oyun.simdi(); f oyun.ym_fezleke;
begin
  if not oyun.ymf_vekil_mi(p.id) then raise exception 'Soruşturma önergesini yalnız milletvekilleri imzalayabilir.'; end if;
  select * into f from oyun.ym_fezleke where id = p_id;
  if f.id is null or f.durum <> 'onerge' or f.asama_bit <= t then raise exception 'Bu fezleke için önerge imzaya açık değil.'; end if;
  if f.bakan_id = p.id then raise exception 'Hakkındaki fezlekede önerge imzalayamazsın.'; end if;
  insert into oyun.ym_fezleke_onerge(fezleke_id, vekil, zaman) values (f.id, p.id, t) on conflict do nothing;
  if not found then raise exception 'Bu önergeyi zaten imzaladın.'; end if;
  perform oyun.ym_fezleke_tick();
  return jsonb_build_object('tamam', true, 'durum', (select durum from oyun.ym_fezleke where id = f.id));
end $$;

create or replace function public.ym_fezleke_oy(p_id bigint, p_oy text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare p oyun.profiller := oyun.profilim(); t timestamptz := oyun.simdi(); f oyun.ym_fezleke; a smallint;
begin
  if p_oy is null or p_oy not in ('kabul','ret') then raise exception 'Kabul ya da ret.'; end if;
  if not oyun.ymf_vekil_mi(p.id) then raise exception 'Yalnız milletvekilleri oy kullanabilir.'; end if;
  select * into f from oyun.ym_fezleke where id = p_id;
  if f.id is null or f.durum not in ('oylama1','oylama2') or f.asama_bit <= t then raise exception 'Bu dosyada açık oylama yok.'; end if;
  if f.bakan_id = p.id then raise exception 'Hakkındaki dosyada oy kullanamazsın.'; end if;
  a := case when f.durum = 'oylama1' then 1 else 2 end;
  insert into oyun.ym_fezleke_oy(fezleke_id, asama, vekil, oy, zaman) values (f.id, a, p.id, p_oy, t)
  on conflict (fezleke_id, asama, vekil) do update set oy = excluded.oy, zaman = excluded.zaman;
  perform oyun.ymf_oy_say(f.id, t);
  return jsonb_build_object('tamam', true, 'durum', (select durum from oyun.ym_fezleke where id = f.id));
end $$;

create or replace function public.ym_fezleke_savunma(p_id bigint, p_metin text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare p oyun.profiller := oyun.profilim(); t timestamptz := oyun.simdi(); f oyun.ym_fezleke; s text := btrim(coalesce(p_metin,''));
begin
  select * into f from oyun.ym_fezleke where id = p_id for update;
  if f.id is null or f.bakan_id <> p.id then raise exception 'Yalnız hakkında fezleke düzenlenen kişi savunma verebilir.'; end if;
  if f.durum not in ('onerge','oylama1','komisyon','oylama2') then raise exception 'Bu aşamada savunma verilemez.'; end if;
  if char_length(s) not between 20 and 6000 then raise exception 'Savunma 20–6000 karakter olmalı.'; end if;
  update oyun.ym_fezleke set savunma = s, savunma_at = t where id = f.id;
  perform oyun.olay('meclis', format('%s, hakkındaki fezleke #%s için TBMM''ye yazılı savunma verdi.', p.kad, f.id), null, null, t);
  return jsonb_build_object('tamam', true);
end $$;

create or replace function public.ym_fezleke_panel() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare p oyun.profiller := oyun.profilim(); t timestamptz := oyun.simdi(); ym boolean := oyun.mahkeme_uyesi_mi(p.id); mv boolean := oyun.ymf_vekil_mi(p.id);
begin
  return jsonb_build_object(
    'ym_uyesi', ym, 'vekil', mv, 'dolu', oyun.aktif_vekil_sayi(), 'imza_gerek', oyun.ymf_imza_gerek(),
    'esik', jsonb_build_object('onerge', oyun.ymf_esik('onerge'), 'sorusturma', oyun.ymf_esik('sorusturma'), 'sevk', oyun.ymf_esik('sevk')),
    'hedefler', case when ym then coalesce((select jsonb_agg(jsonb_build_object('kad', oyun.kad(m.user_id), 'makam', oyun.makam_ad(m.tur, m.il_id, m.bakanlik),
        'acik', exists (select 1 from oyun.ym_fezleke z where z.makam_id = m.id and z.durum in ('imza','onerge','oylama1','komisyon','oylama2')))
        order by (m.tur = 'cb_yardimcisi') desc, oyun.makam_ad(m.tur, m.il_id, m.bakanlik))
      from oyun.makamlar m where m.tur in ('bakan','cb_yardimcisi') and m.bit is null), '[]'::jsonb) else '[]'::jsonb end,
    'dosyalar', coalesce((select jsonb_agg(x order by (x->>'acik')::boolean desc, (x->>'id')::bigint desc) from (
      select jsonb_build_object(
        'id', f.id, 'baslik', f.baslik, 'bakan', oyun.kad(f.bakan_id), 'makam', f.makam_ad, 'durum', f.durum, 'durum_ad', oyun.ymf_durum_ad(f.durum),
        'acik', f.durum in ('imza','onerge','oylama1','komisyon','oylama2'),
        'yazan', oyun.kad(f.yazan), 'imzalar', (select coalesce(jsonb_agg(oyun.kad(u)), '[]'::jsonb) from unnest(f.imzalar) u),
        'isnat', f.isnat, 'deliller', f.deliller, 'hukuki', f.hukuki, 'savunma', f.savunma, 'savunma_at', f.savunma_at,
        'olusturma', f.olusturma, 'gonderilme', f.gonderilme, 'asama_bit', f.asama_bit, 'karar_at', f.karar_at, 'sonuc', f.sonuc,
        'onerge_imza', (select count(*) from oyun.ym_fezleke_onerge o join oyun.makamlar m on m.user_id = o.vekil and m.tur = 'mv' and m.bit is null where o.fezleke_id = f.id),
        'katilim', (select count(*) from oyun.ym_fezleke_oy o where o.fezleke_id = f.id and o.asama = case when f.durum = 'oylama2' then 2 else 1 end),
        'oy1', case when f.oy1_gerek is not null then jsonb_build_object('kabul', f.oy1_kabul, 'ret', f.oy1_ret, 'gerek', f.oy1_gerek) end,
        'oy2', case when f.oy2_gerek is not null then jsonb_build_object('kabul', f.oy2_kabul, 'ret', f.oy2_ret, 'gerek', f.oy2_gerek) end,
        'benim_oyum', (select o.oy from oyun.ym_fezleke_oy o where o.fezleke_id = f.id and o.vekil = p.id and o.asama = case when f.durum = 'oylama2' then 2 else 1 end),
        'hakkimda', f.bakan_id = p.id,
        'imzalayabilirim', ym and f.durum = 'imza' and not (p.id = any(f.imzalar)),
        'geri_cekebilirim', f.yazan = p.id and f.durum = 'imza',
        'onerge_imzalayabilirim', mv and f.durum = 'onerge' and f.bakan_id <> p.id and f.asama_bit > t
           and not exists (select 1 from oyun.ym_fezleke_onerge o where o.fezleke_id = f.id and o.vekil = p.id),
        'onerge_imzaladim', exists (select 1 from oyun.ym_fezleke_onerge o where o.fezleke_id = f.id and o.vekil = p.id),
        'oy_verebilirim', mv and f.durum in ('oylama1','oylama2') and f.bakan_id <> p.id and f.asama_bit > t,
        'savunabilirim', f.bakan_id = p.id and f.durum in ('onerge','oylama1','komisyon','oylama2')) x
      from oyun.ym_fezleke f
      where f.durum <> 'imza' or ym or f.bakan_id = p.id
      order by f.id desc limit 40) q), '[]'::jsonb));
end $$;

