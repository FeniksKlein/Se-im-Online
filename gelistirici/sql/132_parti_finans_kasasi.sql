-- Parti kasası yalnızca parti amaçları için kullanılabilir. Mevcut veri değişmez.
create table if not exists oyun.parti_yatirim_pozisyon (
  parti_id bigint not null references oyun.partiler(id),
  kod text not null references oyun.piyasa_varlik(kod),
  miktar numeric(28,8) not null default 0 check (miktar >= 0),
  maliyet numeric not null default 0 check (maliyet >= 0),
  primary key (parti_id,kod)
);
create table if not exists oyun.parti_yatirim_islem (
  id bigint generated by default as identity primary key,
  parti_id bigint not null references oyun.partiler(id),
  yapan uuid not null,
  kod text not null references oyun.piyasa_varlik(kod),
  yon text not null check (yon in ('al','sat')),
  miktar numeric(28,8) not null check (miktar > 0),
  fiyat numeric not null check (fiyat > 0),
  brut numeric not null check (brut >= 100),
  komisyon numeric not null check (komisyon >= 0),
  zaman timestamptz not null default now()
);
create index if not exists parti_yatirim_islem_parti_idx on oyun.parti_yatirim_islem(parti_id,zaman desc);
create table if not exists oyun.parti_kampanya_gider (
  id bigint generated by default as identity primary key,
  parti_id bigint not null references oyun.partiler(id),
  yapan uuid not null,
  amac text not null check (amac in ('genel_secim','yerel_secim','cumhurbaskanligi','rutin')),
  kanal text not null check (kanal in ('reklam','tanitim')),
  secim_id bigint references oyun.secimler(id),
  il_id smallint references oyun.iller(id),
  baslik text not null,
  tutar numeric not null check (tutar >= 100),
  zaman timestamptz not null default now()
);
create index if not exists parti_kampanya_gider_parti_idx on oyun.parti_kampanya_gider(parti_id,zaman desc);
alter table oyun.parti_yatirim_pozisyon enable row level security;
alter table oyun.parti_yatirim_islem enable row level security;
alter table oyun.parti_kampanya_gider enable row level security;
-- Tabloya istemciden doğrudan yazma izni yok; yalnızca kimlik denetimli RPC fonksiyonları işlem yapar.
revoke all on oyun.parti_yatirim_pozisyon, oyun.parti_yatirim_islem, oyun.parti_kampanya_gider from anon, authenticated;

-- Önceki sürümdeki parti kasasından üyelerin kişisel cüzdanlarına para gönderme açığını kesin kapat.
create or replace function public.parti_destek(p_kad text, p_miktar numeric)
returns jsonb language plpgsql security definer set search_path to ''
as $$
begin
  raise exception 'Parti kasasından kişisel cüzdana ödeme yapılamaz. Seçim kampanyası, miting, reklam, kurum bağışı veya parti adına yatırım kullanın.';
end $$;
revoke all on function public.parti_destek(text,numeric) from public,anon;
grant execute on function public.parti_destek(text,numeric) to authenticated;

create or replace function public.parti_finans_durum(p_parti bigint)
returns jsonb language plpgsql security definer set search_path to ''
as $$
declare
  u uuid := auth.uid();
  pa oyun.partiler;
  yetki boolean;
begin
  if u is null or not exists(select 1 from oyun.profiller where id=u) then raise exception 'Önce giriş yapmalısın.'; end if;
  select * into pa from oyun.partiler where id=p_parti;
  if pa.id is null then raise exception 'Parti bulunamadı.'; end if;
  yetki := not pa.kapali and oyun.parti_gorevli(u,array['mali'])=pa.id;
  return jsonb_build_object(
    'parti',pa.ad, 'kasa',round(pa.kasa), 'yetkili',yetki,
    'portfoy',coalesce((select jsonb_agg(jsonb_build_object(
       'kod',v.kod,'ad',v.ad,'sinif',v.sinif,'fiyat',v.fiyat,
       'miktar',coalesce(pos.miktar,0),'maliyet',coalesce(pos.maliyet,0),
       'deger',round(coalesce(pos.miktar,0)*v.fiyat,2)) order by v.sinif,v.kod)
       from oyun.piyasa_varlik v
       left join oyun.parti_yatirim_pozisyon pos on pos.parti_id=pa.id and pos.kod=v.kod
       where v.aktif or coalesce(pos.miktar,0)>0),'[]'::jsonb),
    'yatirim_degeri',coalesce((select round(sum(p.miktar*v.fiyat),2)
       from oyun.parti_yatirim_pozisyon p join oyun.piyasa_varlik v on v.kod=p.kod
       where p.parti_id=pa.id),0),
    'hareketler',coalesce((select jsonb_agg(jsonb_build_object('zaman',h.zaman,'aciklama',h.aciklama,'tutar',h.tutar,'tur',h.tur)
       order by h.zaman desc,h.id desc)
       from (select * from oyun.parti_hareket where parti_id=pa.id order by zaman desc,id desc limit 30) h),'[]'::jsonb),
    'dernekler',coalesce((select jsonb_agg(jsonb_build_object('id',d.id,'ad',d.ad) order by d.ad)
       from oyun.dernekler d where not d.kapali),'[]'::jsonb),
    'medya',coalesce((select jsonb_agg(jsonb_build_object('id',s.id,'ad',s.ad,'sektor',s.sektor) order by s.ad)
       from oyun.sirketler s where s.aktif and s.sektor in ('medya','ajans')),'[]'::jsonb),
    'gazeteler',coalesce((select jsonb_agg(jsonb_build_object('id',g.id,'ad',g.ad) order by g.ad)
       from oyun.oyuncu_gazeteleri g where g.aktif),'[]'::jsonb));
end $$;

create or replace function public.parti_finans_bagis(p_hedef_tur text, p_hedef_id bigint, p_tutar numeric)
returns jsonb language plpgsql security definer set search_path to ''
as $$
declare
  u uuid:=auth.uid(); pa oyun.partiler; d oyun.dernekler; s oyun.sirketler;
  g oyun.oyuncu_gazeteleri; tut numeric; hedef text; sahib uuid;
  t timestamptz:=oyun.simdi();
begin
  if u is null then raise exception 'Oturum gerekli.'; end if;
  tut:=round(coalesce(p_tutar,0));
  if tut<100 or p_tutar<>trunc(p_tutar) or tut>100000000 then raise exception 'Bağış tutarı 100 - 100.000.000 ₺ arasında tam sayı olmalı.'; end if;
  select * into pa from oyun.partiler where id=oyun.parti_gorevli(u,array['mali']) and not kapali for update;
  if pa.id is null then raise exception 'Parti kasası için genel başkan veya mali işlerden sorumlu yardımcı olmalısın.'; end if;
  if p_hedef_tur='dernek' then
    select * into d from oyun.dernekler where id=p_hedef_id and not kapali for update;
    if d.id is null then raise exception 'Aktif dernek bulunamadı.'; end if;
    if d.baskan in (u,pa.gb) or d.kurucu in (u,pa.gb) then
      raise exception 'Yönettiğin veya genel başkanın yönettiği derneğe parti kasasından bağış yapılamaz.'; end if;
    hedef:=d.ad;
  elsif p_hedef_tur='medya' then
    select * into s from oyun.sirketler where id=p_hedef_id and aktif and sektor in ('medya','ajans') for update;
    if s.id is null then raise exception 'Aktif medya şirketi bulunamadı.'; end if;
    if s.kurucu in (u,pa.gb) or s.yonetici in (u,pa.gb)
      or exists(select 1 from oyun.sirket_ortaklari o where o.sirket_id=s.id and o.user_id in (u,pa.gb) and o.pay>0) then
      raise exception 'Kendine veya genel başkanın şirketine parti kasasından bağış yapılamaz.'; end if;
    hedef:=s.ad;
  elsif p_hedef_tur='gazete' then
    select * into g from oyun.oyuncu_gazeteleri where id=p_hedef_id and aktif for update;
    if g.id is null then raise exception 'Aktif gazete bulunamadı.'; end if;
    if g.sahip in (u,pa.gb) then raise exception 'Kendi gazetenize parti kasasından bağış yapılamaz.'; end if;
    hedef:=g.ad;
  else
    raise exception 'Parti yalnızca dernek, medya şirketi ve gazeteye bağış yapabilir.';
  end if;
  update oyun.partiler set kasa=kasa-tut where id=pa.id and kasa>=tut;
  if not found then raise exception 'Parti kasasında yeterli para yok.'; end if;
  if p_hedef_tur='dernek' then
    update oyun.dernekler set kasa=kasa+tut where id=d.id;
    insert into oyun.dernek_hareket(dernek_id,zaman,tutar,tur,aciklama,user_id)
       values(d.id,t,tut,'bagis',pa.ad||' tarafından kurumsal bağış',u);
    sahib:=d.baskan;
  elsif p_hedef_tur='medya' then
    update oyun.sirketler set kasa=kasa+tut where id=s.id;
    insert into oyun.sirket_hareket(sirket_id,zaman,tutar,aciklama)
       values(s.id,t,tut,pa.ad||' tarafından kurumsal bağış');
    sahib:=oyun.sirket_sahibi(s.id);
  else
    update oyun.oyuncu_gazeteleri set kasa=kasa+tut where id=g.id;
    insert into oyun.gazete_hareket(gazete_id,zaman,tutar,tur,aciklama)
       values(g.id,t,tut,'bagis',pa.ad||' tarafından kurumsal bağış');
    sahib:=g.sahip;
  end if;
  insert into oyun.parti_hareket(parti_id,zaman,tutar,tur,aciklama)
    values(pa.id,t,-tut,'kurum_bagisi',format('%s kurumuna bağış: %s',p_hedef_tur,hedef));
  if sahib is not null and sahib<>u then
    perform oyun.bildir(sahib,format('%s, %s kuruluşuna %s ₺ bağışladı.',pa.ad,hedef,oyun.tl(tut)),t);
  end if;
  return jsonb_build_object('tamam',true,'parti',pa.id,'hedef',hedef,'tutar',tut);
end $$;

create or replace function public.parti_finans_emir(p_parti bigint,p_kod text,p_yon text,p_tutar numeric)
returns jsonb language plpgsql security definer set search_path to ''
as $$
declare
  u uuid:=auth.uid(); pa oyun.partiler; v oyun.piyasa_varlik;
  pos oyun.parti_yatirim_pozisyon; adet numeric(28,8); brut numeric; kom numeric; toplam numeric;
  t timestamptz:=oyun.simdi();
begin
  if u is null then raise exception 'Giriş gerekli.'; end if;
  if p_yon not in ('al','sat') or p_yon is null then raise exception 'Alış veya satış seç.'; end if;
  if p_tutar is null or p_tutar <> trunc(p_tutar) or p_tutar<100 or p_tutar>100000000 then
    raise exception 'İşlem tutarı 100 - 100.000.000 ₺ tam sayı olmalı.'; end if;
  perform oyun.piyasa_guncelle();
  select * into pa from oyun.partiler where id=p_parti and not kapali for update;
  if pa.id is null or oyun.parti_gorevli(u,array['mali']) is distinct from pa.id then
    raise exception 'Parti yatırımlarını yalnız genel başkan veya mali işlerden sorumlu yardımcı yapabilir.'; end if;
  select * into v from oyun.piyasa_varlik where kod=p_kod and aktif for update;
  if v.kod is null or v.fiyat<=0 then raise exception 'Varlık şu anda işleme açık değil.'; end if;
  insert into oyun.parti_yatirim_pozisyon(parti_id,kod) values(pa.id,v.kod) on conflict do nothing;
  select * into pos from oyun.parti_yatirim_pozisyon where parti_id=pa.id and kod=v.kod for update;
  brut:=p_tutar;
  adet:=trunc(brut/v.fiyat,8);
  if adet<=0 then raise exception 'Bu tutarla alınabilecek miktar yok.'; end if;
  if p_yon='al' then
    kom:=greatest(1,round(brut*0.003)); toplam:=brut+kom;
    update oyun.partiler set kasa=kasa-toplam where id=pa.id and kasa>=toplam;
    if not found then raise exception 'Parti kasasında alış bedeli ve komisyon için para yok.'; end if;
    update oyun.parti_yatirim_pozisyon set miktar=miktar+adet,maliyet=maliyet+brut
      where parti_id=pa.id and kod=v.kod;
    insert into oyun.parti_hareket(parti_id,zaman,tutar,tur,aciklama)
      values(pa.id,t,-toplam,'yatirim_al',format('%s parti portföyüne alındı (%s adet, komisyon %s ₺)',v.kod,adet,kom));
  else
    if pos.miktar<adet then raise exception 'Parti portföyünde bu satış için yeterli varlık yok.'; end if;
    brut:=round(adet*v.fiyat);
    if brut<100 then raise exception 'Satış en az 100 ₺ olmalı.'; end if;
    kom:=greatest(1,round(brut*0.003)); toplam:=brut-kom;
    update oyun.parti_yatirim_pozisyon set
      miktar=miktar-adet,
      maliyet=case when miktar-adet<0.00000001 then 0 else round(maliyet*(miktar-adet)/miktar,2) end
      where parti_id=pa.id and kod=v.kod and miktar>=adet;
    if not found then raise exception 'Parti portföyünde yeterli varlık yok.'; end if;
    update oyun.partiler set kasa=kasa+toplam where id=pa.id;
    insert into oyun.parti_hareket(parti_id,zaman,tutar,tur,aciklama)
      values(pa.id,t,toplam,'yatirim_sat',format('%s parti portföyünden satıldı (%s adet, komisyon %s ₺)',v.kod,adet,kom));
  end if;
  update oyun.ulke set hazine=hazine+kom/oyun.pazar_tl_milyar() where id=1;
  insert into oyun.parti_yatirim_islem(parti_id,yapan,kod,yon,miktar,fiyat,brut,komisyon,zaman)
    values(pa.id,u,v.kod,p_yon,adet,v.fiyat,brut,kom,t);
  return jsonb_build_object('tamam',true,'yon',p_yon,'kod',v.kod,'adet',adet,
    'fiyat',v.fiyat,'komisyon',kom,'net',case when p_yon='al' then -toplam else toplam end,'parti_id',pa.id);
end $$;

create or replace function public.parti_finans_kampanya(
  p_parti bigint,p_amac text,p_kanal text,p_tutar numeric,p_baslik text,p_il integer default null)
returns jsonb language plpgsql security definer set search_path to ''
as $$
declare
  u uuid:=auth.uid(); pa oyun.partiler; t timestamptz:=oyun.simdi();
  tut numeric; b text; v_secim bigint; v_il smallint;
begin
  if u is null then raise exception 'Oturum açmalısın.'; end if;
  if p_amac not in ('genel_secim','yerel_secim','cumhurbaskanligi','rutin') or p_amac is null then
    raise exception 'Geçerli bir seçim veya rutin faaliyet amacı seç.'; end if;
  if p_kanal not in ('reklam','tanitim') or p_kanal is null then raise exception 'Reklam veya tanıtım seç.'; end if;
  tut:=round(coalesce(p_tutar,0));
  if tut<100 or p_tutar<>trunc(p_tutar) or tut>100000000 then
    raise exception 'Kampanya bedeli 100 - 100.000.000 ₺ arasında tam sayı olmalı.'; end if;
  b:=oyun.metin_temizle(coalesce(p_baslik,''),120);
  if char_length(b)<10 then raise exception 'Tanıtım açıklaması en az 10 karakter olmalı.'; end if;
  if p_il is not null then
    if not exists(select 1 from oyun.iller where id=p_il) then raise exception 'Geçersiz il.'; end if;
    v_il:=p_il::smallint;
  end if;
  select * into pa from oyun.partiler where id=p_parti and not kapali for update;
  if pa.id is null or oyun.parti_gorevli(u,array['mali','tanitim','secim']) is distinct from pa.id then
    raise exception 'Partinin genel başkanı veya yetkili yardımcısı kampanya harcaması yapabilir.'; end if;
  if p_amac<>'rutin' then
    select s.id into v_secim from oyun.secimler s where s.durum='bekliyor' and s.oy_bit>t
      and s.tur=case p_amac when 'genel_secim' then 'mv' when 'yerel_secim' then 'bel' else 'cb' end
      order by s.oy_bit limit 1;
    if v_secim is null then raise exception 'Bu seçim türü için yaklaşan aktif bir seçim bulunmuyor. Rutin tanıtımı seçebilirsin.'; end if;
  end if;
  if exists(select 1 from oyun.parti_kampanya_gider where parti_id=pa.id and zaman>t-interval '15 minutes') then
    raise exception 'Parti adına yeni tanıtım duyurusu için 15 dakika beklemelisin.'; end if;
  update oyun.partiler set kasa=kasa-tut where id=pa.id and kasa>=tut;
  if not found then raise exception 'Parti kasasında yeterli para yok.'; end if;
  insert into oyun.parti_kampanya_gider(parti_id,yapan,amac,kanal,secim_id,il_id,baslik,tutar,zaman)
    values(pa.id,u,p_amac,p_kanal,v_secim,v_il,b,tut,t);
  insert into oyun.parti_hareket(parti_id,zaman,tutar,tur,aciklama)
    values(pa.id,t,-tut,'kampanya',format('%s / %s: %s',p_amac,p_kanal,b));
  perform oyun.olay('parti',format('%s seçim ve tanıtım faaliyeti: %s',pa.kisa,b),v_il,pa.id,t);
  return jsonb_build_object('tamam',true,'parti_id',pa.id,'tutar',tut,'amac',p_amac,'kanal',p_kanal);
end $$;

