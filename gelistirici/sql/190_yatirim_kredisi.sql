--  190 (11.11.2026) · ŞİRKET YATIRIM KREDİSİ (proje finansmanı) — beta geri bildirimi:
--  "Şahsi kredi limitimiz yatırımlar için çok yetersiz (şube 500 bin, limit 150 bin); yatırıma özel limit olsa,
--   para yalnız yatırımda kullanılsa."
--  Gerçek hayattaki karşılığı: ticari yatırım kredisi / proje finansmanı. Kredi kişiye değil ŞİRKETE verilir ve
--  doğrudan yatırıma (şimdilik şube açılışı) harcanır; kimsenin cüzdanına geçmez.
--  Kurallar:
--   • Banka yatırım bedelinin en fazla %70'ini finanse eder; en az %30 öz katkı + işletme rezervi şirket kasasından.
--   • Vade 30 / 60 / 90 gün; yıllık faiz = Merkez Bankası politika faizi + 4 puan (ticari kredi marjı), sabit.
--     Geri ödeme her gün eşit taksitle şirket kasasından otomatik.
--   • Şirket başına aynı anda en fazla 3 yatırım kredisi ve toplam 25 milyon ₺ açık bakiye.
--   • Şartlar: şirket en az 3 gündür faal, karşılıksız çeki ve gecikmiş yatırım kredisi yok; banka şirketleri kullanamaz.
--   • Taksit ödenemezse gecikir: gecikmiş tutara yıllık faizin 1,5 katı gecikme faizi işler, şirketin kasasına giren
--     para önce gecikmiş taksite gider; gecikme sürerken yeni yatırım kredisi ve ortaklar cari hesabı kapalıdır.
--     Hakim ortak ve yöneticiye bildirim gider.
--   • Açık kredi bakiyesi şirketin defter değerinden düşülür (borç).
--  Para "Devlet bankası" kredisi gibi yaratılır (şahsi kredi_cek ile aynı). Mevcut veriye dokunmaz.
-- =====================================================================

create table if not exists oyun.yatirim_kredisi (
  id           bigint generated by default as identity primary key,
  sirket_id    bigint  not null references oyun.sirketler(id),
  kullanan     uuid    not null references oyun.profiller(id),
  amac         text    not null,
  ref_id       bigint,
  yatirim_bedeli numeric not null,
  anapara      numeric not null check (anapara > 0),
  oran         numeric not null,
  vade_gun     int     not null check (vade_gun in (30, 60, 90)),
  toplam       numeric not null,
  taksit       numeric not null,
  kalan        numeric not null,
  gecikmis     numeric not null default 0,
  gecikme_faizi numeric not null default 0,
  odenen_taksit int    not null default 0,
  son_tahsil   date,
  durum        text    not null default 'aktif' check (durum in ('aktif','gecikmede','kapandi')),
  acilis       timestamptz not null default now(),
  kapanis      timestamptz
);
create index if not exists yatirim_kredisi_sirket on oyun.yatirim_kredisi(sirket_id, durum);
alter table oyun.yatirim_kredisi enable row level security;
revoke all on oyun.yatirim_kredisi from public, anon, authenticated;
grant select, insert, update on oyun.yatirim_kredisi to service_role;

create or replace function oyun.yatirim_kredisi_borc(p_sirket bigint) returns numeric
language sql stable set search_path = '' as $$
  select coalesce((select sum(kalan + gecikme_faizi) from oyun.yatirim_kredisi where sirket_id = p_sirket and durum <> 'kapandi'), 0)
$$;
create or replace function oyun.yatirim_kredisi_oran() returns numeric language sql stable set search_path = '' as $$
  select round(oyun.politika_faizi() + 4, 2)
$$;

-- Şirket defter değeri: ortaklardan alacak (188) dahil, yatırım kredisi borcu düşülür
create or replace function oyun.sirket_defter(p_sirket bigint)
 returns numeric language plpgsql stable set search_path to ''
as $function$
declare s oyun.sirketler; d numeric;
begin
  select * into s from oyun.sirketler where id = p_sirket;
  if s.id is null then return 0; end if;
  d := s.kasa
     + coalesce((select sum(adet * maliyet_birim) from oyun.eko_urun_stok where sirket_id = s.id), 0)
     + coalesce((select sum(fiyat) from oyun.eko_arsalar where sahibi_sirket = s.id), 0)
     + coalesce((select sum(maliyet) from oyun.eko_yapilar where sirket_id = s.id), 0)
     + oyun.ortak_cari_alacak(s.id)
     - oyun.yatirim_kredisi_borc(s.id);
  if s.sektor = 'banka' then
    d := d + coalesce((select sum(kalan) from oyun.oyb_kredi where banka_id = s.id and durum in ('aktif','takip')), 0)
           + coalesce((select sum(borc) from oyun.kredi_kartlari where banka_id = s.id and borc > 0), 0)
           + coalesce((select sum(tutar) from oyun.banka_dibs where banka_id = s.id and durum = 'acik'), 0)
           - coalesce((select sum(round(m.anapara * (1 + m.faiz / 100), 2)) from oyun.banka_mevduat m where m.banka_id = s.id and not m.kapandi), 0)
           - oyun.banka_vadesiz_toplam(s.id);
  end if;
  return greatest(0, d);
end $function$;

-- Ortaklar cari hesabı (188): gecikmiş yatırım kredisi varken kapalı
create or replace function oyun.ortak_cari_durum(p_sirket bigint, u uuid) returns jsonb
language plpgsql stable set search_path = '' as $$
declare s oyun.sirketler; pay numeric; acik numeric; hak numeric; serbest numeric; limit_ numeric; neden text;
begin
  select * into s from oyun.sirketler where id = p_sirket;
  select coalesce(o.pay, 0) into pay from oyun.sirket_ortaklari o where o.sirket_id = p_sirket and o.user_id = u;
  pay := coalesce(pay, 0);
  select coalesce(sum(greatest(0, c.tutar - coalesce(c.odenen, 0))), 0) into acik
    from oyun.cekler c where c.borclu_sirket = p_sirket and c.durum in ('aktif','karsiliksiz');
  select coalesce(sum(greatest(0, h.hak - h.cekilen)), 0) into hak from oyun.eko_ortak_gunluk_hak h where h.sirket_id = p_sirket;
  serbest := greatest(0, coalesce(s.kasa, 0) - coalesce(s.sermaye, 0) - acik - hak);
  limit_ := floor(least(100000000, serbest * pay / 100));
  neden := case
    when s.id is null or not s.aktif then 'Şirket faal değil.'
    when s.sektor = 'banka' then 'Bankalarda ortaklar cari hesabı kullanılamaz (mevduat sahipleri korunur).'
    when s.halka_acik then 'Halka açık şirketlerde ortaklar cari hesabı kullanılamaz (küçük yatırımcı korunur).'
    when pay < 50 then 'Cari hesaptan yalnız en az %50 paya sahip hakim ortak borç çekebilir.'
    when exists (select 1 from oyun.cekler c where c.borclu_sirket = p_sirket and c.durum = 'karsiliksiz') then 'Şirketin karşılıksız çeki varken ortağa borç verilemez.'
    when exists (select 1 from oyun.yatirim_kredisi y where y.sirket_id = p_sirket and y.durum = 'gecikmede') then 'Gecikmiş yatırım kredisi taksiti varken ortağa borç verilemez.'
    when limit_ < 1000 then 'Serbest kâr yetersiz: sermaye ve şirketin borçları çekilemez.'
    else null end;
  return jsonb_build_object('pay', pay, 'kasa', round(coalesce(s.kasa, 0)), 'sermaye', round(coalesce(s.sermaye, 0)), 'acik_cek', round(acik),
    'sakli_hak', round(hak), 'serbest', round(serbest), 'limit', case when neden is null then limit_ else 0 end, 'neden', neden,
    'oran', oyun.politika_faizi());
end $$;

-- Kredi uygunluğu ve şube için azami tutar
create or replace function oyun.yatirim_kredisi_uygunluk(p_sirket bigint) returns jsonb
language plpgsql stable set search_path = '' as $$
declare s oyun.sirketler; adet int; borc numeric; neden text;
begin
  select * into s from oyun.sirketler where id = p_sirket;
  select count(*), coalesce(sum(kalan), 0) into adet, borc from oyun.yatirim_kredisi where sirket_id = p_sirket and durum <> 'kapandi';
  neden := case
    when s.id is null or not s.aktif then 'Şirket faal değil.'
    when s.sektor = 'banka' then 'Bankalar yatırım kredisi kullanamaz.'
    when s.kurulus > now() - interval '3 days' then 'Yatırım kredisi için şirket en az 3 gündür faal olmalı.'
    when exists (select 1 from oyun.cekler c where c.borclu_sirket = p_sirket and c.durum = 'karsiliksiz') then 'Şirketin karşılıksız çeki var.'
    when exists (select 1 from oyun.yatirim_kredisi y where y.sirket_id = p_sirket and y.durum = 'gecikmede') then 'Gecikmiş yatırım kredisi taksiti var.'
    when adet >= 3 then 'Aynı anda en fazla 3 yatırım kredisi kullanılabilir.'
    when borc >= 25000000 then 'Şirketin açık yatırım kredisi bakiyesi 25 milyon ₺ sınırında.'
    else null end;
  return jsonb_build_object('uygun', neden is null, 'neden', neden, 'acik_kredi', adet, 'acik_bakiye', round(borc),
    'kalan_tavan', round(greatest(0, 25000000 - borc)), 'oran', oyun.yatirim_kredisi_oran(), 'finansman_orani', 70);
end $$;

-- Kredili şube açılışı: kredi kasaya girer ve aynı işlemde mevcut şube açma işleviyle yatırıma harcanır
create or replace function public.sirket_sube_ac_kredili(p_sirket bigint, p_il integer, p_kredi numeric, p_vade integer) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare u uuid := auth.uid(); t timestamptz := oyun.simdi(); s oyun.sirketler; d jsonb; uy jsonb; acilis numeric; rezerv numeric;
  azami numeric; oran numeric; toplam numeric; taksit numeric; kid bigint; r jsonb; city text;
begin
  if u is null then raise exception 'Oturum açmalısın.'; end if;
  if p_vade is null or p_vade not in (30, 60, 90) then raise exception 'Vade 30, 60 ya da 90 gün olabilir.'; end if;
  perform pg_advisory_xact_lock(98763, pg_catalog.hashtext(p_sirket::text));
  perform oyun.sirket_hesapla(p_sirket);
  select * into s from oyun.sirketler where id = p_sirket and aktif for update;
  if s.id is null or not oyun.sirket_yonetici_mi(p_sirket, u) then raise exception 'Faaliyetteki şirketin yöneticisi olmalısın.'; end if;
  uy := oyun.yatirim_kredisi_uygunluk(p_sirket);
  if not (uy->>'uygun')::boolean then raise exception '%', uy->>'neden'; end if;
  d := public.sirket_sube_teklif(p_sirket, p_il);
  acilis := (d->>'acilis_maliyeti')::numeric; rezerv := (d->>'isletme_rezervi')::numeric; city := d->>'il';
  azami := least(floor(acilis * 0.70), (uy->>'kalan_tavan')::numeric);
  if p_kredi is null or p_kredi <> round(p_kredi) or p_kredi < 10000 then raise exception 'En az 10.000 ₺, tam sayı kredi tutarı gir.'; end if;
  if p_kredi > azami then
    raise exception 'Banka bu şube yatırımının en fazla %%70''ini finanse eder: azami % ₺ (yatırım bedeli % ₺).', oyun.tl(azami), oyun.tl(acilis);
  end if;
  if s.kasa < (acilis - p_kredi) + rezerv then
    raise exception 'Öz katkı yetersiz: yatırımın kredi dışındaki kısmı % ₺ ve işletme rezervi % ₺ şirket kasasında olmalı (toplam % ₺, kasada % ₺).',
      oyun.tl(acilis - p_kredi), oyun.tl(rezerv), oyun.tl(acilis - p_kredi + rezerv), oyun.tl(s.kasa);
  end if;
  oran := oyun.yatirim_kredisi_oran();
  toplam := round(p_kredi * (1 + oran / 100 * p_vade / 365));
  taksit := ceil(toplam / p_vade);
  -- Kredi kasaya girer, ardından mevcut şube açma işlevi yatırım bedelini kasadan düşer (aynı işlem)
  update oyun.sirketler set kasa = kasa + p_kredi where id = p_sirket;
  insert into oyun.sirket_hareket(sirket_id, zaman, tutar, aciklama, faaliyet_gelir, faaliyet_gider, dagitilan_kar)
  values (p_sirket, t, p_kredi, format('Yatırım kredisi kullandırıldı (%s şubesi): %s ₺, %s gün, yıllık %%%s. Yalnız şube yatırımına harcanır.', city, oyun.tl(p_kredi), p_vade, oran), 0, 0, 0);
  r := public.sirket_sube_ac_ilde(p_sirket, p_il);
  insert into oyun.yatirim_kredisi(sirket_id, kullanan, amac, ref_id, yatirim_bedeli, anapara, oran, vade_gun, toplam, taksit, kalan, son_tahsil, acilis)
  values (p_sirket, u, format('%s şubesi', city), (r->>'id')::bigint, acilis, p_kredi, oran, p_vade, toplam, taksit, toplam, (t at time zone 'Europe/Istanbul')::date, t)
  returning id into kid;
  perform oyun.bildir(u, format('%s: %s şubesi açıldı. Yatırım kredisi #%s: %s ₺ (geri ödeme %s ₺, %s gün boyunca günde %s ₺ şirket kasasından).',
    s.ad, city, kid, oyun.tl(p_kredi), oyun.tl(toplam), p_vade, oyun.tl(taksit)), t);
  return r || jsonb_build_object('kredi_id', kid, 'kredi', p_kredi, 'toplam_geri_odeme', toplam, 'gunluk_taksit', taksit, 'oran', oran, 'oz_katki', acilis - p_kredi);
end $$;

-- Günlük taksit tahsilatı
create or replace function oyun.yatirim_kredisi_tick() returns int
language plpgsql security definer set search_path = '' as $$
declare t timestamptz := oyun.simdi(); bugun date := (oyun.simdi() at time zone 'Europe/Istanbul')::date; k record; gun int; borc_bugun numeric;
  v_kasa numeric; odenen numeric; gf numeric; n int := 0; ad text; hk uuid; i int;
begin
  if not pg_try_advisory_xact_lock(hashtext('oyun.yatirim_kredisi_tick')) then return 0; end if;
  for k in select * from oyun.yatirim_kredisi where durum <> 'kapandi' and son_tahsil < bugun order by id loop
    perform pg_advisory_xact_lock(98763, pg_catalog.hashtext(k.sirket_id::text));
    gun := least(31, bugun - k.son_tahsil);
    -- gecikme faizi: gecikmiş tutara yıllık oranın 1,5 katı
    gf := round(k.gecikmis * k.oran * 1.5 / 100 / 365 * gun);
    -- vadesi gelen taksitler (kalan bakiyeyi aşmaz)
    -- gecikmiş taksitler zaten kalan bakiyenin içinde: bugün vadesi gelen = kalan − gecikmiş ile sınırlı
    borc_bugun := least(greatest(0, k.kalan - k.gecikmis), k.taksit * gun);
    select s.kasa, s.ad into v_kasa, ad from oyun.sirketler s where s.id = k.sirket_id for update;
    odenen := greatest(0, least(coalesce(v_kasa, 0), k.gecikmis + gf + borc_bugun));
    update oyun.sirketler sx set kasa = sx.kasa - odenen where sx.id = k.sirket_id;
    -- önce gecikme faizi, sonra gecikmiş taksit, sonra bugünkü taksit
    update oyun.yatirim_kredisi set
      gecikme_faizi = 0,
      gecikmis = greatest(0, k.gecikmis + gf + borc_bugun - odenen),
      kalan = greatest(0, k.kalan + gf - odenen),
      odenen_taksit = odenen_taksit + gun,
      son_tahsil = bugun,
      durum = case when k.kalan + gf - odenen <= 0 then 'kapandi'
                   when k.gecikmis + gf + borc_bugun - odenen > 0 then 'gecikmede' else 'aktif' end,
      kapanis = case when k.kalan + gf - odenen <= 0 then t end
     where id = k.id;
    if odenen > 0 then
      insert into oyun.sirket_hareket(sirket_id, zaman, tutar, aciklama, faaliyet_gelir, faaliyet_gider, dagitilan_kar)
      values (k.sirket_id, t, -odenen, format('Yatırım kredisi #%s taksiti (%s)%s', k.id, k.amac, case when gf > 0 then format(', gecikme faizi %s ₺ dahil', oyun.tl(gf)) else '' end), 0, gf, 0);
    end if;
    if k.gecikmis + gf + borc_bugun - odenen > 0 then
      for hk in select distinct v from (select s.yonetici v from oyun.sirketler s where s.id = k.sirket_id
                 union select o.user_id from oyun.sirket_ortaklari o where o.sirket_id = k.sirket_id and o.pay >= 50) z where v is not null loop
        perform oyun.bildir(hk, format('%s: yatırım kredisi #%s taksiti kasada para olmadığı için ödenemedi. Gecikmiş tutar %s ₺; gecikme faizi işliyor, kasaya giren para önce bu borca gider.',
          ad, k.id, oyun.tl(k.gecikmis + gf + borc_bugun - odenen)), t);
      end loop;
    end if;
    n := n + 1;
  end loop;
  return n;
end $$;

-- Erken / gecikmiş taksit ödemesi (şirket kasasından)
create or replace function public.yatirim_kredisi_ode(p_kredi bigint, p_tutar numeric default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare u uuid := auth.uid(); t timestamptz := oyun.simdi(); k oyun.yatirim_kredisi; s oyun.sirketler; tutar numeric; kalan_yeni numeric; gec_yeni numeric;
begin
  select * into k from oyun.yatirim_kredisi where id = p_kredi for update;
  if k.id is null or k.durum = 'kapandi' then raise exception 'Açık yatırım kredisi bulunamadı.'; end if;
  if not oyun.sirket_yonetici_mi(k.sirket_id, u) then raise exception 'Krediyi yalnız şirket yöneticisi ödeyebilir.'; end if;
  perform pg_advisory_xact_lock(98763, pg_catalog.hashtext(k.sirket_id::text));
  select * into s from oyun.sirketler where id = k.sirket_id for update;
  tutar := round(least(coalesce(p_tutar, k.kalan), k.kalan));
  if tutar < 1 then raise exception 'Geçerli bir tutar gir.'; end if;
  if s.kasa < tutar then raise exception 'Şirket kasasında yeterli para yok (% ₺ gerekli, kasada % ₺).', oyun.tl(tutar), oyun.tl(s.kasa); end if;
  kalan_yeni := k.kalan - tutar; gec_yeni := greatest(0, k.gecikmis - tutar);
  update oyun.sirketler set kasa = kasa - tutar, son_islem = t where id = k.sirket_id;
  update oyun.yatirim_kredisi set kalan = kalan_yeni, gecikmis = gec_yeni,
    durum = case when kalan_yeni <= 0 then 'kapandi' when gec_yeni > 0 then 'gecikmede' else 'aktif' end,
    kapanis = case when kalan_yeni <= 0 then t end where id = k.id;
  insert into oyun.sirket_hareket(sirket_id, zaman, tutar, aciklama, faaliyet_gelir, faaliyet_gider, dagitilan_kar)
  values (k.sirket_id, t, -tutar, format('Yatırım kredisi #%s ödemesi (%s)', k.id, k.amac), 0, 0, 0);
  return jsonb_build_object('tamam', true, 'kalan', kalan_yeni, 'kapandi', kalan_yeni <= 0);
end $$;

create or replace function public.yatirim_kredisi_panel(p_sirket bigint, p_il integer default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare u uuid := auth.uid(); d jsonb; uy jsonb; acilis numeric;
begin
  if not exists (select 1 from oyun.sirket_ortaklari o where o.sirket_id = p_sirket and o.user_id = u and o.pay > 0)
     and not coalesce(oyun.sirket_yonetici_mi(p_sirket, u), false) then raise exception 'Bu şirketin ortağı değilsin.'; end if;
  uy := oyun.yatirim_kredisi_uygunluk(p_sirket);
  if p_il is not null then
    begin
      d := public.sirket_sube_teklif(p_sirket, p_il);
      acilis := (d->>'acilis_maliyeti')::numeric;
      uy := uy || jsonb_build_object('sube', jsonb_build_object('il', d->>'il', 'acilis', acilis, 'rezerv', (d->>'isletme_rezervi')::numeric,
        'azami_kredi', least(floor(acilis * 0.70), (uy->>'kalan_tavan')::numeric), 'kasa', (d->>'mevcut_kasa')::numeric,
        'gerekli_oz_katki', acilis - least(floor(acilis * 0.70), (uy->>'kalan_tavan')::numeric) + (d->>'isletme_rezervi')::numeric));
    exception when others then uy := uy || jsonb_build_object('sube_hata', sqlerrm);
    end;
  end if;
  return uy || jsonb_build_object('yonetici', coalesce(oyun.sirket_yonetici_mi(p_sirket, u), false),
    'krediler', coalesce((select jsonb_agg(jsonb_build_object('id', k.id, 'amac', k.amac, 'anapara', k.anapara, 'oran', k.oran, 'vade', k.vade_gun,
        'toplam', k.toplam, 'taksit', k.taksit, 'kalan', k.kalan, 'gecikmis', k.gecikmis, 'durum', k.durum, 'acilis', k.acilis,
        'odenen_gun', least(k.vade_gun, k.odenen_taksit)) order by k.id desc)
      from (select * from oyun.yatirim_kredisi where sirket_id = p_sirket order by id desc limit 10) k), '[]'::jsonb));
end $$;

