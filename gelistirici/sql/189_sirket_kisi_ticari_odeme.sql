--  189 (11.11.2026) · ŞİRKETTEN KİŞİYE TİCARİ ÖDEME (fatura / serbest meslek makbuzu → cari bakiye → ödeme)
--  Ercan'ın kuralı: şirket kişiye çek yazamaz (187); ama arada ticari ilişki varsa o ticaretteki cari bakiye
--  kadar doğrudan ödeme yapabilir (köşe yazısı/telif, danışmanlık, tasarım, hukuki hizmet, mal satışı…).
--  Akış (gerçek hayattaki gibi):
--   1) Kişi şirkete fatura / serbest meslek makbuzu keser (tür, tutar, açıklama).
--   2) Şirket yöneticisi onaylar ya da reddeder. Onaylanan fatura şirketin o kişiye cari borcudur.
--   3) Şirket, kişinin cari bakiyesi kadar kasasından doğrudan öder. Hizmet bedellerinde stopaj kesilir
--      (telif %17, diğer serbest meslek %20; mal satışında stopaj yok) ve Hazine'ye aktarılır.
--  Kötüye kullanım koruması:
--   • Şirketin ortağı ya da yöneticisi kendi şirketine fatura kesemez (onlar maaş, kâr payı, cari hesap kullanır).
--   • Bir şirketin son 30 günde onayladığı faturalar toplamı, son 30 günlük faaliyet gelirinin %30'unu
--     (en az 25.000 ₺) aşamaz. Kişi başına aynı anda en fazla 5 bekleyen fatura.
--   • Tüm onay ve ödemeler şirket hareketlerine yazılır, diğer ortaklara bildirim gider.
--  Mevcut tablo ve verilere dokunmaz.
-- =====================================================================

create table if not exists oyun.sirket_fatura (
  id          bigint generated by default as identity primary key,
  sirket_id   bigint  not null references oyun.sirketler(id),
  user_id     uuid    not null references oyun.profiller(id),
  tur         text    not null check (tur in ('telif','kose_yazisi','danismanlik','tasarim_reklam','hukuki','mal_satisi','diger')),
  aciklama    text    not null check (char_length(aciklama) between 10 and 1000),
  tutar       numeric not null check (tutar >= 100 and tutar <= 50000000),
  odenen      numeric not null default 0,
  durum       text    not null default 'bekliyor' check (durum in ('bekliyor','onaylandi','red','iptal','odendi')),
  olusturma   timestamptz not null default now(),
  karar_at    timestamptz,
  karar_veren uuid,
  karar_not   text
);
create index if not exists sirket_fatura_sirket on oyun.sirket_fatura(sirket_id, durum);
create index if not exists sirket_fatura_user on oyun.sirket_fatura(user_id, durum);
alter table oyun.sirket_fatura enable row level security;
revoke all on oyun.sirket_fatura from public, anon, authenticated;
grant select, insert, update on oyun.sirket_fatura to service_role;

create or replace function oyun.fatura_tur_ad(t text) returns text language sql immutable as $$
  select case t when 'telif' then 'Telif (kitap/eser)' when 'kose_yazisi' then 'Köşe yazısı / içerik'
    when 'danismanlik' then 'Danışmanlık' when 'tasarim_reklam' then 'Tasarım / reklam hizmeti'
    when 'hukuki' then 'Hukuki hizmet' when 'mal_satisi' then 'Mal satışı' else 'Diğer hizmet' end
$$;
create or replace function oyun.fatura_stopaj_oran(t text) returns numeric language sql immutable as $$
  select case t when 'mal_satisi' then 0 when 'telif' then 17 else 20 end
$$;
-- Şirketin son 30 günde onaylayabileceği fatura toplamı
create or replace function oyun.fatura_tavan(p_sirket bigint) returns jsonb language sql stable set search_path = '' as $$
  with g as (select coalesce(sum(h.faaliyet_gelir), 0) gelir from oyun.sirket_hareket h
              where h.sirket_id = p_sirket and h.zaman > now() - interval '30 days' and h.faaliyet_gelir > 0),
       o as (select coalesce(sum(f.tutar), 0) onayli from oyun.sirket_fatura f
              where f.sirket_id = p_sirket and f.durum in ('onaylandi','odendi') and f.karar_at > now() - interval '30 days')
  select jsonb_build_object('gelir30', round(g.gelir), 'tavan', round(greatest(25000, g.gelir * 0.30)),
                            'onayli30', round(o.onayli), 'kalan', round(greatest(0, greatest(25000, g.gelir * 0.30) - o.onayli)))
    from g, o
$$;
create or replace function oyun.fatura_yetkili(p_sirket bigint, u uuid) returns boolean language sql stable set search_path = '' as $$
  select coalesce(oyun.sirket_yonetici_mi(p_sirket, u), false)
      or exists (select 1 from oyun.sirket_ortaklari o where o.sirket_id = p_sirket and o.user_id = u and o.pay >= 50)
$$;

-- ---------- kişi: fatura kes / iptal ----------
create or replace function public.sirket_fatura_kes(p_sirket bigint, p_tur text, p_tutar numeric, p_aciklama text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare u uuid := auth.uid(); t timestamptz := oyun.simdi(); s oyun.sirketler; a text := btrim(coalesce(p_aciklama, '')); yeni bigint; x record;
begin
  if u is null then raise exception 'İşlem için giriş yapmalısın.'; end if;
  select * into s from oyun.sirketler where id = p_sirket and aktif;
  if s.id is null then raise exception 'Faal şirket bulunamadı.'; end if;
  if p_tur is null or p_tur not in ('telif','kose_yazisi','danismanlik','tasarim_reklam','hukuki','mal_satisi','diger') then raise exception 'Fatura türünü seç.'; end if;
  if p_tutar is null or p_tutar <> round(p_tutar) or p_tutar < 100 or p_tutar > 50000000 then raise exception '100 ₺ ile 50 milyon ₺ arasında tam sayı tutar gir.'; end if;
  if char_length(a) not between 10 and 1000 then raise exception 'Verdiğin mal ya da hizmeti 10–1000 karakterle açıkla.'; end if;
  if oyun.cek_sirket_ilgilisi(p_sirket, u) then
    raise exception 'Ortağı ya da yöneticisi olduğun şirkete fatura kesemezsin. Şirketten maaş, kâr payı ya da ortaklar cari hesabıyla para alınır.';
  end if;
  if (select count(*) from oyun.sirket_fatura where user_id = u and durum = 'bekliyor') >= 5 then raise exception 'Aynı anda en fazla 5 bekleyen faturan olabilir.'; end if;
  insert into oyun.sirket_fatura(sirket_id, user_id, tur, aciklama, tutar, olusturma) values (p_sirket, u, p_tur, a, p_tutar, t) returning id into yeni;
  for x in select distinct v from (select s.yonetici v union select o.user_id from oyun.sirket_ortaklari o where o.sirket_id = p_sirket and o.pay >= 50) z where v is not null loop
    perform oyun.bildir(x.v, format('%s, %s şirketine %s ₺ tutarında fatura kesti (%s). Şirket › Kasa / Sermaye › Ticari borçlar.', oyun.kad(u), s.ad, oyun.tl(p_tutar), oyun.fatura_tur_ad(p_tur)), t);
  end loop;
  return jsonb_build_object('tamam', true, 'id', yeni);
end $$;

create or replace function public.sirket_fatura_iptal(p_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
begin
  update oyun.sirket_fatura set durum = 'iptal', karar_at = oyun.simdi() where id = p_id and user_id = auth.uid() and durum = 'bekliyor';
  if not found then raise exception 'Yalnız kendi bekleyen faturanı iptal edebilirsin.'; end if;
  return jsonb_build_object('tamam', true);
end $$;

-- ---------- şirket: onay / red ----------
create or replace function public.sirket_fatura_karar(p_id bigint, p_kabul boolean, p_not text default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare u uuid := auth.uid(); t timestamptz := oyun.simdi(); f oyun.sirket_fatura; tv jsonb; ad text;
begin
  select * into f from oyun.sirket_fatura where id = p_id for update;
  if f.id is null or f.durum <> 'bekliyor' then raise exception 'Bu fatura karar bekliyor değil.'; end if;
  if not oyun.fatura_yetkili(f.sirket_id, u) then raise exception 'Faturayı yalnız şirket yöneticisi ya da hakim ortak onaylayabilir.'; end if;
  select s.ad into ad from oyun.sirketler s where s.id = f.sirket_id;
  if p_kabul then
    perform pg_advisory_xact_lock(98763, pg_catalog.hashtext(f.sirket_id::text));
    tv := oyun.fatura_tavan(f.sirket_id);
    if f.tutar > (tv->>'kalan')::numeric then
      raise exception 'Şirket son 30 günde faaliyet gelirinin %%30''u kadar (en az 25.000 ₺) kişilere fatura onaylayabilir. Kalan: % ₺ (30 günlük gelir % ₺).',
        oyun.tl((tv->>'kalan')::numeric), oyun.tl((tv->>'gelir30')::numeric);
    end if;
    update oyun.sirket_fatura set durum = 'onaylandi', karar_at = t, karar_veren = u, karar_not = left(p_not, 300) where id = f.id;
    insert into oyun.sirket_hareket(sirket_id, zaman, tutar, aciklama)
    values (f.sirket_id, t, 0, format('Fatura #%s onaylandı: %s, %s, %s ₺ (cari borç).', f.id, oyun.kad(f.user_id), oyun.fatura_tur_ad(f.tur), oyun.tl(f.tutar)));
    perform oyun.bildir(f.user_id, format('%s faturanı (#%s, %s ₺) onayladı. Şirket bu bakiye kadar sana ödeme yapabilir.', ad, f.id, oyun.tl(f.tutar)), t);
  else
    update oyun.sirket_fatura set durum = 'red', karar_at = t, karar_veren = u, karar_not = left(p_not, 300) where id = f.id;
    perform oyun.bildir(f.user_id, format('%s faturanı (#%s) reddetti.%s', ad, f.id, coalesce(' Not: ' || left(p_not, 200), '')), t);
  end if;
  return jsonb_build_object('tamam', true);
end $$;

-- ---------- şirket: cari bakiye kadar doğrudan ödeme ----------
create or replace function public.sirket_kisi_ode(p_sirket bigint, p_kad text, p_tutar numeric default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare u uuid := auth.uid(); t timestamptz := oyun.simdi(); s oyun.sirketler; k uuid; bakiye numeric; v_tutar numeric; kalan numeric;
  f record; parca numeric; stopaj numeric := 0; st numeric; x record;
begin
  if not oyun.fatura_yetkili(p_sirket, u) then raise exception 'Ödemeyi yalnız şirket yöneticisi ya da hakim ortak yapabilir.'; end if;
  select id into k from oyun.profiller where lower(kad) = lower(btrim(coalesce(p_kad, '')));
  if k is null then raise exception 'Oyuncu bulunamadı.'; end if;
  perform pg_advisory_xact_lock(98763, pg_catalog.hashtext(p_sirket::text));
  begin perform oyun.sirket_hesapla(p_sirket); exception when undefined_function then null; end;
  select * into s from oyun.sirketler where id = p_sirket and aktif for update;
  if s.id is null then raise exception 'Faal şirket bulunamadı.'; end if;
  select coalesce(sum(sf.tutar - sf.odenen), 0) into bakiye from oyun.sirket_fatura sf where sirket_id = p_sirket and user_id = k and durum = 'onaylandi';
  if bakiye <= 0 then raise exception 'Bu kişiyle onaylanmış ödenmemiş fatura yok. Şirket kişilere yalnız ticari cari bakiye kadar ödeme yapabilir.'; end if;
  v_tutar := round(least(coalesce(p_tutar, bakiye), bakiye));
  if v_tutar < 1 then raise exception 'Geçerli bir tutar gir.'; end if;
  if s.kasa < v_tutar then raise exception 'Şirket kasasında yeterli para yok (% ₺ gerekli, kasada % ₺).', oyun.tl(v_tutar), oyun.tl(s.kasa); end if;
  kalan := v_tutar;
  for f in select * from oyun.sirket_fatura sf where sf.sirket_id = p_sirket and sf.user_id = k and sf.durum = 'onaylandi' order by sf.karar_at, sf.id for update loop
    exit when kalan <= 0;
    parca := least(kalan, f.tutar - f.odenen);
    st := round(parca * oyun.fatura_stopaj_oran(f.tur) / 100);
    stopaj := stopaj + st;
    update oyun.sirket_fatura sfx set odenen = sfx.odenen + parca, durum = case when sfx.odenen + parca >= sfx.tutar then 'odendi' else sfx.durum end where sfx.id = f.id;
    kalan := kalan - parca;
  end loop;
  update oyun.sirketler set kasa = kasa - v_tutar, son_islem = t where id = p_sirket;
  perform oyun.para_islem(k, v_tutar - stopaj, 'sirket', format('%s: ticari ödeme (fatura bakiyesi %s ₺, stopaj %s ₺ kesildi)', s.ad, oyun.tl(v_tutar), oyun.tl(stopaj)), t, stopaj);
  if stopaj > 0 then
    perform oyun.hazine_kaydet('stopaj', round(stopaj / greatest(oyun.pazar_tl_milyar(), 1), 6), format('Serbest meslek/telif stopajı: %s', s.ad));
  end if;
  insert into oyun.sirket_hareket(sirket_id, zaman, tutar, aciklama, faaliyet_gider)
  values (p_sirket, t, -v_tutar, format('Ticari ödeme: %s (fatura bakiyesi; %s ₺ stopaj Hazine''ye aktarıldı)', oyun.kad(k), oyun.tl(stopaj)), v_tutar);
  perform oyun.bildir(k, format('%s sana %s ₺ ödedi (stopaj %s ₺ kesildi, cüzdanına %s ₺ geçti).', s.ad, oyun.tl(v_tutar), oyun.tl(stopaj), oyun.tl(v_tutar - stopaj)), t);
  for x in select o.user_id from oyun.sirket_ortaklari o where o.sirket_id = p_sirket and o.pay > 0 and o.user_id <> u loop
    perform oyun.bildir(x.user_id, format('%s, %s kasasından %s kişisine fatura karşılığı %s ₺ ödedi.', oyun.kad(u), s.ad, oyun.kad(k), oyun.tl(v_tutar)), t);
  end loop;
  return jsonb_build_object('tamam', true, 'odenen', v_tutar, 'stopaj', stopaj, 'net', v_tutar - stopaj,
    'kalan_bakiye', greatest(0, bakiye - v_tutar));
end $$;

-- ---------- paneller ----------
create or replace function public.sirket_fatura_panel(p_sirket bigint default null) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare u uuid := auth.uid();
begin
  if p_sirket is null then   -- kişinin kendi faturaları
    return jsonb_build_object('faturalarim', coalesce((select jsonb_agg(jsonb_build_object('id', f.id, 'sirket', s.ad, 'sirket_id', f.sirket_id,
        'tur', oyun.fatura_tur_ad(f.tur), 'tutar', f.tutar, 'odenen', f.odenen, 'durum', f.durum, 'olusturma', f.olusturma, 'karar_not', f.karar_not) order by f.id desc)
      from (select * from oyun.sirket_fatura where user_id = u order by id desc limit 30) f join oyun.sirketler s on s.id = f.sirket_id), '[]'::jsonb));
  end if;
  if not (oyun.fatura_yetkili(p_sirket, u) or exists (select 1 from oyun.sirket_ortaklari o where o.sirket_id = p_sirket and o.user_id = u)) then
    raise exception 'Bu şirketin ortağı değilsin.';
  end if;
  return oyun.fatura_tavan(p_sirket) || jsonb_build_object(
    'yetkili', oyun.fatura_yetkili(p_sirket, u),
    'bekleyen', coalesce((select jsonb_agg(jsonb_build_object('id', f.id, 'kad', oyun.kad(f.user_id), 'tur', oyun.fatura_tur_ad(f.tur), 'tutar', f.tutar,
        'aciklama', f.aciklama, 'olusturma', f.olusturma) order by f.id) from oyun.sirket_fatura f where f.sirket_id = p_sirket and f.durum = 'bekliyor'), '[]'::jsonb),
    'bakiyeler', coalesce((select jsonb_agg(jsonb_build_object('kad', oyun.kad(z.user_id), 'bakiye', round(z.b), 'adet', z.n) order by z.b desc)
        from (select user_id, sum(tutar - odenen) b, count(*) n from oyun.sirket_fatura where sirket_id = p_sirket and durum = 'onaylandi' group by user_id) z), '[]'::jsonb),
    'toplam_borc', (select round(coalesce(sum(tutar - odenen), 0)) from oyun.sirket_fatura where sirket_id = p_sirket and durum = 'onaylandi'));
end $$;

-- Fatura kesilecek şirket arama (ad ile)
create or replace function public.sirket_fatura_ara(p_ara text) returns jsonb
language sql stable security definer set search_path = '' as $$
  select coalesce(jsonb_agg(jsonb_build_object('id', s.id, 'ad', s.ad, 'sektor', s.sektor) order by s.ad), '[]'::jsonb)
    from (select * from oyun.sirketler where aktif and char_length(btrim(coalesce(p_ara, ''))) >= 2 and ad ilike '%' || btrim(p_ara) || '%' order by ad limit 12) s
$$;

revoke all on function oyun.fatura_tur_ad(text), oyun.fatura_stopaj_oran(text), oyun.fatura_tavan(bigint), oyun.fatura_yetkili(bigint, uuid) from public, anon, authenticated;
revoke all on function public.sirket_fatura_kes(bigint, text, numeric, text), public.sirket_fatura_iptal(bigint), public.sirket_fatura_karar(bigint, boolean, text),
  public.sirket_kisi_ode(bigint, text, numeric), public.sirket_fatura_panel(bigint), public.sirket_fatura_ara(text) from public, anon;
grant execute on function public.sirket_fatura_kes(bigint, text, numeric, text), public.sirket_fatura_iptal(bigint), public.sirket_fatura_karar(bigint, boolean, text),
  public.sirket_kisi_ode(bigint, text, numeric), public.sirket_fatura_panel(bigint), public.sirket_fatura_ara(text) to authenticated, service_role;
