-- Yasama dokunulmazligi: fezleke -> bagimsiz yargi imzasi -> 5 uyeli hazirlik
-- -> 7 uyeli karma komisyon -> 600 sandalye TBMM -> 7 gun AYM itirazi
-- -> yalniz dosyaya ozgu ceza davasi -> kesin hukmun TBMM'ye bildirimi.
-- Anayasa 83,84,85,96 ve TBMM Ictuzuk 131-138. Tum eski oyun verileri korunur.
create table if not exists oyun.mv_fezleke (
 id bigint generated by default as identity primary key,
 hedef uuid not null references oyun.profiller(id),
 yazan uuid not null references oyun.profiller(id),
 suc text not null check(suc in ('hakaret','iftira','rusvet','yolsuzluk','usulsuzluk','dolandiricilik','diger')),
 baslik text not null, isnat text not null, deliller text not null, hukuki text not null,
 acilis timestamptz not null default now(),
 asama text not null default 'imza' check(asama in ('imza','hazirlik','karma','genel_kurul','itiraz','aym','yargilanabilir','dava','ret')),
 asama_bit timestamptz not null,
 savunma text, sonuc_gerekce text, meclis_at timestamptz,
 itiraz_eden uuid references oyun.profiller(id),
 itiraz_at timestamptz, itiraz_gerekce text,
 kesin_at timestamptz,
 dava_id bigint references oyun.adliye_davalar(id)
);
create unique index if not exists mv_fezleke_acik_tek on oyun.mv_fezleke(hedef)
 where asama in ('imza','hazirlik','karma','genel_kurul','itiraz','aym');
create index if not exists mv_fezleke_sure on oyun.mv_fezleke(asama,asama_bit);
create index if not exists mv_fezleke_dava on oyun.mv_fezleke(dava_id) where dava_id is not null;
create table if not exists oyun.mv_fezleke_imza(
 fezleke_id bigint not null references oyun.mv_fezleke(id), uye uuid not null references oyun.profiller(id),
 zaman timestamptz not null default now(), primary key(fezleke_id,uye)
);
create table if not exists oyun.mv_fezleke_komisyon(
 fezleke_id bigint not null references oyun.mv_fezleke(id),
 evre text not null check(evre in ('hazirlik','karma')),
 uye uuid not null references oyun.profiller(id),
 oy text check(oy in ('kabul','ret')),
 zaman timestamptz, primary key(fezleke_id,evre,uye)
);
create table if not exists oyun.mv_fezleke_meclis_oy(
 fezleke_id bigint not null references oyun.mv_fezleke(id),
 vekil uuid not null references oyun.profiller(id),
 oy text not null check(oy in ('kabul','ret','cekimser')),
 zaman timestamptz not null default now(), primary key(fezleke_id,vekil)
);
create table if not exists oyun.mv_fezleke_aym_oy(
 fezleke_id bigint not null references oyun.mv_fezleke(id),
 uye uuid not null references oyun.profiller(id),
 oy text not null check(oy in ('onay','iptal')),
 gerekce text not null, zaman timestamptz not null default now(),
 primary key(fezleke_id,uye)
);
create table if not exists oyun.mv_uyelik_bildirim(
 id bigint generated by default as identity primary key,
 fezleke_id bigint not null unique references oyun.mv_fezleke(id),
 dava_id bigint not null unique references oyun.adliye_davalar(id),
 hedef uuid not null references oyun.profiller(id),
 acilis timestamptz not null default now(),
 teblig_at timestamptz, teblig_eden uuid references oyun.profiller(id)
);
alter table oyun.mv_fezleke enable row level security;
alter table oyun.mv_fezleke_imza enable row level security;
alter table oyun.mv_fezleke_komisyon enable row level security;
alter table oyun.mv_fezleke_meclis_oy enable row level security;
alter table oyun.mv_fezleke_aym_oy enable row level security;
alter table oyun.mv_uyelik_bildirim enable row level security;
revoke all on oyun.mv_fezleke,oyun.mv_fezleke_imza,oyun.mv_fezleke_komisyon,
 oyun.mv_fezleke_meclis_oy,oyun.mv_fezleke_aym_oy,oyun.mv_uyelik_bildirim from public,anon,authenticated;
grant select,insert,update on oyun.mv_fezleke,oyun.mv_fezleke_imza,oyun.mv_fezleke_komisyon,
 oyun.mv_fezleke_meclis_oy,oyun.mv_fezleke_aym_oy,oyun.mv_uyelik_bildirim to service_role;

-- Hicbir ceza mahkemesi henuz milletvekilinin gorevini tek basina bitiremez.
-- Kesin mahkeme karari ayri bir TBMM bildirimi olarak kaydedilir.
create or replace function oyun.mv_yargi_makam_koruma()
returns trigger language plpgsql set search_path='' as $f$
begin
 if old.bit is null and new.bit is not null
    and old.tur in ('mv','tbmm','bskv','grup_bskv')
    and coalesce(new.bitis_neden,'') ~ '^Adliye #[0-9]+ karari$'
 then
  return old;
 end if;
 return new;
end; $f$;
drop trigger if exists mv_yargi_makam_koruma on oyun.makamlar;
create trigger mv_yargi_makam_koruma before update of bit on oyun.makamlar
for each row execute function oyun.mv_yargi_makam_koruma();

-- Bir ceza davasi dogrudan public RPC veya baska bir insert yoluyla acilamaz.
-- Yalniz dokunulmazligi o dosya icin kaldirilmis fezleke, mahkeme surecine baglanabilir.
create or replace function oyun.mv_ceza_dava_kapi()
returns trigger language plpgsql set search_path='' as $f$
declare f_id bigint; v text;
begin
 if new.davali is null or new.tur='tazminat' or not exists
  (select 1 from oyun.makamlar where tur='mv' and user_id=new.davali and bit is null)
 then return new; end if;
 v:=nullif(current_setting('oyun.mv_fezleke_dava_izin',true),'');
 if v is null or v !~ '^[0-9]+$' then
  raise exception 'Milletvekiline ceza davasi acilamaz: oncelikle fezleke ve TBMM dokunulmazlik karari gereklidir.';
 end if;
 f_id:=v::bigint;
 if not exists(select 1 from oyun.mv_fezleke f
   where f.id=f_id and f.hedef=new.davali and f.suc=new.tur
     and f.asama='yargilanabilir' and f.dava_id is null and f.kesin_at is not null)
 then raise exception 'Bu suclama icin kesinlesmis dokunulmazlik kaldirma karari bulunmuyor.'; end if;
 return new;
end; $f$;
drop trigger if exists mv_ceza_dava_kapi on oyun.adliye_davalar;
create trigger mv_ceza_dava_kapi before insert on oyun.adliye_davalar
for each row execute function oyun.mv_ceza_dava_kapi();

-- Mahkeme zamanlayicisi yetkilendirilmis dosyayi dokunulmazlik nedeniyle
-- dusurmesin; bu istisna farkli/sonradan acilacak davalara sirayet etmez.
create or replace function oyun.dokunulmazlik_engel(u uuid,p_tur text)
returns text language sql stable set search_path='' as $f$
select case
 when u is null or p_tur='tazminat' then null
 when exists(select 1 from oyun.makamlar m where m.user_id=u and m.tur='cb' and m.bit is null)
 then 'Cumhurbaskani hakkinda gorevdeyken olağan ceza davasi acilamaz (Anayasa 105).'
 when exists(select 1 from oyun.makamlar m where m.user_id=u and m.tur='mv' and m.bit is null)
  and not exists(select 1 from oyun.mv_fezleke f join oyun.adliye_davalar d on d.id=f.dava_id
   where f.hedef=u and d.davali=u and d.tur=p_tur and d.durum='acik'
    and f.asama='dava' and f.kesin_at is not null)
 then 'Milletvekili dokunulmazligi: fezleke, komisyonlar ve TBMM karari kesinlesmeden ceza davasi gorulemez (Anayasa 83). Tazminat davasi acilabilir.'
end
$f$;

-- Fezleke evreleri: asla zaman dolunca otomatik kabul olmaz.
create or replace function oyun.mvf_ilerlet(p_id bigint)
returns void language plpgsql security definer set search_path='' as $f$
declare f oyun.mv_fezleke; t timestamptz:=oyun.simdi(); evre text;
 say int; olum int; kat int; olum_meclis int; aym_onay int; aym_iptal int;
begin
 select * into f from oyun.mv_fezleke where id=p_id for update;
 if f.id is null then return; end if;
 if f.asama='imza' then
  select count(*) into say from oyun.mv_fezleke_imza where fezleke_id=p_id;
  if say>=2 and t<=f.asama_bit then
   if (select count(*) from oyun.makamlar where tur='mv' and bit is null and user_id<>f.hedef)<7 then
    update oyun.mv_fezleke set asama='ret',sonuc_gerekce='5 uyeli hazirlik ve 7 uyeli karma komisyon icin yeterli milletvekili yok.' where id=p_id;
    return;
   end if;
   insert into oyun.mv_fezleke_komisyon(fezleke_id,evre,uye)
    select p_id,'hazirlik',x.user_id from (select distinct m.user_id from oyun.makamlar m
      where m.tur='mv' and m.bit is null and m.user_id<>f.hedef order by m.user_id) x
    order by random() limit 5;
   update oyun.mv_fezleke set asama='hazirlik',asama_bit=t+interval '72 hours' where id=p_id;
   perform oyun.bildir(f.hedef,format('Milletvekili fezlekesi #%s: Hazirlik Komisyonu incelemesinde. Savunma hakkiniz vardir.',p_id),t);
  elsif t>f.asama_bit then
   update oyun.mv_fezleke set asama='ret',sonuc_gerekce='Yuksek Mahkeme iki bagimsiz imzayi suresinde tamamlamadi.' where id=p_id;
  end if;
 elsif f.asama in ('hazirlik','karma') then
  evre:=f.asama;
  select count(*) filter(where oy='kabul'),count(*) filter(where oy is not null)
  into olum,kat from oyun.mv_fezleke_komisyon where fezleke_id=p_id and evre=f.asama;
  if olum>=case when f.asama='hazirlik' then 3 else 4 end and t<=f.asama_bit then
   if f.asama='hazirlik' then
    insert into oyun.mv_fezleke_komisyon(fezleke_id,evre,uye)
     select p_id,'karma',x.user_id from (select distinct m.user_id from oyun.makamlar m
       where m.tur='mv' and m.bit is null and m.user_id<>f.hedef order by m.user_id) x
     order by random() limit 7;
    if (select count(*) from oyun.mv_fezleke_komisyon where fezleke_id=p_id and evre='karma')<>7 then
     update oyun.mv_fezleke set asama='ret',sonuc_gerekce='Karma Komisyonda yedi mevcut milletvekili yok.' where id=p_id;
    else update oyun.mv_fezleke set asama='karma',asama_bit=t+interval '72 hours' where id=p_id; end if;
   else
    update oyun.mv_fezleke set asama='genel_kurul',asama_bit=t+interval '72 hours',meclis_at=t where id=p_id;
    perform oyun.olay('adliye',format('Fezleke #%s: Karma Komisyon raporunu kabul etti. TBMM dokunulmazlik oylamasi basladi.',p_id),null,null,t);
   end if;
  elsif t>f.asama_bit or kat>=case when f.asama='hazirlik' then 5 else 7 end then
   update oyun.mv_fezleke set asama='ret',sonuc_gerekce='Komisyon olumlu rapor cikarmadi.' where id=p_id;
  end if;
 elsif f.asama='genel_kurul' and t>=f.asama_bit then
  select count(*),count(*) filter(where oy='kabul') into kat,olum_meclis
    from oyun.mv_fezleke_meclis_oy where fezleke_id=p_id;
  if kat>=greatest(200,ceil(oyun.tbmm_tamsayi()/3.0)::int)
   and olum_meclis>=greatest(151,floor(oyun.tbmm_tamsayi()/4.0)::int+1)
   and olum_meclis>kat/2.0 then
   update oyun.mv_fezleke set asama='itiraz',asama_bit=t+interval '7 days'
    where id=p_id;
   perform oyun.bildir(f.hedef,format('TBMM fezleke #%s icin dokunulmazligi kaldirdi. Anayasa Mahkemesine 7 gun icinde itiraz edilebilir; bu surede karar kesinlesmez.',p_id),t);
  else
   update oyun.mv_fezleke set asama='ret',sonuc_gerekce=format('TBMM nisabi veya kabul esigi saglanmadi: katilim %s, kabul %s; gerekli en az 200 katilim ve 151 kabul.',kat,olum_meclis) where id=p_id;
  end if;
 elsif f.asama='itiraz' and t>=f.asama_bit then
  update oyun.mv_fezleke set asama='yargilanabilir',kesin_at=t,sonuc_gerekce='TBMM karari kesinlesti, yedi gunluk iptal basvurusu suresi doldu.' where id=p_id;
 elsif f.asama='aym' then
  select count(*) filter(where oy='onay'),count(*) filter(where oy='iptal')
    into aym_onay,aym_iptal from oyun.mv_fezleke_aym_oy where fezleke_id=p_id;
  if aym_iptal>=2 then
   update oyun.mv_fezleke set asama='ret',sonuc_gerekce='Anayasa Mahkemesi TBMM kararini iptal etti.' where id=p_id;
  elsif aym_onay>=2 then
   update oyun.mv_fezleke set asama='yargilanabilir',kesin_at=t,sonuc_gerekce='Anayasa Mahkemesi TBMM kararini uygun buldu.' where id=p_id;
  elsif t>=f.asama_bit then
   update oyun.mv_fezleke set asama='ret',sonuc_gerekce='Anayasa Mahkemesinde tarafsiz iki onay cikmadi; milletvekili korunur.' where id=p_id;
  end if;
 end if;
end; $f$;
revoke all on function oyun.mvf_ilerlet(bigint) from public,anon,authenticated;

create or replace function oyun.mvf_tick()
returns integer language plpgsql security definer set search_path='' as $f$
declare r record; n int:=0;
begin
 if not pg_try_advisory_xact_lock(958101) then return 0; end if;
 for r in select id from oyun.mv_fezleke
  where asama in ('imza','hazirlik','karma','genel_kurul','itiraz','aym')
   and asama_bit<=oyun.simdi() order by asama_bit limit 30 loop
  perform oyun.mvf_ilerlet(r.id); n:=n+1;
 end loop;
 return n;
end; $f$;
revoke all on function oyun.mvf_tick() from public,anon,authenticated;

create or replace function public.mv_fezleke_yaz(
 p_hedef text,p_suc text,p_baslik text,p_isnat text,p_deliller text,p_hukuki text)
returns jsonb language plpgsql security definer set search_path='' as $f$
declare u uuid:=auth.uid(); v_hedef uuid; yeni bigint; t timestamptz:=oyun.simdi();
begin
 if u is null or not oyun.mahkeme_uyesi_mi(u) then raise exception 'Yalniz gorevdeki Yuksek Mahkeme uyesi fezleke hazirlayabilir.';end if;
 select id into v_hedef from oyun.profiller where lower(kad)=lower(btrim(p_hedef)) and not yasakli;
 if v_hedef is null or not exists(select 1 from oyun.makamlar where tur='mv' and user_id=v_hedef and bit is null)
 then raise exception 'Aktif milletvekili bulunamadi.';end if;
 if v_hedef=u then raise exception 'Kendi hakkinizda fezleke duzenleyemezsiniz.';end if;
 if p_suc not in ('hakaret','iftira','rusvet','yolsuzluk','usulsuzluk','dolandiricilik','diger')
  or length(btrim(coalesce(p_baslik,''))) not between 15 and 160
  or length(btrim(coalesce(p_isnat,''))) not between 120 and 5000
  or length(btrim(coalesce(p_deliller,''))) not between 60 and 4000
  or length(btrim(coalesce(p_hukuki,''))) not between 60 and 3000
 then raise exception 'Suc turu, 15-160 baslik, 120-5000 isnat, 60-4000 delil ve 60-3000 hukuki gerekce zorunludur.';end if;
 if lower(p_isnat) ~ '(mecliste kullandigi oy|meclisteki oyu|yasama konusmasi)' then
  raise exception 'Yasama sorumsuzlugu kapsamindaki Meclis oyu veya konusmasi ceza fezlekesine konu edilemez.';end if;
 perform oyun.mvf_tick();
 if exists(select 1 from oyun.mv_fezleke where hedef=v_hedef and asama in ('imza','hazirlik','karma','genel_kurul','itiraz','aym')) then
  raise exception 'Bu milletvekili hakkinda halen acik fezleke vardir.';end if;
 if exists(select 1 from oyun.mv_fezleke where hedef=v_hedef and suc=p_suc and acilis>t-interval '7 days') then
  raise exception 'Ayni hedef ve isnat turu icin 7 gun yeni fezleke acilamaz.';end if;
 insert into oyun.mv_fezleke(hedef,yazan,suc,baslik,isnat,deliller,hukuki,asama_bit)
  values(v_hedef,u,p_suc,btrim(p_baslik),btrim(p_isnat),btrim(p_deliller),btrim(p_hukuki),t+interval '72 hours')
  returning id into yeni;
 insert into oyun.mv_fezleke_imza(fezleke_id,uye) values(yeni,u);
 perform oyun.bildir(v_hedef,format('Yuksek Mahkeme fezleke #%s hakkinda imza sureci basladi. Bu bir mahkumiyet veya gozaltisi degildir.',yeni),t);
 return jsonb_build_object('id',yeni,'asama','imza');
end; $f$;

create or replace function public.mv_fezleke_imzala(p_id bigint)
returns jsonb language plpgsql security definer set search_path='' as $f$
declare f oyun.mv_fezleke; u uuid:=auth.uid();
begin
 if u is null or not oyun.mahkeme_uyesi_mi(u) then raise exception 'Yalniz Yuksek Mahkeme uyesi imza atabilir.';end if;
 select * into f from oyun.mv_fezleke where id=p_id for update;
 if f.id is null or f.asama<>'imza' or f.asama_bit<=oyun.simdi() then raise exception 'Imza asamasi kapandi.';end if;
 if u=f.hedef or exists(select 1 from oyun.mv_fezleke_imza where fezleke_id=p_id and uye=u)
 then raise exception 'Bu dosyayi imzalamaya yetkiniz yok veya zaten imzaladiniz.';end if;
 insert into oyun.mv_fezleke_imza values(p_id,u,oyun.simdi());
 perform oyun.mvf_ilerlet(p_id);
 return jsonb_build_object('tamam',true);
end; $f$;

create or replace function public.mv_fezleke_savun(p_id bigint,p_metin text)
returns jsonb language plpgsql security definer set search_path='' as $f$
declare f oyun.mv_fezleke; u uuid:=auth.uid();
begin
 select * into f from oyun.mv_fezleke where id=p_id for update;
 if f.id is null or f.hedef is distinct from u or f.asama not in ('hazirlik','karma','genel_kurul','itiraz','aym')
 then raise exception 'Savunma bu dosyada ilgili milletvekiline aittir.';end if;
 if length(btrim(coalesce(p_metin,''))) not between 30 and 5000 then raise exception 'Savunma 30-5000 karakter olmalidir.';end if;
 update oyun.mv_fezleke set savunma=btrim(p_metin) where id=p_id;
 return jsonb_build_object('tamam',true);
end; $f$;

create or replace function public.mv_fezleke_komisyon_oy(p_id bigint,p_oy text)
returns jsonb language plpgsql security definer set search_path='' as $f$
declare f oyun.mv_fezleke; u uuid:=auth.uid();
begin
 select * into f from oyun.mv_fezleke where id=p_id for update;
 if f.id is null or f.asama not in ('hazirlik','karma') or f.asama_bit<=oyun.simdi()
 then raise exception 'Komisyon oylamasi kapali.';end if;
 if p_oy not in ('kabul','ret') then raise exception 'Kabul veya ret seciniz.';end if;
 update oyun.mv_fezleke_komisyon set oy=p_oy,zaman=oyun.simdi()
  where fezleke_id=p_id and evre=f.asama and uye=u and oy is null;
 if not found then raise exception 'Bu komisyona atanmamissiniz veya oyunuzu kullandiniz.';end if;
 perform oyun.mvf_ilerlet(p_id);
 return jsonb_build_object('tamam',true);
end; $f$;

create or replace function public.mv_fezleke_meclis_oy(p_id bigint,p_oy text)
returns jsonb language plpgsql security definer set search_path='' as $f$
declare f oyun.mv_fezleke; u uuid:=auth.uid();
begin
 select * into f from oyun.mv_fezleke where id=p_id for update;
 if f.id is null or f.asama<>'genel_kurul' or f.asama_bit<=oyun.simdi() then raise exception 'Meclis oylamasi kapali.';end if;
 if u=f.hedef or not oyun.ymf_vekil_mi(u) then raise exception 'Yalniz tarafsiz aktif milletvekilleri oy verebilir.';end if;
 if p_oy not in ('kabul','ret','cekimser') then raise exception 'Gecersiz oy.';end if;
 insert into oyun.mv_fezleke_meclis_oy(fezleke_id,vekil,oy) values(p_id,u,p_oy)
 on conflict(fezleke_id,vekil) do nothing;
 if not found then raise exception 'Bu dosyada daha once oy kullandiniz.';end if;
 return jsonb_build_object('tamam',true,'gizli_oy',true);
end; $f$;

create or replace function public.mv_fezleke_itiraz(p_id bigint,p_gerekce text)
returns jsonb language plpgsql security definer set search_path='' as $f$
declare f oyun.mv_fezleke; u uuid:=auth.uid();
begin
 select * into f from oyun.mv_fezleke where id=p_id for update;
 if f.id is null or f.asama<>'itiraz' or f.asama_bit<=oyun.simdi()
 then raise exception '7 gunluk Anayasa Mahkemesi itiraz suresi doldu.';end if;
 if u is null or not oyun.ymf_vekil_mi(u) then raise exception 'Anayasa 85: Yalniz bir milletvekili itiraz edebilir.';end if;
 if length(btrim(coalesce(p_gerekce,''))) not between 50 and 3000 then raise exception 'Hukuki itiraz gerekcesi 50-3000 karakter olmalidir.';end if;
 update oyun.mv_fezleke set asama='aym',asama_bit=oyun.simdi()+interval '15 days',
  itiraz_eden=u,itiraz_at=oyun.simdi(),itiraz_gerekce=btrim(p_gerekce) where id=p_id;
 return jsonb_build_object('tamam',true,'asama','aym');
end; $f$;

create or replace function public.mv_fezleke_aym_oy(p_id bigint,p_oy text,p_gerekce text)
returns jsonb language plpgsql security definer set search_path='' as $f$
declare f oyun.mv_fezleke; u uuid:=auth.uid();
begin
 select * into f from oyun.mv_fezleke where id=p_id for update;
 if f.id is null or f.asama<>'aym' or f.asama_bit<=oyun.simdi() then raise exception 'Anayasa Mahkemesi incelemesi kapali.';end if;
 if u is null or u=f.yazan or u=f.hedef or not oyun.mahkeme_uyesi_mi(u)
 then raise exception 'Fezlekeyi yazan veya ilgili hakim bu itirazda oy kullanamaz.';end if;
 if p_oy not in ('onay','iptal') or length(btrim(coalesce(p_gerekce,''))) not between 50 and 3000
 then raise exception 'Karar ve 50-3000 karakter bagimsiz hukuki gerekce gerekli.';end if;
 insert into oyun.mv_fezleke_aym_oy values(p_id,u,p_oy,btrim(p_gerekce),oyun.simdi())
 on conflict(fezleke_id,uye) do nothing;
 if not found then raise exception 'AYM oyunuzu zaten verdiniz.';end if;
 perform oyun.mvf_ilerlet(p_id);
 return jsonb_build_object('tamam',true);
end; $f$;

create or replace function public.mv_fezleke_dava_ac(p_id bigint)
returns jsonb language plpgsql security definer set search_path='' as $f$
declare f oyun.mv_fezleke; u uuid:=auth.uid(); yeni bigint; t timestamptz:=oyun.simdi(); saat int;
begin
 if u is null or not oyun.mahkeme_uyesi_mi(u) then raise exception 'Ceza dosyasini yalniz Yuksek Mahkeme isleme alabilir.';end if;
 select * into f from oyun.mv_fezleke where id=p_id for update;
 if f.id is null or f.asama<>'yargilanabilir' or f.kesin_at is null or f.dava_id is not null
 then raise exception 'Kesinlesmis, henuz dava acilmamis dokunulmazlik karari gerekli.';end if;
 if u=f.yazan or u=f.hedef then raise exception 'Cikar catismasi: fezlekeyi yazan hakim dosyayi yargiya sevk edemez.';end if;
 if not exists(select 1 from oyun.makamlar where tur='mv' and user_id=f.hedef and bit is null)
 then raise exception 'Milletvekilligi sona ermis; bu ozel dosya yolu kullanilamaz.';end if;
 saat:=coalesce((select avukat_savunma_saat from oyun.ayarlar where id=1),24);
 perform set_config('oyun.mv_fezleke_dava_izin',p_id::text,true);
 insert into oyun.adliye_davalar(davaci,davali,tur,iddia,delil,acilis,savunma_son,karar_son,harc,kesin)
 values(u,f.hedef,f.suc,f.isnat,f.deliller,t,t+make_interval(hours=>saat),
  t+make_interval(hours=>saat)+make_interval(hours=>coalesce((select karar_saat from oyun.mahkeme_ayar),24)),0,false)
 returning id into yeni;
 perform set_config('oyun.mv_fezleke_dava_izin','',true);
 update oyun.mv_fezleke set asama='dava',dava_id=yeni where id=p_id;
 perform oyun.bildir(f.hedef,format('Fezleke #%s: TBMM dokunulmazligi bu dosya icin kaldirdi. Adliye #%s ceza davasi acildi; savunma ve istinaf hakkiniz vardir. Vekilliginiz devam ediyor.',p_id,yeni),t);
 return jsonb_build_object('tamam',true,'dava_id',yeni);
end; $f$;

create or replace function oyun.mv_uyelik_kesin_bildir()
returns trigger language plpgsql security definer set search_path='' as $f$
declare f_id bigint;
begin
 if new.kesin is true and old.kesin is distinct from true
  and new.karar='vekillik_dusur' and new.davali is not null then
  select id into f_id from oyun.mv_fezleke where dava_id=new.id and hedef=new.davali and asama='dava';
  if f_id is not null then
   insert into oyun.mv_uyelik_bildirim(fezleke_id,dava_id,hedef) values(f_id,new.id,new.davali)
    on conflict(dava_id) do nothing;
   perform oyun.bildir(new.davali,format('Kesin mahkeme karari TBMM ye bildirilmek uzere kaydedildi (Adliye #%s). Henüz vekilliginiz sona ermedi.',new.id),oyun.simdi());
  end if;
 end if;
 return new;
end; $f$;
drop trigger if exists mv_uyelik_kesin_bildir on oyun.adliye_davalar;
create trigger mv_uyelik_kesin_bildir after update of kesin on oyun.adliye_davalar
for each row execute function oyun.mv_uyelik_kesin_bildir();

create or replace function public.mv_uyelik_teblig(p_id bigint)
returns jsonb language plpgsql security definer set search_path='' as $f$
declare u uuid:=auth.uid(); b oyun.mv_uyelik_bildirim; t timestamptz:=oyun.simdi();
begin
 if u is null or not exists(select 1 from oyun.makamlar where user_id=u and tur='tbmm' and bit is null)
 then raise exception 'Kesinlesmis yargi kararini Genel Kurula TBMM Baskani teblig eder.';end if;
 select * into b from oyun.mv_uyelik_bildirim where id=p_id for update;
 if b.id is null or b.teblig_at is not null then raise exception 'Teblig edilecek aktif bildirim yok.';end if;
 if not exists(select 1 from oyun.adliye_davalar d where id=b.dava_id and kesin=true and karar='vekillik_dusur' and davali=b.hedef)
 then raise exception 'Kesin ve uygun mahkeme karari yok.';end if;
 update oyun.makamlar set bit=t,bitis_neden='Kesin hukmun TBMM Genel Kuruluna bildirimi: Adliye #'||b.dava_id
 where user_id=b.hedef and bit is null and tur in ('mv','tbmm','bskv','grup_bskv');
 update oyun.mv_uyelik_bildirim set teblig_at=t,teblig_eden=u where id=b.id;
 perform oyun.bildir(b.hedef,format('Kesin mahkeme karari #%s TBMM Genel Kuruluna bildirildi; milletvekilliginiz bu tarihte sona erdi.',b.dava_id),t);
 perform oyun.olay('adliye',format('TBMM, #%s kesin mahkeme kararinin Genel Kurula bildirilmesiyle milletvekilligi uyeliginin sona erdigini duyurdu.',b.dava_id),null,null,t);
 return jsonb_build_object('tamam',true,'uyelik_dustu',true);
end; $f$;

create or replace function public.mv_fezleke_panel()
returns jsonb language plpgsql security definer set search_path='' as $f$
declare u uuid:=auth.uid(); hakim boolean; vekil boolean; baskan boolean;
begin
 if u is null then raise exception 'Giris gerekli';end if;
 perform oyun.mvf_tick();
 hakim:=oyun.mahkeme_uyesi_mi(u); vekil:=oyun.ymf_vekil_mi(u);
 baskan:=exists(select 1 from oyun.makamlar where user_id=u and tur='tbmm' and bit is null);
 return jsonb_build_object(
 'hakim',hakim,'vekil',vekil,'baskan',baskan,'tamsayi',oyun.tbmm_tamsayi(),
 'toplanti_esigi',greatest(200,ceil(oyun.tbmm_tamsayi()/3.0)::int),
 'kabul_alt_esigi',greatest(151,floor(oyun.tbmm_tamsayi()/4.0)::int+1),
 'dosyalar',coalesce((select jsonb_agg(jsonb_build_object(
  'id',f.id,'hedef',oyun.kad(f.hedef),'yazan',oyun.kad(f.yazan),
  'suc',f.suc,'baslik',f.baslik,'isnat',f.isnat,
  'deliller',case when hakim or vekil or f.hedef=u then f.deliller else '' end,
  'hukuki',f.hukuki,'savunma',f.savunma,'asama',f.asama,
  'bitis',f.asama_bit,'sonuc_gerekce',f.sonuc_gerekce,'dava_id',f.dava_id,
  'meclis_at',f.meclis_at,'kesin_at',f.kesin_at,
  'itiraz_gerekce',f.itiraz_gerekce,
  'imza_sayi',(select count(*) from oyun.mv_fezleke_imza i where i.fezleke_id=f.id),
  'komisyon_oyum',(select z.oy from oyun.mv_fezleke_komisyon z where z.fezleke_id=f.id and z.evre=f.asama and z.uye=u),
  'komisyon_uyesi',exists(select 1 from oyun.mv_fezleke_komisyon z where z.fezleke_id=f.id and z.evre=f.asama and z.uye=u),
  'komisyon_kabul',(select count(*) from oyun.mv_fezleke_komisyon z where z.fezleke_id=f.id and z.evre=f.asama and z.oy='kabul'),
  'oyum',(select o.oy from oyun.mv_fezleke_meclis_oy o where o.fezleke_id=f.id and o.vekil=u),
  'katilim',(select count(*) from oyun.mv_fezleke_meclis_oy o where o.fezleke_id=f.id),
  'kabul',case when f.asama<>'genel_kurul' then (select count(*) from oyun.mv_fezleke_meclis_oy o where o.fezleke_id=f.id and o.oy='kabul') else null end,
  'aym_oyum',(select y.oy from oyun.mv_fezleke_aym_oy y where y.fezleke_id=f.id and y.uye=u),
  'imzaladim',exists(select 1 from oyun.mv_fezleke_imza i where i.fezleke_id=f.id and i.uye=u),
  'benim',f.hedef=u,'yazan_benim',f.yazan=u
 ) order by f.id desc) from
 (select * from oyun.mv_fezleke where asama not in ('imza','hazirlik','karma')
  or hedef=u or yazan=u or hakim or exists
   (select 1 from oyun.mv_fezleke_komisyon x where x.fezleke_id=mv_fezleke.id and x.uye=u)
  order by id desc limit 45) f),'[]'::jsonb),
 'bildirimler',case when baskan then coalesce((select jsonb_agg(jsonb_build_object(
  'id',b.id,'dava_id',b.dava_id,'hedef',oyun.kad(b.hedef),'teblig_at',b.teblig_at
 ) order by b.id desc) from (select * from oyun.mv_uyelik_bildirim order by id desc limit 25)b),'[]'::jsonb) else '[]'::jsonb end
 );
end; $f$;

do $f$
declare p record;
begin
 for p in select oid,proname,pg_get_function_identity_arguments(oid) args from pg_proc
  where pronamespace='public'::regnamespace and proname in
   ('mv_fezleke_yaz','mv_fezleke_imzala','mv_fezleke_savun','mv_fezleke_komisyon_oy',
    'mv_fezleke_meclis_oy','mv_fezleke_itiraz','mv_fezleke_aym_oy',
    'mv_fezleke_dava_ac','mv_fezleke_panel','mv_uyelik_teblig')
 loop
  execute format('revoke all on function %s from public,anon,authenticated',p.oid::regprocedure);
  execute format('grant execute on function %s to authenticated,service_role',p.oid::regprocedure);
 end loop;
end; $f$;
