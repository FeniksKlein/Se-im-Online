create or replace function public.ilan_ver(p_veri jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  p oyun.profiller := oyun.profilim(); v_t timestamptz := oyun.simdi();
  v_varlik text := p_veri->>'varlik'; v_id bigint := nullif(p_veri->>'id', '')::bigint;
  v_pay numeric := nullif(p_veri->>'pay', '')::numeric;
  v_baslik text := btrim(regexp_replace(coalesce(p_veri->>'baslik', ''), '\s+', ' ', 'g'));
  v_aciklama text := nullif(btrim(regexp_replace(coalesce(p_veri->>'aciklama', ''), '[\r\n]{3,}', E'\n\n', 'g')), '');
  v_fiyat numeric := nullif(p_veri->>'fiyat', '')::numeric;
  v_pazarlik boolean := coalesce((p_veri->>'pazarlik')::boolean, true);
  v_mali boolean := coalesce((p_veri->>'mali_goster')::boolean, false);
  v_paketler text[]; v_kategori text; v_il smallint; v_sektor text; v_bant record;
  tp oyun.yatirim_pazar_tapu; bo oyun.eko_bolumler; s oyun.sirketler; v_sahip_pay numeric;
  v_ucret numeric := 0; v_kod text; v_ilan bigint; a oyun.ilan_ayar;
begin
  select coalesce(array_agg(distinct e), array[]::text[]) into v_paketler
    from jsonb_array_elements_text(case when jsonb_typeof(p_veri->'paketler') = 'array' then p_veri->'paketler' else '[]'::jsonb end) e
   where e in ('vitrin','ust_sira','acil','renkli');
  if v_varlik is null or v_varlik not in ('tapu','bolum','sirket','hisse') or v_id is null then raise exception 'İlana çıkarılacak varlığı seç.'; end if;
  if char_length(v_baslik) < 5 or char_length(v_baslik) > 70 then raise exception 'İlan başlığı 5 ile 70 karakter arasında olmalı.'; end if;
  if v_aciklama is not null and char_length(v_aciklama) > 1200 then raise exception 'Açıklama en fazla 1.200 karakter olabilir.'; end if;
  if oyun.kufurlu(v_baslik) or (v_aciklama is not null and oyun.kufurlu(v_aciklama)) then
    raise exception 'İlan metninde uygunsuz bir ifade var. Hakaret ve küfür yasaktır.'; end if;
  if v_fiyat is null or v_fiyat <> round(v_fiyat) or v_fiyat < 1000 or v_fiyat > 1000000000 then
    raise exception 'Fiyat 1.000 ₺ ile 1 milyar ₺ arasında, kuruşsuz olmalı.'; end if;
  if (select count(*) from oyun.ilanlar i where i.satici = p.id and i.durum = 'yayinda') >= 10 then
    raise exception 'Aynı anda en fazla 10 ilanın yayında olabilir. Önce bir ilanını kaldır.'; end if;
  perform pg_advisory_xact_lock(99511, hashtext(v_varlik || ':' || v_id::text));

  if v_varlik = 'tapu' then
    select * into tp from oyun.yatirim_pazar_tapu where id = v_id for update;
    if tp.id is null or tp.sahip <> p.id then raise exception 'Bu tapu sana ait değil.'; end if;
    if exists (select 1 from oyun.yatirim_pazar_ilan yi where yi.kaynak = 'yatirim' and yi.ref_id = tp.id and yi.durum = 'acik') then
      raise exception 'Bu tapu Yatırım Pazarı’nda zaten satılık. Önce oradaki ilanı kaldır.'; end if;
    v_kategori := case tp.tip when 'daire' then 'konut' when 'dukkan' then 'isyeri' else 'arsa' end; v_il := tp.il_id; v_pay := null;
  elsif v_varlik = 'bolum' then
    select * into bo from oyun.eko_bolumler where id = v_id for update;
    if bo.id is null or bo.sahibi is distinct from p.id then raise exception 'Bu konut ya da dükkân sana ait değil.'; end if;
    if exists (select 1 from oyun.eko_subeler sb where sb.bolum_id = bo.id and sb.aktif) then
      raise exception 'Kiracısı olan dükkân satılığa çıkarılamaz.'; end if;
    if exists (select 1 from oyun.yatirim_pazar_ilan yi where yi.kaynak = 'proje' and yi.ref_id = bo.id and yi.durum = 'acik') then
      raise exception 'Bu taşınmaz Yatırım Pazarı’nda zaten satılık. Önce oradaki ilanı kaldır.'; end if;
    v_kategori := case bo.tur when 'daire' then 'konut' else 'isyeri' end;
    select y.il_id into v_il from oyun.eko_yapilar y where y.id = bo.yapi_id; v_pay := null;
  else
    if not oyun.uzaktan_modul_acik('sirket_pazari') then raise exception 'Şirket pazarı geçici olarak kapalı.'; end if;
    perform pg_advisory_xact_lock(98763, hashtext(v_id::text));
    select * into s from oyun.sirketler where id = v_id for update;
    if s.id is null or not s.aktif then raise exception 'Yalnız faal şirketler ilana çıkarılabilir.'; end if;
    if s.sektor = 'banka' then raise exception 'Bankalar İlan Meydanı’nda satılamaz; banka devri ayrı izin gerektirir.'; end if;
    select o.pay into v_sahip_pay from oyun.sirket_ortaklari o where o.sirket_id = s.id and o.user_id = p.id;
    if v_sahip_pay is null then raise exception 'Bu şirkette payın yok.'; end if;
    v_kategori := v_varlik; v_il := oyun.ilan_sirket_il(s.id); v_sektor := s.sektor;
    if v_varlik = 'sirket' then
      if v_sahip_pay <> 100 then raise exception 'Şirketin tamamını yalnız %%100 sahibi satabilir. Payını satmak için “Şirket hissesi” seç.'; end if;
      if exists (select 1 from oyun.ilanlar i where i.varlik = 'hisse' and i.varlik_id = s.id and i.durum = 'yayinda') then
        raise exception 'Bu şirketin hisse ilanı yayında. Önce onu kaldır.'; end if;
      if exists (select 1 from oyun.sirket_hisse_ilanlari h where h.sirket_id = s.id and h.durum = 'acik') then
        raise exception 'Bu şirketin eski hisse pazarında açık ilanı var. Önce onu kaldır.'; end if;
      v_pay := 100;
    else
      if v_pay is null or v_pay <= 0 or v_pay > 100 or v_pay <> round(v_pay, 2) then
        raise exception 'Satılacak pay 0,01 ile 100 arasında, en fazla 2 ondalıklı olmalı.'; end if;
      if v_sahip_pay = 100 and v_pay = 100 then raise exception 'Şirketin tamamını satmak için “Satılık şirket” kategorisini seç.'; end if;
      if exists (select 1 from oyun.ilanlar i where i.varlik = 'sirket' and i.varlik_id = s.id and i.durum = 'yayinda') then
        raise exception 'Bu şirketin tamamı için verdiğin ilan yayında. Önce onu kaldır.'; end if;
      if oyun.ilan_kullanilabilir_pay(s.id, p.id, null) < v_pay then
        raise exception 'Satabileceğin pay %. Borsadaki emirler ve diğer ilanlar düşüldü.', oyun.ilan_pay_yaz(oyun.ilan_kullanilabilir_pay(s.id, p.id, null)); end if;
    end if;
  end if;

  if exists (select 1 from oyun.ilanlar i where i.varlik = v_varlik and i.varlik_id = v_id and i.satici = p.id and i.durum = 'yayinda') then
    raise exception 'Bu varlık için zaten yayında bir ilanın var.'; end if;
  select * into v_bant from oyun.ilan_bant(v_varlik, v_id, v_pay);
  if v_fiyat < v_bant.alt or v_fiyat > v_bant.ust then
    raise exception 'Bu ilan için fiyat % ₺ ile % ₺ arasında olmalı.', oyun.tl(v_bant.alt), oyun.tl(v_bant.ust); end if;

  v_kod := case when v_varlik in ('tapu','bolum') then 'ilan_emlak' when v_varlik = 'hisse' then 'ilan_hisse' else 'ilan_sirket' end;
  select coalesce(sum(a2.tutar), 0) into v_ucret from oyun.ilan_ayar a2 where a2.kod = v_kod or a2.kod = any(v_paketler);
  if v_ucret > 0 then
    perform oyun.para_islem(p.id, -v_ucret, 'reklam',
      format('İlan Meydanı: “%s” ilan ücreti%s', v_baslik, case when cardinality(v_paketler) > 0 then ' ve öne çıkarma' else '' end), v_t);
    update oyun.ulke set hazine = hazine + v_ucret / oyun.pazar_tl_milyar() where id = 1;
  end if;

  insert into oyun.ilanlar(kategori, varlik, varlik_id, pay, satici, baslik, aciklama, fiyat, ilk_fiyat, pazarlik, mali_goster,
                           il_id, sektor, olusturma, siralama, bitis)
    values (v_kategori, v_varlik, v_id, v_pay, p.id, v_baslik, v_aciklama, v_fiyat, v_fiyat, v_pazarlik,
            v_mali and v_varlik in ('sirket','hisse'), v_il, v_sektor, v_t, v_t,
            v_t + make_interval(days => (select a3.gun from oyun.ilan_ayar a3 where a3.kod = v_kod)))
    returning id into v_ilan;
  for a in select * from oyun.ilan_ayar a4 where a4.kod = v_kod or a4.kod = any(v_paketler) loop
    insert into oyun.ilan_odeme(ilan_id, user_id, kod, tutar, zaman) values (v_ilan, p.id, a.kod, a.tutar, v_t);
    if a.kod = 'vitrin' then update oyun.ilanlar set vitrin_bitis = v_t + make_interval(days => a.gun) where id = v_ilan;
    elsif a.kod = 'ust_sira' then update oyun.ilanlar set ust_bitis = v_t + make_interval(days => a.gun) where id = v_ilan;
    elsif a.kod = 'acil' then update oyun.ilanlar set acil_bitis = v_t + make_interval(days => a.gun) where id = v_ilan;
    elsif a.kod = 'renkli' then update oyun.ilanlar set renkli_bitis = v_t + make_interval(days => a.gun) where id = v_ilan;
    end if;
  end loop;

  -- Şirketin tamamı: eski "satılık şirket" alanı da eşlenir (eski ekranlar aynı fiyatı görür)
  perform set_config('oyun.ilan_senkron', '1', true);
  if v_varlik = 'sirket' then
    update oyun.sirketler set satilik = v_fiyat where id = v_id;
  elsif v_varlik = 'hisse' then
    update oyun.sirketler set satilik = null where id = v_id and satilik is not null;
  end if;
  perform set_config('oyun.ilan_senkron', '', true);

  return jsonb_build_object('tamam', true, 'id', v_ilan, 'no', oyun.ilan_no(v_ilan), 'ucret', v_ucret);
end $$;

create or replace function public.ilan_duzenle(p_ilan bigint, p_veri jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare p oyun.profiller := oyun.profilim(); i oyun.ilanlar; v_bant record; v_fiyat numeric; v_baslik text; v_aciklama text;
begin
  select * into i from oyun.ilanlar where id = p_ilan for update;
  if i.id is null or i.satici <> p.id then raise exception 'Bu ilan sana ait değil.'; end if;
  if i.durum <> 'yayinda' then raise exception 'Yalnız yayındaki ilanlar düzenlenebilir.'; end if;
  if p_veri ? 'baslik' then
    v_baslik := btrim(regexp_replace(coalesce(p_veri->>'baslik', ''), '\s+', ' ', 'g'));
    if char_length(v_baslik) < 5 or char_length(v_baslik) > 70 then raise exception 'İlan başlığı 5 ile 70 karakter arasında olmalı.'; end if;
    if oyun.kufurlu(v_baslik) then raise exception 'İlan metninde uygunsuz bir ifade var.'; end if;
    update oyun.ilanlar set baslik = v_baslik where id = i.id;
  end if;
  if p_veri ? 'aciklama' then
    v_aciklama := nullif(btrim(regexp_replace(coalesce(p_veri->>'aciklama', ''), '[\r\n]{3,}', E'\n\n', 'g')), '');
    if v_aciklama is not null and (char_length(v_aciklama) > 1200 or oyun.kufurlu(v_aciklama)) then
      raise exception 'Açıklama en fazla 1.200 karakter olmalı ve uygunsuz ifade içermemeli.'; end if;
    update oyun.ilanlar set aciklama = v_aciklama where id = i.id;
  end if;
  if p_veri ? 'pazarlik' then update oyun.ilanlar set pazarlik = (p_veri->>'pazarlik')::boolean where id = i.id; end if;
  if p_veri ? 'mali_goster' and i.varlik in ('sirket','hisse') then
    update oyun.ilanlar set mali_goster = (p_veri->>'mali_goster')::boolean where id = i.id; end if;
  if p_veri ? 'fiyat' then
    v_fiyat := (p_veri->>'fiyat')::numeric;
    if v_fiyat is null or v_fiyat <> round(v_fiyat) or v_fiyat < 1000 or v_fiyat > 1000000000 then raise exception 'Geçerli bir fiyat yaz.'; end if;
    if v_fiyat <> i.fiyat then
      select * into v_bant from oyun.ilan_bant(i.varlik, i.varlik_id, i.pay);
      if v_fiyat < v_bant.alt or v_fiyat > v_bant.ust then
        raise exception 'Bu ilan için fiyat % ₺ ile % ₺ arasında olmalı.', oyun.tl(v_bant.alt), oyun.tl(v_bant.ust); end if;
      update oyun.ilanlar set onceki_fiyat = i.fiyat, fiyat = v_fiyat where id = i.id;
      if i.varlik = 'sirket' then
        perform set_config('oyun.ilan_senkron', '1', true);
        update oyun.sirketler set satilik = v_fiyat where id = i.varlik_id;
        perform set_config('oyun.ilan_senkron', '', true);
      end if;
    end if;
  end if;
