-- Şirketin il bilgisi: merkez kaydı, yoksa en büyük ortağın ili
create or replace function oyun.ilan_sirket_il(p_sirket bigint) returns smallint
language sql stable set search_path = '' as $$
  select coalesce(
    (select m.il_id from oyun.sirket_merkezleri m where m.sirket_id = p_sirket limit 1),
    (select p.il_id from oyun.profiller p where p.id = oyun.sirket_sahibi(p_sirket)))
$$;

-- Satıcının ilana çıkarabileceği pay (borsa emirleri, eski hisse ilanları ve diğer ilanları düşülür)
create or replace function oyun.ilan_kullanilabilir_pay(p_sirket bigint, p_user uuid, p_haric bigint default null)
returns numeric language plpgsql stable set search_path = '' as $$
declare v_pay numeric; v_borsa numeric := 0; v_eski numeric; v_ilan numeric;
begin
  select o.pay into v_pay from oyun.sirket_ortaklari o where o.sirket_id = p_sirket and o.user_id = p_user;
  if v_pay is null then return 0; end if;
  if to_regclass('oyun.borsa_emir') is not null then
    execute 'select coalesce(sum(kalan),0) from oyun.borsa_emir where sirket_id=$1 and satici=$2 and durum=''acik'''
      into v_borsa using p_sirket, p_user;
  end if;
  select coalesce(sum(h.pay), 0) into v_eski from oyun.sirket_hisse_ilanlari h
   where h.sirket_id = p_sirket and h.satici = p_user and h.durum = 'acik';
  select coalesce(sum(i.pay), 0) into v_ilan from oyun.ilanlar i
   where i.varlik = 'hisse' and i.varlik_id = p_sirket and i.satici = p_user and i.durum = 'yayinda'
     and i.id is distinct from p_haric;
  return greatest(0, v_pay - coalesce(v_borsa, 0) - v_eski - v_ilan);
end $$;

-- Fiyat bandı: emlakta il rayicinin %40–%400'ü; şirket ve hissede pay bandı (kasa ve sermayeye göre)
create or replace function oyun.ilan_bant(p_varlik text, p_id bigint, p_pay numeric,
  out alt numeric, out ust numeric, out rayic numeric)
language plpgsql stable set search_path = '' as $$
declare v_il smallint; v_tip text; v_b record; v_carpan numeric;
begin
  if p_varlik = 'tapu' then
    select tp.il_id, tp.tip into v_il, v_tip from oyun.yatirim_pazar_tapu tp where tp.id = p_id;
  elsif p_varlik = 'bolum' then
    select y.il_id, bo.tur into v_il, v_tip from oyun.eko_bolumler bo join oyun.eko_yapilar y on y.id = bo.yapi_id where bo.id = p_id;
  end if;
  if p_varlik in ('tapu','bolum') then
    rayic := oyun.yatirim_pazar_fiyat(v_il, v_tip);
    alt := round(rayic * 0.4); ust := round(rayic * 4);
  elsif oyun.bant_acik() then
    select * into v_b from oyun.pay_bandi(p_id);
    v_carpan := case when p_varlik = 'sirket' then 100 else coalesce(p_pay, 0) end;
    alt := round(coalesce(v_b.alt, 0) * v_carpan); ust := round(coalesce(v_b.ust, 0) * v_carpan);
  else
    alt := 1000; ust := 1000000000;
  end if;
  alt := greatest(1000, coalesce(alt, 1000));
  ust := least(1000000000, greatest(alt, coalesce(ust, 1000000000)));
end $$;

-- İlan hâlâ geçerli mi? (varlık satıcıda mı, satılabilir mi)
create or replace function oyun.ilan_gecerli(p_ilan bigint) returns boolean
language plpgsql stable set search_path = '' as $$
declare i oyun.ilanlar;
begin
  select * into i from oyun.ilanlar where id = p_ilan;
  if i.id is null then return false; end if;
  if exists (select 1 from oyun.profiller p where p.id = i.satici and p.yasakli
             and (p.engel_bitis is null or p.engel_bitis > oyun.simdi())) then return false; end if;
  if i.varlik = 'tapu' then
    return exists (select 1 from oyun.yatirim_pazar_tapu tp where tp.id = i.varlik_id and tp.sahip = i.satici);
  elsif i.varlik = 'bolum' then
    return exists (select 1 from oyun.eko_bolumler b where b.id = i.varlik_id and b.sahibi = i.satici)
       and not exists (select 1 from oyun.eko_subeler sb where sb.bolum_id = i.varlik_id and sb.aktif);
  elsif i.varlik = 'sirket' then
    return exists (select 1 from oyun.sirketler s where s.id = i.varlik_id and s.aktif and s.sektor <> 'banka')
       and exists (select 1 from oyun.sirket_ortaklari o where o.sirket_id = i.varlik_id and o.user_id = i.satici and o.pay = 100);
  else
    return exists (select 1 from oyun.sirketler s where s.id = i.varlik_id and s.aktif and s.sektor <> 'banka')
       and oyun.ilan_kullanilabilir_pay(i.varlik_id, i.satici, i.id) >= i.pay;
  end if;
end $$;

-- Listede görünen kısa ilan kartı
create or replace function oyun.ilan_ozet(p_id bigint, p_u uuid) returns jsonb
language plpgsql stable set search_path = '' as $$
declare i oyun.ilanlar; v_t timestamptz := oyun.simdi(); v_oz text; v_gorsel text; v_il text; v_kad text;
begin
  select * into i from oyun.ilanlar where id = p_id;
  if i.id is null then return null; end if;
  select x.ad into v_il from oyun.iller x where x.id = i.il_id;
  select pr.kad into v_kad from oyun.profiller pr where pr.id = i.satici;
  if i.varlik = 'tapu' then
    select tp.tip, concat_ws(' · ', tp.alan_m2 || ' m²',
             case when tp.haftalik_kira > 0 then 'haftalık kira ' || oyun.tl(tp.haftalik_kira) || ' ₺' end)
      into v_gorsel, v_oz from oyun.yatirim_pazar_tapu tp where tp.id = i.varlik_id;
  elsif i.varlik = 'bolum' then
    select bo.tur, concat_ws(' · ', bo.alan_m2 || ' m²', y.ad)
      into v_gorsel, v_oz from oyun.eko_bolumler bo join oyun.eko_yapilar y on y.id = bo.yapi_id where bo.id = i.varlik_id;
  elsif i.varlik = 'sirket' then
    v_gorsel := 'sirket'; v_oz := concat_ws(' · ', oyun.ilan_sektor_ad(i.sektor), 'şirketin tamamı');
  else
    v_gorsel := 'hisse'; v_oz := concat_ws(' · ', oyun.ilan_sektor_ad(i.sektor), oyun.ilan_pay_yaz(i.pay) || ' hisse');
  end if;
  return jsonb_build_object(
    'id', i.id, 'no', oyun.ilan_no(i.id), 'kategori', i.kategori, 'varlik', i.varlik, 'baslik', i.baslik,
    'fiyat', i.fiyat, 'dustu', coalesce(i.onceki_fiyat > i.fiyat, false), 'il', v_il, 'il_id', i.il_id,
    'tarih', i.olusturma, 'siralama', i.siralama, 'sektor', i.sektor, 'pay', i.pay, 'satici', v_kad,
    'benim', i.satici = p_u, 'acil', coalesce(i.acil_bitis > v_t, false), 'vitrin', coalesce(i.vitrin_bitis > v_t, false),
    'ust', coalesce(i.ust_bitis > v_t, false), 'renkli', coalesce(i.renkli_bitis > v_t, false),
    'gorsel', coalesce(v_gorsel, i.varlik), 'ozellik', v_oz, 'pazarlik', i.pazarlik, 'durum', i.durum,
    'bitis', i.bitis, 'goruntulenme', i.goruntulenme, 'kaynak', i.kaynak, 'satis_bedeli', i.satis_bedeli);
end $$;

-- Teklifi kapat ve emanetini iade et
create or replace function oyun.ilan_teklif_kapat(p_teklif bigint, p_durum text, p_mesaj text default null)
returns void language plpgsql security definer set search_path = '' as $$
declare tk oyun.ilan_teklifler; v_t timestamptz := oyun.simdi();
begin
  select * into tk from oyun.ilan_teklifler where id = p_teklif for update;
  if tk.id is null or tk.durum not in ('bekliyor','karsi') then return; end if;
  if tk.emanet > 0 then
    perform oyun.para_islem(tk.alici, tk.emanet, 'iade',
      format('İlan #%s: teklif emaneti iade edildi', oyun.ilan_no(tk.ilan_id)), v_t);
  end if;
  update oyun.ilan_teklifler set durum = p_durum, emanet = 0, sonuc = v_t where id = tk.id;
  if p_mesaj is not null then perform oyun.bildir(tk.alici, p_mesaj, v_t); end if;
end $$;

-- İlanı kapat (kaldırıldı / süresi doldu / geçersiz); açık teklifler iade edilir
create or replace function oyun.ilan_kapat(p_ilan bigint, p_durum text, p_bildir boolean default true)
returns void language plpgsql security definer set search_path = '' as $$
declare i oyun.ilanlar; r record; v_t timestamptz := oyun.simdi(); v_mesaj text;
begin
  select * into i from oyun.ilanlar where id = p_ilan for update;
  if i.id is null or i.durum <> 'yayinda' then return; end if;
  update oyun.ilanlar set durum = p_durum, kapanis = v_t where id = i.id;
  v_mesaj := format('“%s” ilanı yayından kalktı; teklif emanetin iade edildi.', i.baslik);
  for r in select tk.id from oyun.ilan_teklifler tk where tk.ilan_id = i.id and tk.durum in ('bekliyor','karsi') loop
    perform oyun.ilan_teklif_kapat(r.id, 'kapandi', v_mesaj);
  end loop;
  if i.varlik = 'sirket' then
    perform set_config('oyun.ilan_senkron', '1', true);
    update oyun.sirketler set satilik = null where id = i.varlik_id and satilik is not null;
    perform set_config('oyun.ilan_senkron', '', true);
  end if;
  if p_bildir and p_durum = 'suresi_doldu' then
    perform oyun.bildir(i.satici, format('“%s” ilanının 30 günlük yayın süresi doldu. İstersen İlan Meydanı’ndan yeniden ilan verebilirsin.', i.baslik), v_t);
  elsif p_bildir and p_durum = 'gecersiz' then
    perform oyun.bildir(i.satici, format('“%s” ilanı yayından kalktı: ilandaki varlık artık satılabilir durumda değil.', i.baslik), v_t);
  end if;
end $$;

-- Bir varlık el değiştirince aynı varlığa / şirkete ait geçersiz kalan ilanları kapat
create or replace function oyun.ilan_varlik_temizle(p_varlik text, p_id bigint)
returns void language plpgsql security definer set search_path = '' as $$
declare r record;
begin
  for r in select i.id from oyun.ilanlar i where i.durum = 'yayinda'
            and ((p_varlik in ('sirket','hisse') and i.varlik in ('sirket','hisse') and i.varlik_id = p_id)
              or (p_varlik in ('tapu','bolum') and i.varlik = p_varlik and i.varlik_id = p_id)) loop
    if not oyun.ilan_gecerli(r.id) then perform oyun.ilan_kapat(r.id, 'gecersiz'); end if;
  end loop;
end $$;

-- ---------------------------------------------------------------------
-- C. DEVİR (satışın kalbi): hemen al ve kabul edilen teklif buradan geçer
-- ---------------------------------------------------------------------
create or replace function oyun.ilan_devret(p_ilan bigint, p_alici uuid, p_bedel numeric, p_emanet numeric, p_teklif bigint)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  i oyun.ilanlar; v_t timestamptz := oyun.simdi(); v_harc_a numeric; v_harc_s numeric; v_tur text;
  tp oyun.yatirim_pazar_tapu; bo oyun.eko_bolumler; s oyun.sirketler; v_pay numeric; v_odenecek numeric;
  v_il smallint; v_tip text; r record; v_alici_kad text; v_satici_kad text;
begin
  select * into i from oyun.ilanlar where id = p_ilan for update;
  if i.id is null or i.durum <> 'yayinda' or i.bitis <= v_t then raise exception 'Bu ilan artık yayında değil.'; end if;
  if i.satici = p_alici then raise exception 'Kendi ilanını satın alamazsın.'; end if;
  if p_bedel is null or p_bedel < 1000 or p_bedel <> round(p_bedel) then raise exception 'Geçersiz satış bedeli.'; end if;
  if not exists (select 1 from oyun.profiller p where p.id = i.satici and not p.yasakli) then
    raise exception 'Satıcının hesabı şu an işlem yapamıyor.'; end if;
  if oyun.iliskili(i.satici, p_alici) then perform oyun.iliskili_hata(); end if;
  v_harc_a := oyun.ilan_harc(i.varlik, p_bedel); v_harc_s := v_harc_a;
  v_tur := case when i.varlik in ('tapu','bolum') then 'emlak' else 'sirket' end;
  select kad into v_alici_kad from oyun.profiller where id = p_alici;
  select kad into v_satici_kad from oyun.profiller where id = i.satici;

  -- 1) Varlığı kilitle, satıcıda olduğunu doğrula
  if i.varlik = 'tapu' then
    perform oyun.yatirim_pazar_kira_tahsil(i.satici);
    select * into tp from oyun.yatirim_pazar_tapu where id = i.varlik_id for update;
    if tp.id is null or tp.sahip <> i.satici then raise exception 'Satıcı artık bu tapunun sahibi değil; ilan geçersiz.'; end if;
    v_il := tp.il_id; v_tip := tp.tip;
  elsif i.varlik = 'bolum' then
    select * into bo from oyun.eko_bolumler where id = i.varlik_id for update;
    if bo.id is null or bo.sahibi is distinct from i.satici then raise exception 'Satıcı artık bu taşınmazın sahibi değil; ilan geçersiz.'; end if;
    if exists (select 1 from oyun.eko_subeler sb where sb.bolum_id = bo.id and sb.aktif) then
      raise exception 'Kiracısı olan dükkân devredilemez; satıcı önce kira sözleşmesini bitirmeli.'; end if;
    select y.il_id into v_il from oyun.eko_yapilar y where y.id = bo.yapi_id; v_tip := bo.tur;
  else
    if not oyun.uzaktan_modul_acik('sirket_pazari') then raise exception 'Şirket pazarı geçici olarak kapalı.'; end if;
    perform pg_advisory_xact_lock(98763, hashtext(i.varlik_id::text));
    perform oyun.sirket_hesapla(i.varlik_id);
    select * into s from oyun.sirketler where id = i.varlik_id for update;
    if s.id is null or not s.aktif then raise exception 'Şirket artık faal değil; ilan geçersiz.'; end if;
    if s.sektor = 'banka' then raise exception 'Bankalar ilanla devredilemez.'; end if;
    select o.pay into v_pay from oyun.sirket_ortaklari o where o.sirket_id = s.id and o.user_id = i.satici for update;
    if i.varlik = 'sirket' and v_pay is distinct from 100::numeric then
      raise exception 'Satıcı artık şirketin tamamına sahip değil; ilan geçersiz.'; end if;
    if i.varlik = 'hisse' and oyun.ilan_kullanilabilir_pay(s.id, i.satici, i.id) < i.pay then
      raise exception 'Satıcının satılabilir hissesi artık yetersiz; ilan geçersiz.'; end if;
  end if;

  -- 2) Para: alıcı (emanetten düşülür, eksik varsa cüzdandan) ve satıcı
  v_odenecek := p_bedel + v_harc_a - coalesce(p_emanet, 0);
  if v_odenecek > 0 then
    perform oyun.para_islem(p_alici, -v_odenecek, v_tur,
      format('İlan #%s: %s alımı%s', oyun.ilan_no(i.id), i.baslik, case when v_harc_a > 0 then ' (alıcı %2 tapu harcı dahil)' else '' end),
      v_t, v_harc_a);
  elsif v_odenecek < 0 then
    perform oyun.para_islem(p_alici, -v_odenecek, 'iade', format('İlan #%s: emanet farkı iade edildi', oyun.ilan_no(i.id)), v_t);
  end if;
  perform oyun.para_islem(i.satici, p_bedel - v_harc_s, v_tur,
    format('İlan #%s: %s satışı%s', oyun.ilan_no(i.id), i.baslik, case when v_harc_s > 0 then ' (satıcı %2 tapu harcı düşüldü)' else '' end),
    v_t, v_harc_s);

  -- 3) Devir
  if i.varlik = 'tapu' then
    update oyun.yatirim_pazar_tapu set sahip = p_alici, alis_bedeli = p_bedel, satin_alma = v_t, sonraki_kira = v_t + interval '7 days'
     where id = tp.id;
    update oyun.yatirim_pazar_ilan set durum = 'iptal', kapanma = v_t where kaynak = 'yatirim' and ref_id = tp.id and durum = 'acik';
    insert into oyun.yatirim_pazar_islem(kaynak, ref_id, il_id, tip, satici, alici, bedel, alici_harc, satici_harc)
      values ('ilan', tp.id, v_il, v_tip, i.satici, p_alici, p_bedel, v_harc_a, v_harc_s);
  elsif i.varlik = 'bolum' then
    update oyun.eko_bolumler set sahibi = p_alici, satildi = v_t where id = bo.id;
    update oyun.yatirim_pazar_ilan set durum = 'iptal', kapanma = v_t where kaynak = 'proje' and ref_id = bo.id and durum = 'acik';
    insert into oyun.yatirim_pazar_islem(kaynak, ref_id, il_id, tip, satici, alici, bedel, alici_harc, satici_harc)
      values ('ilan', bo.id, v_il, v_tip, i.satici, p_alici, p_bedel, v_harc_a, v_harc_s);
  elsif i.varlik = 'hisse' then
    if v_pay = i.pay then
      delete from oyun.sirket_ortaklari where sirket_id = s.id and user_id = i.satici;
    else
      update oyun.sirket_ortaklari set pay = pay - i.pay where sirket_id = s.id and user_id = i.satici;
    end if;
    insert into oyun.sirket_ortaklari(sirket_id, user_id, pay) values (s.id, p_alici, i.pay)
      on conflict (sirket_id, user_id) do update set pay = oyun.sirket_ortaklari.pay + excluded.pay;
    perform set_config('oyun.ilan_senkron', '1', true);
    update oyun.sirketler set satilik = null where id = s.id and satilik is not null;
    perform set_config('oyun.ilan_senkron', '', true);
    update oyun.sirket_teklif set durum = 'iptal' where sirket_id = s.id and satici = i.satici and durum = 'bekliyor'
      and pay > coalesce((select o.pay from oyun.sirket_ortaklari o where o.sirket_id = s.id and o.user_id = i.satici), 0);
    insert into oyun.ticaret_devir_kayit(tur, varlik_id, satici, alici, bedel, pay, zaman, aciklama)
      values ('sirket_hisse', s.id, i.satici, p_alici, p_bedel, i.pay, v_t,
              format('İlan Meydanı #%s: %s şirketinden %s pay devri', oyun.ilan_no(i.id), s.ad, oyun.ilan_pay_yaz(i.pay)));
  else
    delete from oyun.sirket_ortaklari where sirket_id = s.id;
    insert into oyun.sirket_ortaklari(sirket_id, user_id, pay) values (s.id, p_alici, 100);
    perform set_config('oyun.ilan_senkron', '1', true);
    update oyun.sirketler set satilik = null where id = s.id and satilik is not null;
    perform set_config('oyun.ilan_senkron', '', true);
    update oyun.sirket_teklif set durum = 'iptal' where sirket_id = s.id and durum = 'bekliyor';
    insert into oyun.ticaret_devir_kayit(tur, varlik_id, satici, alici, bedel, pay, zaman, aciklama)
      values ('sirket_tam', s.id, i.satici, p_alici, p_bedel, 100, v_t,
              format('İlan Meydanı #%s: %s şirketinin tamamı devredildi', oyun.ilan_no(i.id), s.ad));
  end if;

  -- 4) Tapu harçları Hazine'ye (milyar birimi); emlakta MASAK tekrar kontrolü
  if v_harc_a + v_harc_s > 0 then
    update oyun.ulke set hazine = hazine + (v_harc_a + v_harc_s) / oyun.pazar_tl_milyar() where id = 1;
    perform oyun.masak_cift_kontrol(i.satici, p_alici, p_bedel);
  end if;

  -- 5) İlanı ve teklifleri kapat
  update oyun.ilanlar set durum = 'satildi', alici = p_alici, satis_bedeli = p_bedel, kapanis = v_t where id = i.id;
  if p_teklif is not null then
    update oyun.ilan_teklifler set durum = 'kabul', emanet = 0, sonuc = v_t where id = p_teklif;
  end if;
  for r in select tk.id from oyun.ilan_teklifler tk where tk.ilan_id = i.id and tk.durum in ('bekliyor','karsi')
             and tk.id is distinct from p_teklif loop
    perform oyun.ilan_teklif_kapat(r.id, 'kapandi', format('“%s” ilanı başka bir alıcıya satıldı; teklif emanetin iade edildi.', i.baslik));
  end loop;
  perform oyun.ilan_varlik_temizle(i.varlik, i.varlik_id);

  perform oyun.bildir(i.satici, format('Satış tamamlandı: “%s” %s ₺ bedelle %s adlı oyuncuya geçti.', i.baslik, oyun.tl(p_bedel), v_alici_kad), v_t);
  perform oyun.bildir(p_alici, format('Hayırlı olsun! “%s” artık senin (%s ₺, satıcı %s).', i.baslik, oyun.tl(p_bedel), v_satici_kad), v_t);
  return jsonb_build_object('tamam', true, 'ilan', i.id, 'bedel', p_bedel, 'odenen', p_bedel + v_harc_a,
                            'saticiya', p_bedel - v_harc_s, 'harc', v_harc_a);
end $$;

