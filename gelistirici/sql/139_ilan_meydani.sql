create table if not exists oyun.ilanlar (
  id bigint generated by default as identity primary key,
  kategori text not null check (kategori in ('konut','isyeri','arsa','sirket','hisse')),
  varlik text not null check (varlik in ('tapu','bolum','sirket','hisse')),
  varlik_id bigint not null,
  pay numeric check (pay is null or (pay > 0 and pay <= 100)),
  satici uuid not null references oyun.profiller(id),
  baslik text not null check (char_length(baslik) between 5 and 70),
  aciklama text check (aciklama is null or char_length(aciklama) <= 1200),
  fiyat numeric not null check (fiyat >= 1000 and fiyat <= 1000000000 and fiyat = round(fiyat)),
  ilk_fiyat numeric not null,
  onceki_fiyat numeric,
  pazarlik boolean not null default true,
  mali_goster boolean not null default false,
  il_id smallint references oyun.iller(id),
  sektor text,
  durum text not null default 'yayinda' check (durum in ('yayinda','satildi','kaldirildi','suresi_doldu','gecersiz')),
  kaynak text not null default 'oyuncu' check (kaynak in ('oyuncu','aktarim')),
  olusturma timestamptz not null default now(),
  siralama timestamptz not null default now(),
  bitis timestamptz not null,
  kapanis timestamptz,
  alici uuid references oyun.profiller(id),
  satis_bedeli numeric,
  vitrin_bitis timestamptz,
  ust_bitis timestamptz,
  acil_bitis timestamptz,
  renkli_bitis timestamptz,
  goruntulenme integer not null default 0
);
