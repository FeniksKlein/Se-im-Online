create or replace function public.ilan_meydani(p_filtre jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  p oyun.profiller := oyun.profilim(); v_t timestamptz := oyun.simdi();
  v_k text := coalesce(nullif(p_filtre->>'kategori', ''), 'tumu');
  v_il smallint := nullif(p_filtre->>'il', '')::smallint;
  v_min numeric := nullif(p_filtre->>'min', '')::numeric;
  v_max numeric := nullif(p_filtre->>'max', '')::numeric;
  v_sek text := nullif(p_filtre->>'sektor', '');
  v_ara text := left(nullif(btrim(coalesce(p_filtre->>'ara', '')), ''), 60);
  v_sir text := coalesce(nullif(p_filtre->>'sirala', ''), 'akilli');
  v_acil boolean := coalesce((p_filtre->>'acil')::boolean, false);
  v_sat uuid; v_sayfa int := greatest(1, least(50, coalesce(nullif(p_filtre->>'sayfa', '')::int, 1)));
  v_boy int := 20; v_kats text[]; v_toplam int; v_liste jsonb; v_vitrin jsonb; v_kat jsonb; v_mut jsonb;
  v_desen text; v_sektorler jsonb;
begin
  if nullif(p_filtre->>'satici', '') is not null then
    select pr.id into v_sat from oyun.profiller pr where lower(pr.kad) = lower(p_filtre->>'satici');
    if v_sat is null then v_sat := '00000000-0000-0000-0000-000000000000'; end if;
  end if;
  v_kats := case v_k when 'tumu' then array['konut','isyeri','arsa','sirket','hisse']
                     when 'emlak' then array['konut','isyeri','arsa']
                     when 'sirketler' then array['sirket','hisse']
                     when 'muteahhit' then array[]::text[]
                     else array[v_k] end;
  if v_ara is not null then
    v_desen := '%' || replace(replace(replace(v_ara, '\', '\\'), '%', '\%'), '_', '\_') || '%';
  end if;

  with f as (
    select i.id, i.fiyat, i.olusturma, i.siralama, i.ust_bitis from oyun.ilanlar i
     where i.durum = 'yayinda' and i.bitis > v_t and i.kategori = any(v_kats)
       and (v_il is null or i.il_id = v_il)
       and (v_min is null or i.fiyat >= v_min) and (v_max is null or i.fiyat <= v_max)
       and (v_sek is null or i.sektor = v_sek)
       and (not v_acil or i.acil_bitis > v_t)
       and (v_sat is null or i.satici = v_sat)
       and (v_desen is null or i.baslik ilike v_desen or coalesce(i.aciklama, '') ilike v_desen
            or exists (select 1 from oyun.iller x where x.id = i.il_id and x.ad ilike v_desen)
            or exists (select 1 from oyun.sirketler s where i.varlik in ('sirket','hisse') and s.id = i.varlik_id and s.ad ilike v_desen))
  ), sirali as (
    select f.id, count(*) over () as n,
           row_number() over (order by
             case when v_sir = 'akilli' and f.ust_bitis > v_t then 0 else 1 end,
             case when v_sir = 'ucuz' then f.fiyat end asc nulls last,
             case when v_sir = 'pahali' then f.fiyat end desc nulls last,
             case when v_sir = 'yeni' then f.olusturma end desc nulls last,
             f.siralama desc, f.id desc) as rn
      from f
  )
  select coalesce(max(n), 0)::int,
         coalesce(jsonb_agg(oyun.ilan_ozet(id, p.id) order by rn) filter (where rn > (v_sayfa - 1) * v_boy and rn <= v_sayfa * v_boy), '[]'::jsonb)
    into v_toplam, v_liste from sirali;

  select coalesce(jsonb_agg(oyun.ilan_ozet(x.id, p.id)), '[]'::jsonb) into v_vitrin
    from (select i.id from oyun.ilanlar i
           where i.durum = 'yayinda' and i.bitis > v_t and i.vitrin_bitis > v_t and i.kategori = any(v_kats)
           order by random() limit 8) x;

  select jsonb_build_object(
      'konut',  count(*) filter (where i.kategori = 'konut'),
      'isyeri', count(*) filter (where i.kategori = 'isyeri'),
      'arsa',   count(*) filter (where i.kategori = 'arsa'),
      'sirket', count(*) filter (where i.kategori = 'sirket'),
      'hisse',  count(*) filter (where i.kategori = 'hisse'),
      'acil',   count(*) filter (where i.acil_bitis > v_t),
      'toplam', count(*),
      'muteahhit', (select count(*) from oyun.eko_bolumler bo join oyun.eko_yapilar y on y.id = bo.yapi_id
                     join oyun.sirketler s on s.id = y.sirket_id
                    where bo.sahibi is null and bo.satis_fiyati is not null and y.bitis <= v_t and s.aktif))
    into v_kat from oyun.ilanlar i where i.durum = 'yayinda' and i.bitis > v_t;

  -- Müteahhitten sıfır (ilk satış; satın alma mevcut eko_emlak_islem('bolum_al') ile)
  if v_k in ('tumu','emlak','konut','isyeri','muteahhit') and v_sat is null and not v_acil and v_sek is null then
    select coalesce(jsonb_agg(g order by g->>'il', (g->>'fiyat')::numeric), '[]'::jsonb) into v_mut from (
      select jsonb_build_object(
               'bolum', min(bo.id) filter (where bo.satis_fiyati = mn.fiyat), 'yapi', y.id, 'proje', y.ad, 'tur', bo.tur,
               'kategori', case bo.tur when 'daire' then 'konut' else 'isyeri' end,
               'il', x.ad, 'il_id', y.il_id, 'fiyat', mn.fiyat, 'adet', count(*), 'alan_m2', min(bo.alan_m2),
               'firma', s.ad, 'harc', oyun.ilan_harc('bolum', mn.fiyat)) g
        from oyun.eko_bolumler bo
        join oyun.eko_yapilar y on y.id = bo.yapi_id
        join oyun.sirketler s on s.id = y.sirket_id and s.aktif
        join oyun.iller x on x.id = y.il_id
        cross join lateral (select min(b2.satis_fiyati) fiyat from oyun.eko_bolumler b2
                             where b2.yapi_id = y.id and b2.tur = bo.tur and b2.sahibi is null and b2.satis_fiyati is not null) mn
       where bo.sahibi is null and bo.satis_fiyati is not null and y.bitis <= v_t
         and (v_k not in ('konut','isyeri') or bo.tur = case v_k when 'konut' then 'daire' else 'dukkan' end)
         and (v_il is null or y.il_id = v_il)
         and (v_min is null or mn.fiyat >= v_min) and (v_max is null or mn.fiyat <= v_max)
         and (v_desen is null or y.ad ilike v_desen or x.ad ilike v_desen or s.ad ilike v_desen)
       group by y.id, y.ad, bo.tur, x.ad, y.il_id, s.ad, mn.fiyat
       limit 24) q;
  end if;

  select coalesce(jsonb_agg(jsonb_build_object('kod', z.sektor, 'ad', oyun.ilan_sektor_ad(z.sektor)) order by oyun.ilan_sektor_ad(z.sektor)), '[]'::jsonb)
    into v_sektorler from (select distinct s.sektor from oyun.sirketler s where s.aktif and s.sektor <> 'banka') z;

  return jsonb_build_object(
    'liste', v_liste, 'toplam', v_toplam, 'sayfa', v_sayfa, 'boy', v_boy,
    'vitrin', v_vitrin, 'kategoriler', v_kat, 'muteahhit', coalesce(v_mut, '[]'::jsonb), 'sektorler', v_sektorler,
    'benim', jsonb_build_object(
      'aktif_ilan', (select count(*) from oyun.ilanlar i where i.satici = p.id and i.durum = 'yayinda'),
      'gelen', (select count(*) from oyun.ilan_teklifler tk join oyun.ilanlar i on i.id = tk.ilan_id
                 where i.satici = p.id and tk.durum = 'bekliyor'),
      'giden', (select count(*) from oyun.ilan_teklifler tk where tk.alici = p.id and tk.durum in ('bekliyor','karsi')),
      'karsi', (select count(*) from oyun.ilan_teklifler tk where tk.alici = p.id and tk.durum = 'karsi'),
      'favori', coalesce((select jsonb_agg(fv.ilan_id) from oyun.ilan_favori fv where fv.user_id = p.id), '[]'::jsonb),
      'cuzdan', (select c.para from oyun.cuzdan c where c.user_id = p.id)),
    'tarife', (select jsonb_agg(jsonb_build_object('kod', a.kod, 'ad', a.ad, 'tutar', a.tutar, 'gun', a.gun, 'aciklama', a.aciklama) order by a.sira)
                 from oyun.ilan_ayar a));
end $$;

create or replace function public.ilan_detay(p_ilan bigint)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  p oyun.profiller := oyun.profilim(); v_t timestamptz := oyun.simdi(); i oyun.ilanlar;
  v_bilgi jsonb := '[]'::jsonb; v_mali jsonb; v_satici jsonb; v_teklifler jsonb; v_teklifim jsonb; v_benzer jsonb;
  v_benim boolean; v_alt numeric; v_ust numeric; v_rayic numeric; tp oyun.yatirim_pazar_tapu; bo oyun.eko_bolumler; y oyun.eko_yapilar; s oyun.sirketler;
  v_il text; v_mali_izin boolean; v_ekledi int; v_damga numeric;
begin
  select * into i from oyun.ilanlar where id = p_ilan;
  if i.id is null then raise exception 'İlan bulunamadı.'; end if;
  v_benim := i.satici = p.id;
  if i.durum = 'yayinda' and (i.bitis <= v_t or not oyun.ilan_gecerli(i.id)) then
    perform oyun.ilan_kapat(i.id, case when i.bitis <= v_t then 'suresi_doldu' else 'gecersiz' end);
    select * into i from oyun.ilanlar where id = p_ilan;
  end if;
  if not v_benim then
    insert into oyun.ilan_bakan(ilan_id, user_id, zaman) values (i.id, p.id, v_t) on conflict do nothing;
    get diagnostics v_ekledi = row_count;
    if v_ekledi > 0 then update oyun.ilanlar set goruntulenme = goruntulenme + 1 where id = i.id; i.goruntulenme := i.goruntulenme + 1; end if;
  end if;
  select x.ad into v_il from oyun.iller x where x.id = i.il_id;

  if i.varlik = 'tapu' then
    select * into tp from oyun.yatirim_pazar_tapu where id = i.varlik_id;
    v_bilgi := jsonb_build_array(
      jsonb_build_array('Emlak tipi', oyun.ilan_tip_ad(tp.tip)),
      jsonb_build_array('İl', v_il),
      jsonb_build_array('Alan', tp.alan_m2 || ' m²'),
      jsonb_build_array('Haftalık kira geliri', case when tp.haftalik_kira > 0 then oyun.tl(tp.haftalik_kira) || ' ₺' else 'Yok' end),
      jsonb_build_array('Tapu durumu', 'Tapulu, belediyeden alınmış'),
      jsonb_build_array('İl rayici', oyun.tl(oyun.yatirim_pazar_fiyat(tp.il_id, tp.tip)) || ' ₺'));
  elsif i.varlik = 'bolum' then
    select * into bo from oyun.eko_bolumler where id = i.varlik_id;
    select * into y from oyun.eko_yapilar where id = bo.yapi_id;
    v_bilgi := jsonb_build_array(
      jsonb_build_array('Emlak tipi', oyun.ilan_tip_ad(bo.tur)),
      jsonb_build_array('İl', v_il),
      jsonb_build_array('Proje', y.ad),
      jsonb_build_array('Bağımsız bölüm', bo.sira || ' numara'),
      jsonb_build_array('Alan', bo.alan_m2 || ' m²'),
      jsonb_build_array('Yapım', 'Tamamlandı ' || oyun.ilan_tarih(y.bitis)),
      jsonb_build_array('Müteahhit', coalesce((select s2.ad from oyun.sirketler s2 where s2.id = y.sirket_id), '—')),
      jsonb_build_array('Kira bedeli', case when bo.kira_bedeli is not null then oyun.tl(bo.kira_bedeli) || ' ₺ / hafta' else 'Belirlenmemiş' end),
      jsonb_build_array('İl rayici', oyun.tl(oyun.yatirim_pazar_fiyat(y.il_id, bo.tur)) || ' ₺'));
  else
    select * into s from oyun.sirketler where id = i.varlik_id;
    v_bilgi := jsonb_build_array(
      jsonb_build_array('Şirket', s.ad),
      jsonb_build_array('Sektör', oyun.ilan_sektor_ad(s.sektor)),
      jsonb_build_array('Hukuki tür', case s.tur_hukuki when 'as' then 'Anonim şirket (A.Ş.)' when 'ltd' then 'Limited şirket' else coalesce(s.tur_hukuki, '—') end),
      jsonb_build_array('Kuruluş', oyun.ilan_tarih(s.kurulus)),
      jsonb_build_array('Merkez', coalesce(v_il, '—')),
      jsonb_build_array('Şube', ((select count(*) from oyun.sirket_il_subeleri sb where sb.sirket_id = s.id)
                               + (select count(*) from oyun.eko_subeler sb where sb.sirket_id = s.id and sb.aktif)) || ' şube'),
      jsonb_build_array('Ortak sayısı', (select count(*) from oyun.sirket_ortaklari o where o.sirket_id = s.id) || ' ortak'),
      jsonb_build_array('Satılan', case when i.varlik = 'sirket' then 'Şirketin tamamı (%100)' else oyun.ilan_pay_yaz(i.pay) || ' hisse' end),
      jsonb_build_array('Borsada', case when s.halka_acik then 'İşlem görüyor' else 'Hayır' end));
    v_mali_izin := i.mali_goster or v_benim or p.yonetici;
    if v_mali_izin then
      v_mali := jsonb_build_object('kasa', s.kasa, 'sermaye', s.sermaye, 'defter', round(oyun.sirket_defter(s.id)),
                                   'acik', i.mali_goster);
    end if;
  end if;
  v_bilgi := v_bilgi || jsonb_build_array(
    jsonb_build_array('İlan no', oyun.ilan_no(i.id)::text),
    jsonb_build_array('İlan tarihi', oyun.ilan_tarih(i.olusturma)),
    jsonb_build_array('Pazarlık', case when i.pazarlik then 'Teklif kabul ediliyor' else 'Yok, sabit fiyat' end));

  v_satici := (select jsonb_build_object('kad', pr.kad, 'uye', oyun.ilan_tarih(pr.olusturma),
                 'il', (select x.ad from oyun.iller x where x.id = pr.il_id), 'son_gorulme', pr.son_gorulme,
                 'satis', (select count(*) from oyun.ilanlar z where z.satici = pr.id and z.durum = 'satildi'),
                 'aktif', (select count(*) from oyun.ilanlar z where z.satici = pr.id and z.durum = 'yayinda' and z.bitis > v_t))
                 from oyun.profiller pr where pr.id = i.satici);

  if v_benim then
    select coalesce(jsonb_agg(jsonb_build_object('id', tk.id, 'alici', (select kad from oyun.profiller where id = tk.alici),
             'tutar', tk.tutar, 'karsi', tk.karsi, 'durum', tk.durum, 'bitis', tk.bitis, 'not', tk.not_metni, 'zaman', tk.olusturma)
             order by (tk.durum in ('bekliyor','karsi')) desc, tk.tutar desc, tk.id desc), '[]'::jsonb)
      into v_teklifler from oyun.ilan_teklifler tk where tk.ilan_id = i.id;
    select b.alt, b.ust, b.rayic into v_alt, v_ust, v_rayic from oyun.ilan_bant(i.varlik, i.varlik_id, i.pay) b;
  else
    select jsonb_build_object('id', tk.id, 'tutar', tk.tutar, 'karsi', tk.karsi, 'durum', tk.durum, 'bitis', tk.bitis,
                              'emanet', tk.emanet, 'not', tk.not_metni)
      into v_teklifim from oyun.ilan_teklifler tk where tk.ilan_id = i.id and tk.alici = p.id
     order by (tk.durum in ('bekliyor','karsi')) desc, tk.id desc limit 1;
  end if;

  select coalesce(jsonb_agg(oyun.ilan_ozet(z.id, p.id)), '[]'::jsonb) into v_benzer from (
    select z.id from oyun.ilanlar z where z.durum = 'yayinda' and z.bitis > v_t and z.kategori = i.kategori and z.id <> i.id
     order by (z.il_id is not distinct from i.il_id) desc, abs(z.fiyat - i.fiyat), z.id desc limit 4) z;

  v_damga := case when i.varlik in ('sirket','hisse') then greatest(0, coalesce(oyun.eko_vergi_oran('damga'), 1)) end;
  return oyun.ilan_ozet(i.id, p.id) || jsonb_build_object(
    'aciklama', i.aciklama, 'bilgi', v_bilgi, 'mali', v_mali, 'mali_goster', i.mali_goster, 'satici_bilgi', v_satici,
    'ilk_fiyat', i.ilk_fiyat, 'onceki_fiyat', i.onceki_fiyat,
    'favori', exists (select 1 from oyun.ilan_favori fv where fv.user_id = p.id and fv.ilan_id = i.id),
    'favori_sayisi', (select count(*) from oyun.ilan_favori fv where fv.ilan_id = i.id),
    'teklifler', v_teklifler, 'teklifim', v_teklifim, 'benzer', v_benzer,
    'alici_harc', oyun.ilan_harc(i.varlik, i.fiyat), 'satici_harc_oran', case when i.varlik in ('tapu','bolum') then 2 else v_damga end,
    'bant', case when v_benim then jsonb_build_object('alt', v_alt, 'ust', v_ust, 'rayic', v_rayic) end,
    'paketler', case when v_benim then jsonb_build_object('vitrin', i.vitrin_bitis, 'ust_sira', i.ust_bitis, 'acil', i.acil_bitis, 'renkli', i.renkli_bitis) end,
    'cuzdan', (select c.para from oyun.cuzdan c where c.user_id = p.id),
    'yonetici', p.yonetici);
end $$;

