-- ---------------------------------------------------------------------
-- G. BAKIM (zamanlayıcı): süresi dolan teklif ve ilanlar, geçersiz ilanlar
-- ---------------------------------------------------------------------
create or replace function oyun.ilan_bakim()
returns integer language plpgsql security definer set search_path = '' as $$
declare r record; v_t timestamptz := oyun.simdi(); v_n int := 0;
begin
  for r in select tk.id, i.baslik from oyun.ilan_teklifler tk join oyun.ilanlar i on i.id = tk.ilan_id
            where tk.durum in ('bekliyor','karsi') and tk.bitis <= v_t loop
    begin
      perform oyun.ilan_teklif_kapat(r.id, 'suresi_doldu',
        format('“%s” ilanına verdiğin teklifin süresi doldu; emanetin iade edildi.', r.baslik));
      v_n := v_n + 1;
    exception when others then raise warning 'ilan_bakim teklif %: %', r.id, sqlerrm;
    end;
  end loop;
  for r in select i.id, i.bitis from oyun.ilanlar i where i.durum = 'yayinda' loop
    begin
      if r.bitis <= v_t then perform oyun.ilan_kapat(r.id, 'suresi_doldu'); v_n := v_n + 1;
      elsif not oyun.ilan_gecerli(r.id) then perform oyun.ilan_kapat(r.id, 'gecersiz'); v_n := v_n + 1;
      end if;
    exception when others then raise warning 'ilan_bakim ilan %: %', r.id, sqlerrm;
    end;
  end loop;
  return v_n;
end $$;

-- ---------------------------------------------------------------------
-- H. ESKİ "SATILIK ŞİRKET" ALANIYLA EŞLEME
--    Eski ekrandan satilik verilirse ücretsiz ilan açılır / fiyat güncellenir;
--    satilik kaldırılırsa ilan kapanır. İlan Meydanı'nın kendi güncellemeleri atlanır.
-- ---------------------------------------------------------------------
create or replace function oyun.tg_ilan_satilik_senkron()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_ilan oyun.ilanlar; v_sahip uuid; v_t timestamptz := oyun.simdi();
begin
  if coalesce(current_setting('oyun.ilan_senkron', true), '') = '1' then return new; end if;
  if new.satilik is not distinct from old.satilik then return new; end if;
  select * into v_ilan from oyun.ilanlar i where i.varlik = 'sirket' and i.varlik_id = new.id and i.durum = 'yayinda' limit 1;
  if new.satilik is null then
    if v_ilan.id is not null then perform oyun.ilan_kapat(v_ilan.id, 'kaldirildi', false); end if;
    return new;
  end if;
  if v_ilan.id is not null then
    if new.satilik between 1000 and 1000000000 and new.satilik = round(new.satilik) and new.satilik <> v_ilan.fiyat then
      update oyun.ilanlar set onceki_fiyat = fiyat, fiyat = new.satilik where id = v_ilan.id;
    end if;
    return new;
  end if;
  select o.user_id into v_sahip from oyun.sirket_ortaklari o where o.sirket_id = new.id and o.pay = 100;
  if v_sahip is null or new.sektor = 'banka' or not new.aktif or new.satilik < 1000 or new.satilik > 1000000000
     or new.satilik <> round(new.satilik) then return new; end if;
  insert into oyun.ilanlar(kategori, varlik, varlik_id, pay, satici, baslik, aciklama, fiyat, ilk_fiyat, pazarlik,
                           il_id, sektor, kaynak, olusturma, siralama, bitis)
    values ('sirket', 'sirket', new.id, 100, v_sahip, left(new.ad, 52) || ' — devren satılık',
            'Şirketin tamamı devren satılık.', new.satilik, new.satilik, true,
            oyun.ilan_sirket_il(new.id), new.sektor, 'aktarim', v_t, v_t, v_t + interval '30 days')
    on conflict do nothing;
  return new;
end $$;

create or replace trigger ilan_satilik_senkron after update of satilik on oyun.sirketler
  for each row execute function oyun.tg_ilan_satilik_senkron();

-- Mevcut satılık şirketleri İlan Meydanı'na ücretsiz aktar (bir kez; tekrarında atlanır)
insert into oyun.ilanlar(kategori, varlik, varlik_id, pay, satici, baslik, aciklama, fiyat, ilk_fiyat, pazarlik,
                         il_id, sektor, kaynak, olusturma, siralama, bitis)
select 'sirket', 'sirket', s.id, 100, o.user_id, left(s.ad, 52) || ' — devren satılık',
       'Şirketin tamamı devren satılık.', s.satilik, s.satilik, true,
       oyun.ilan_sirket_il(s.id), s.sektor, 'aktarim', now(), now(), now() + interval '30 days'
  from oyun.sirketler s join oyun.sirket_ortaklari o on o.sirket_id = s.id and o.pay = 100
 where s.aktif and s.satilik is not null and s.sektor <> 'banka'
   and s.satilik between 1000 and 1000000000 and s.satilik = round(s.satilik)
   and exists (select 1 from oyun.profiller pr where pr.id = o.user_id and not pr.yasakli)
   and not exists (select 1 from oyun.ilanlar i where i.varlik = 'sirket' and i.varlik_id = s.id and i.durum = 'yayinda');

-- ---------------------------------------------------------------------
-- I. CANLI YAMA: müteahhitten ilk satışta ve Yatırım Pazarı'nda tapu harcı
--    Hazine'ye TL olarak yazılıyordu; Hazine milyar biriminde tutulur.
-- ---------------------------------------------------------------------
do $yama$
declare v_tanim text; v_yeni text; v_adet int := 0;
begin
  v_tanim := pg_get_functiondef('public.eko_emlak_islem(text,jsonb)'::regprocedure);
  v_yeni := replace(v_tanim, 'update oyun.ulke set hazine=hazine+harc where id=1;',
                             'update oyun.ulke set hazine=hazine+harc/oyun.pazar_tl_milyar() where id=1;');
  if v_yeni <> v_tanim then execute v_yeni; v_adet := v_adet + 1; end if;
  v_tanim := pg_get_functiondef('public.yatirim_pazar_islem(text,jsonb)'::regprocedure);
  v_yeni := replace(v_tanim, 'hazine=hazine+harc/1000000.0 where id=1', 'hazine=hazine+harc/oyun.pazar_tl_milyar() where id=1');
  v_yeni := replace(v_yeni, 'hazine=hazine+2*harc/1000000.0 where id=1', 'hazine=hazine+2*harc/oyun.pazar_tl_milyar() where id=1');
  if v_yeni <> v_tanim then execute v_yeni; v_adet := v_adet + 1; end if;
  raise notice 'ilan_meydani yamalari: % fonksiyon', v_adet;
exception when undefined_function then raise notice 'ilan_meydani yamasi atlandi: %', sqlerrm;
end $yama$;

-- ---------------------------------------------------------------------
-- J. ZAMANLAYICI VE YETKİLER
-- ---------------------------------------------------------------------
do $cron$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    if exists (select 1 from cron.job where jobname = 'ilan-meydani-bakim') then perform cron.unschedule('ilan-meydani-bakim'); end if;
    perform cron.schedule('ilan-meydani-bakim', '3-59/10 * * * *', 'select oyun.ilan_bakim()');
  end if;
end $cron$;

do $yetki$
declare f text;
begin
  foreach f in array array[
    'public.ilan_meydani(jsonb)', 'public.ilan_detay(bigint)', 'public.ilan_varliklarim()', 'public.ilan_ver(jsonb)',
    'public.ilan_duzenle(bigint,jsonb)', 'public.ilan_one_cikar(bigint,text)', 'public.ilan_kaldir(bigint)',
    'public.ilan_hemen_al(bigint,numeric)', 'public.ilan_teklif_ver(bigint,numeric,text)',
    'public.ilan_teklif_yanit(bigint,text,numeric)', 'public.ilan_karsi_yanit(bigint,boolean)',
    'public.ilan_teklif_geri_cek(bigint)', 'public.ilan_favori(bigint,boolean)', 'public.ilan_hesabim()']
  loop
    execute format('revoke all on function %s from public, anon', f);
    execute format('grant execute on function %s to authenticated', f);
  end loop;
  foreach f in array array[
    'oyun.ilan_devret(bigint,uuid,numeric,numeric,bigint)', 'oyun.ilan_teklif_kapat(bigint,text,text)',
    'oyun.ilan_kapat(bigint,text,boolean)', 'oyun.ilan_varlik_temizle(text,bigint)', 'oyun.ilan_bakim()',
    'oyun.tg_ilan_satilik_senkron()']
  loop
    execute format('revoke all on function %s from public, anon, authenticated', f);
  end loop;
end $yetki$;
