create or replace function public.ilan_teklif_ver(p_ilan bigint, p_tutar numeric, p_not text default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  p oyun.profiller := oyun.profilim(); v_t timestamptz := oyun.simdi(); i oyun.ilanlar; tk oyun.ilan_teklifler;
  v_bant record; v_harc numeric; v_emanet numeric; v_not text; v_tur text; v_id bigint;
begin
  select * into i from oyun.ilanlar where id = p_ilan for update;
  if i.id is null or i.durum <> 'yayinda' or i.bitis <= v_t then raise exception 'Bu ilan artık yayında değil.'; end if;
  if i.satici = p.id then raise exception 'Kendi ilanına teklif veremezsin.'; end if;
  if not i.pazarlik then raise exception 'Satıcı bu ilanda teklif kabul etmiyor; ilan fiyatından satın alabilirsin.'; end if;
  if p_tutar is null or p_tutar <> round(p_tutar) or p_tutar < 1000 then raise exception 'Teklif en az 1.000 ₺ ve kuruşsuz olmalı.'; end if;
  if p_tutar >= i.fiyat then raise exception 'Teklifin ilan fiyatına eşit ya da yüksek; doğrudan “Hemen al” ile satın alabilirsin.'; end if;
  if p_tutar < ceil(i.fiyat * 0.5) then raise exception 'Teklif, ilan fiyatının en az yarısı olmalı (% ₺).', oyun.tl(ceil(i.fiyat * 0.5)); end if;
  select * into v_bant from oyun.ilan_bant(i.varlik, i.varlik_id, i.pay);
  if p_tutar < v_bant.alt then raise exception 'Bu teklif, bu varlık için izin verilen fiyat aralığının altında kalıyor.'; end if;
  if oyun.iliskili(i.satici, p.id) then perform oyun.iliskili_hata(); end if;
  v_not := nullif(btrim(coalesce(p_not, '')), '');
  if v_not is not null and (char_length(v_not) > 280 or oyun.kufurlu(v_not)) then
    raise exception 'Not en fazla 280 karakter olmalı ve uygunsuz ifade içermemeli.'; end if;
  select * into tk from oyun.ilan_teklifler where ilan_id = i.id and alici = p.id and durum in ('bekliyor','karsi') for update;
  if tk.id is null and (select count(*) from oyun.ilan_teklifler z where z.alici = p.id and z.durum in ('bekliyor','karsi')) >= 10 then
    raise exception 'Aynı anda en fazla 10 açık teklifin olabilir.'; end if;
  v_harc := oyun.ilan_harc(i.varlik, p_tutar); v_emanet := p_tutar + v_harc;
  v_tur := case when i.varlik in ('tapu','bolum') then 'emlak' else 'sirket' end;
  if tk.id is null then
    perform oyun.para_islem(p.id, -v_emanet, v_tur,
      format('İlan #%s: %s ₺ teklif Güvenli Ödeme’de bloke edildi%s', oyun.ilan_no(i.id), oyun.tl(p_tutar),
             case when v_harc > 0 then ' (tapu harcı dahil)' else '' end), v_t);
    insert into oyun.ilan_teklifler(ilan_id, alici, tutar, emanet, not_metni, durum, olusturma, bitis)
      values (i.id, p.id, p_tutar, v_emanet, v_not, 'bekliyor', v_t, v_t + interval '48 hours') returning id into v_id;
  else
    if v_emanet > tk.emanet then
      perform oyun.para_islem(p.id, -(v_emanet - tk.emanet), v_tur,
        format('İlan #%s: teklif %s ₺ olarak güncellendi, fark bloke edildi', oyun.ilan_no(i.id), oyun.tl(p_tutar)), v_t);
    elsif v_emanet < tk.emanet then
      perform oyun.para_islem(p.id, tk.emanet - v_emanet, 'iade',
        format('İlan #%s: teklif %s ₺ olarak güncellendi, fark iade edildi', oyun.ilan_no(i.id), oyun.tl(p_tutar)), v_t);
    end if;
    update oyun.ilan_teklifler set tutar = p_tutar, karsi = null, emanet = v_emanet, not_metni = v_not, durum = 'bekliyor',
                                   olusturma = v_t, bitis = v_t + interval '48 hours' where id = tk.id;
    v_id := tk.id;
  end if;
  perform oyun.bildir(i.satici, format('“%s” ilanına %s ₺ teklif geldi (%s). 48 saat içinde İlan Meydanı’ndan yanıtla.',
                                       i.baslik, oyun.tl(p_tutar), p.kad), v_t);
  return jsonb_build_object('tamam', true, 'teklif', v_id, 'emanet', v_emanet);
end $$;

create or replace function public.ilan_teklif_yanit(p_teklif bigint, p_karar text, p_karsi numeric default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare p oyun.profiller := oyun.profilim(); v_t timestamptz := oyun.simdi(); tk oyun.ilan_teklifler; i oyun.ilanlar; v_bant record;
begin
  select * into tk from oyun.ilan_teklifler where id = p_teklif for update;
  if tk.id is null then raise exception 'Teklif bulunamadı.'; end if;
  select * into i from oyun.ilanlar where id = tk.ilan_id for update;
  if i.satici <> p.id then raise exception 'Bu teklif senin ilanına ait değil.'; end if;
  if i.durum <> 'yayinda' then raise exception 'İlan artık yayında değil.'; end if;
  if p_karar = 'kabul' then
    if tk.durum <> 'bekliyor' then raise exception 'Bu teklif artık yanıt beklemiyor.'; end if;
    if tk.bitis <= v_t then raise exception 'Teklifin süresi dolmuş.'; end if;
    return oyun.ilan_devret(i.id, tk.alici, tk.tutar, tk.emanet, tk.id);
  elsif p_karar = 'red' then
    if tk.durum not in ('bekliyor','karsi') then raise exception 'Bu teklif artık açık değil.'; end if;
    perform oyun.ilan_teklif_kapat(tk.id, 'red',
      format('“%s” ilanına verdiğin %s ₺ teklif kabul edilmedi; emanetin iade edildi.', i.baslik, oyun.tl(tk.tutar)));
    return jsonb_build_object('tamam', true);
  elsif p_karar = 'karsi' then
    if tk.durum <> 'bekliyor' then raise exception 'Bu teklife zaten yanıt verdin.'; end if;
    if p_karsi is null or p_karsi <> round(p_karsi) or p_karsi <= tk.tutar or p_karsi > i.fiyat then
      raise exception 'Karşı teklif, alıcının teklifinden yüksek ve ilan fiyatından düşük ya da eşit olmalı.'; end if;
    select * into v_bant from oyun.ilan_bant(i.varlik, i.varlik_id, i.pay);
    if p_karsi > v_bant.ust then raise exception 'Karşı teklif izin verilen fiyat aralığının üstünde.'; end if;
    update oyun.ilan_teklifler set karsi = p_karsi, durum = 'karsi', bitis = v_t + interval '48 hours' where id = tk.id;
    perform oyun.bildir(tk.alici, format('Satıcı “%s” ilanı için karşı teklif verdi: %s ₺. 48 saat içinde İlan Meydanı’ndan yanıtla.',
                                         i.baslik, oyun.tl(p_karsi)), v_t);
    return jsonb_build_object('tamam', true);
  end if;
  raise exception 'Geçersiz karar.';
end $$;

