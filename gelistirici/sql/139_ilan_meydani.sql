end $$;

create or replace function public.ilan_one_cikar(p_ilan bigint, p_paket text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare p oyun.profiller := oyun.profilim(); v_t timestamptz := oyun.simdi(); i oyun.ilanlar; a oyun.ilan_ayar; v_bitis timestamptz;
begin
  select * into i from oyun.ilanlar where id = p_ilan for update;
  if i.id is null or i.satici <> p.id then raise exception 'Bu ilan sana ait değil.'; end if;
  if i.durum <> 'yayinda' or i.bitis <= v_t then raise exception 'Yalnız yayındaki ilanlar öne çıkarılabilir.'; end if;
  select * into a from oyun.ilan_ayar where kod = p_paket and kod in ('vitrin','ust_sira','acil','renkli','yukari');
  if a.kod is null then raise exception 'Geçersiz öne çıkarma paketi.'; end if;
  if a.tutar > 0 then
    perform oyun.para_islem(p.id, -a.tutar, 'reklam', format('İlan Meydanı: “%s” için %s', i.baslik, a.ad), v_t);
    update oyun.ulke set hazine = hazine + a.tutar / oyun.pazar_tl_milyar() where id = 1;
  end if;
  insert into oyun.ilan_odeme(ilan_id, user_id, kod, tutar, zaman) values (i.id, p.id, a.kod, a.tutar, v_t);
  if a.kod = 'yukari' then
    update oyun.ilanlar set siralama = v_t where id = i.id; v_bitis := v_t;
  elsif a.kod = 'vitrin' then
    update oyun.ilanlar set vitrin_bitis = greatest(coalesce(vitrin_bitis, v_t), v_t) + make_interval(days => a.gun) where id = i.id returning vitrin_bitis into v_bitis;
  elsif a.kod = 'ust_sira' then
    update oyun.ilanlar set ust_bitis = greatest(coalesce(ust_bitis, v_t), v_t) + make_interval(days => a.gun) where id = i.id returning ust_bitis into v_bitis;
  elsif a.kod = 'acil' then
    update oyun.ilanlar set acil_bitis = greatest(coalesce(acil_bitis, v_t), v_t) + make_interval(days => a.gun) where id = i.id returning acil_bitis into v_bitis;
  else
    update oyun.ilanlar set renkli_bitis = greatest(coalesce(renkli_bitis, v_t), v_t) + make_interval(days => a.gun) where id = i.id returning renkli_bitis into v_bitis;
  end if;
  return jsonb_build_object('tamam', true, 'paket', a.kod, 'bitis', v_bitis, 'ucret', a.tutar);
end $$;

